import json
from pathlib import Path

START = "<!-- tl-numbers: generated by eng/refresh-numbers from benchmarks/Systems/results/numbers.json; edit the renderer, not this block -->"
END = "<!-- /tl-numbers -->"
RECEIPT_PATH = Path("benchmarks/Systems/results/numbers.json")


def cpu_short(cpu: str) -> str:
    for marker in ("(TM) ", "(R) "):
        at = cpu.rfind(marker)
        if at >= 0:
            cpu = cpu[at + len(marker) :]
    return cpu.strip()


def load_receipt(root: Path) -> dict:
    return json.loads((root / RECEIPT_PATH).read_text(encoding="utf-8"))


def render(receipt: dict) -> str:
    scenarios = receipt["Scenarios"]
    fingerprint = receipt["Fingerprint"]
    lines = [
        f"4.0 systems, one step per call ({cpu_short(fingerprint['Cpu'])}, {fingerprint['Cores']} cores, .NET {fingerprint['Dotnet']}, Release; "
        f"best of {receipt['Reps']} in-process runs after per-shape steady-state warm-up "
        "(at least 0.5 s and until the best frame is flat across three rounds); "
        "hot = consecutive frames with the working set cache-resident, cold = interleaved shapes streaming from DRAM; "
        "every shape bit-exact forward and backward, 0 B allocated:",
        "",
        "| shape | hot ns/entity | cold ns/entity | warm alloc B |",
        "| --- | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {s['Label']} | {s['Hot']['Ns']:.2f} | {s['Cold']['Ns']:.2f} | {s['Allocated']} |"
        for s in scenarios
    ]
    lines += [
        "",
        f"Two playbacks per entity cost {receipt.get('TwoVsOne', 0):.2f}x one playback on the same run. "
        "Committed 3.x LiveBatch baselines (per-entity medians from a different harness and row count) ship in the receipt for reference; "
        "the 4.10 gates (folded ≤1.03x, fold-fed ≤0.15x, frame ≤0.25x, four-pair ≤0.70x, 64-consumer ≤1.5x, 2-playback ≤2.2x) "
        "are decided by same-harness BenchmarkDotNet runs on the release machine, not by the ratios above. "
        "Warm allocation is 0 B on every shape and determinism is verified by identical state hashes across two full runs.",
    ]
    return "\n".join(lines)


def block(readme: str) -> str:
    start = readme.index(START) + len(START)
    end = readme.index(END)
    return readme[start:end].strip("\n")


def apply(receipt: dict, readme: str) -> str:
    start = readme.index(START) + len(START)
    end = readme.index(END)
    return readme[:start] + "\n" + render(receipt) + "\n" + readme[end:]
