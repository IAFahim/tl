using System.Text;
using Tl.Gen.CSharp.Model;

namespace Tl.Gen.CSharp;

internal static class DerivedKindsEmitter
{
    internal static string Emit(IReadOnlyList<KindDecl> kinds)
    {
        var text = new StringBuilder("// <auto-generated/>\nnamespace Tl.Derived\n{\n");
        foreach (var kind in kinds)
        {
            var value = kind.ValueTypeName;
            text.Append("[global::Tl.TimelineKind(Accepts = ").Append(kind.Derived == DerivedKind.While ? "global::Tl.KindEntries.Spans" : "global::Tl.KindEntries.Both").Append(")]\ninternal struct ").Append(kind.Name).Append("\n{\npublic static void Combine(ref ").Append(value).Append(" total, in ").Append(value).Append(" next)\n{\n");
            if (kind.Derived == DerivedKind.Set) text.Append("total = next;\n");
            else
                foreach (var field in kind.DerivedFields)
                    text.Append("total.").Append(field.Name).Append(kind.Derived == DerivedKind.Sum ? " += " : field.Kind == DerivedFieldKind.Float ? " = global::System.Math.Max(total." + field.Name + ", " : " |= ")
                        .Append("next.").Append(field.Name).Append(kind.Derived == DerivedKind.While && field.Kind == DerivedFieldKind.Float ? ")" : "").Append(";\n");
            text.Append("}\npublic static void Apply(in ").Append(value).Append(" total, ref ").Append(value).Append(" column)\n{\n");
            if (kind.Derived == DerivedKind.Sum)
                foreach (var field in kind.DerivedFields) text.Append("column.").Append(field.Name).Append(" += total.").Append(field.Name).Append(";\n");
            else text.Append("column = total;\n");
            text.Append("}\n");
            if (kind.Derived == DerivedKind.While) text.Append("public static void Idle(ref ").Append(value).Append(" column)\n{\ncolumn = default;\n}\n");
            text.Append("}\n");
        }
        return text.Append("}\n").ToString();
    }
}
