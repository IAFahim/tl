using System.Text;
using Tl.Gen.CSharp.Model;

namespace Tl.Gen.CSharp;

internal static class DerivedKindsEmitter
{
    internal static string Emit(IReadOnlyList<KindDecl> kinds)
    {
        var writer = new StringBuilder();
        void W(string text) => writer.Append(text).Append('\n');
        W("// <auto-generated/>");
        W("namespace Tl.Derived");
        W("{");
        foreach (var kind in kinds)
        {
            var accepts = kind.Derived == DerivedKind.While ? "global::Tl.KindEntries.Spans" : "global::Tl.KindEntries.Both";
            var value = kind.ValueTypeName;
            W("[global::Tl.TimelineKind(Accepts = " + accepts + ")]");
            W("public struct " + kind.Name);
            W("{");
            W("public static void Combine(ref " + value + " total, in " + value + " next)");
            W("{");
            if (kind.Derived == DerivedKind.Set)
            {
                W("total = next;");
            }
            else foreach (var field in kind.DerivedFields)
            {
                if (kind.Derived == DerivedKind.Sum)
                    W("total." + field.Name + " += next." + field.Name + ";");
                else if (field.FieldKind == DerivedFieldKind.Float)
                    W("total." + field.Name + " = global::System.Math.Max(total." + field.Name + ", next." + field.Name + ");");
                else
                    W("total." + field.Name + " |= next." + field.Name + ";");
            }
            W("}");
            W("public static void Apply(in " + value + " total, ref " + value + " column)");
            W("{");
            if (kind.Derived == DerivedKind.Sum)
                foreach (var field in kind.DerivedFields)
                    W("column." + field.Name + " += total." + field.Name + ";");
            else
                W("column = total;");
            W("}");
            if (kind.Derived == DerivedKind.While)
            {
                W("public static void Idle(ref " + value + " column)");
                W("{");
                W("column = default;");
                W("}");
            }
            W("}");
        }
        W("}");
        return writer.ToString();
    }
}
