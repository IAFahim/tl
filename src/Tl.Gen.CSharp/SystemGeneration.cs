using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Tl.Gen.CSharp.Analysis;
using Tl.Gen.CSharp.Model;

namespace Tl.Gen.CSharp;
internal static class SystemGeneration
{
    internal static bool IsPlainState(ITypeSymbol type)
        => type is { TypeKind: TypeKind.Struct, IsUnmanagedType: true, SpecialType: SpecialType.None }
        && type.ContainingNamespace?.ToDisplayString() != "Tl";

    public static (IReadOnlyList<CompileArtifact> Artifacts, IReadOnlyList<DeclarationDiagnostic> Diagnostics) Emit(CSharpCompilation compilation, string id = "")
    {
        var models = SystemReader.Order(SystemReader.CollectModels(compilation), compilation, default);
        var read = SystemReader.AssignModels(models, id.Length == 0 ? "Game" : id);
        var diagnostics = new List<DeclarationDiagnostic>(read.Diagnostics);
        Connections.Warn(compilation, diagnostics);
        var artifacts = ArtifactsFor(read.Assignments, diagnostics, read.AutoSource, compilation.AssemblyName ?? "", id);
        return (artifacts, diagnostics);
    }

    internal static IReadOnlyList<CompileArtifact> ArtifactsFor(IReadOnlyList<SystemAssignment> assignments, IReadOnlyList<DeclarationDiagnostic> diagnostics, string autoSource, string assemblyName, string id)
    {
        var errors = diagnostics.Any(static diagnostic => diagnostic.Code is not ("TLGEN98" or "TLGEN107" or "TLGEN113" or "TLGEN114" or "TLGEN115"));
        var artifacts = new List<CompileArtifact>();
        if (!errors)
        {
            artifacts.Add(new CompileArtifact($"TlSystems{id}.g.cs", SystemEmitter.Emit(assignments, id, NewStyle.FeedKey(assemblyName))));
            var derived = assignments.SelectMany(static a => a.Kinds).Where(static k => k.Derived != DerivedKind.None).GroupBy(static k => k.Id, StringComparer.Ordinal).Select(static g => g.First()).OrderBy(static k => k.Id, StringComparer.Ordinal).ToList();
            if (derived.Count > 0)
                artifacts.Add(new CompileArtifact($"TlDerivedKinds{id}.g.cs", DerivedKindsEmitter.Emit(derived)));
            if (autoSource.Length > 0)
                artifacts.Add(new CompileArtifact($"TlSystems{id}.Auto.g.cs", "// <auto-generated/>\n" + autoSource));
            if (PulseHelpers.Emit(assignments) is { Length: > 0 } pulses) artifacts.Add(new($"TlSystems{id}.Pulses.g.cs", "// <auto-generated/>\n" + pulses));
        }
        return artifacts;
    }
}
