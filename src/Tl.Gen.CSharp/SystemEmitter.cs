internal static class SystemEmitter
{
    internal static string Emit(IReadOnlyList<SystemAssignment> a, string id, int feedKey = 0)
    {
        var w = new StringBuilder();
        w.Append("// <auto-generated/>\nusing __PF = Tl.PlaybackFlags;\nusing __FF = Tl.FrameFlags;\nnamespace TlSystems\n{\n");
        EmitModule(w, a, id);
        foreach (var x in a) EmitSystem(w, x, id, feedKey);
        w.Append("}\n");
        foreach (var x in a) EmitRun(w, x, id);
        foreach (var x in a) if (HasLegacy(x)) EmitRunFused(w, x, id);
        return w.ToString().Replace("\r\n", "\n");
    }

    static bool IsLegacy(SystemConsumer c)
    {
        foreach (var m in c.Methods)
            if (m.Kind is not (ConsumerMethodKind.Feeder or ConsumerMethodKind.Fold)) return true;
        return false;
    }

    static bool HasLegacy(SystemAssignment a)
    {
        foreach (var c in a.Consumers) if (IsLegacy(c)) return true;
        return false;
    }

    static void W(StringBuilder w, string t) => w.Append(t.Replace("global::Tl.", "Tl.").Replace("global::System.", "System.").Replace("global::TlSystems.", "TlSystems.").Replace("Tl.PlaybackFlags.", "__PF.").Replace("Tl.FrameFlags.", "__FF.")).Append('\n');

    static void EmitModule(StringBuilder w, IReadOnlyList<SystemAssignment> a, string id)
    {
        var folds = new List<(SystemConsumer consumer, int assignment, int index)>();
        for (var i = 0; i < a.Count; i++)
            for (var c = 0; c < a[i].Consumers.Count; c++)
            {
                var has = false;
                foreach (var m in a[i].Consumers[c].Methods) if (m.Kind == ConsumerMethodKind.Fold) has = true;
                if (has && !a[i].Consumers[c].IsMarker) folds.Add((a[i].Consumers[c], i, c));
            }
        W(w, $"internal sealed class TlModule_{id} : Tl.ITlModule\n{{\npublic int PairCount => {folds.Count};");
        void EmitSwitch(string sig, Func<int, string> val, string def)
        {
            W(w, $"{sig}\n{{\nswitch (index)\n{{");
            for (var i = 0; i < folds.Count; i++) W(w, $"case {i}: return {val(i)};");
            W(w, $"default: return {def};\n}}\n}}");
        }
        EmitSwitch("public ulong PairKey(int index)", i => $"{folds[i].consumer.PairKey}UL", "0UL");
        EmitSwitch("public int FoldLaneBytes(int index)", i => $"{LaneBytes(folds[i].consumer)}", "0");
        EmitSwitch("public int FoldLaneOffset(int index)", i => $"{LaneOffset(folds, i)}", "0");
        W(w, "public unsafe void FoldStep(int index, byte* track, byte* first, byte* second, float blend, ushort tick, ushort windowLength, ushort withinClip, ushort trackIndex, ushort duration, sbyte direction, byte* lane)\n{\nswitch (index)\n{");
        for (var i = 0; i < folds.Count; i++)
        {
            var fold = folds[i];
            W(w, $"case {i}:\n{{\nTlSystem_{id}_{Sanitize(a[fold.assignment].System.TypeName)}.Frame_{fold.index}(track, first, second == first ? null : second, blend, tick, windowLength, withinClip, trackIndex, duration, direction, __FF.None, out var __t, out var __c, out var __frame);");
            var m = FoldOf(fold.consumer)!;
            for (var o = 0; o < m.Params.Count; o++) W(w, $"{m.Params[o].TypeName} __out{o} = default;");
            var outs = new List<string>();
            for (var o = 0; o < m.Params.Count; o++) outs.Add($"out __out{o}");
            W(w, $"{fold.consumer.ConsumerTypeName}.Fold(in __frame, {string.Join(", ", outs)});");
            var off = 0;
            for (var o = 0; o < m.Params.Count; o++)
            {
                W(w, $"*({m.Params[o].TypeName}*)(lane + {off}) = __out{o};");
                off += m.FoldSizes[o];
            }
            W(w, "return;\n}");
        }
        W(w, $"default: return;\n}}\n}}\ninternal static void Install()\n{{\nTl.TlGenerated.Install(new TlModule_{id}());\n}}\n#if NET\n[System.Runtime.CompilerServices.ModuleInitializer]\ninternal static void InstallModule() => Install();\n#endif\n}}");
    }

    static ConsumerMethod? FoldOf(SystemConsumer c)
    {
        foreach (var m in c.Methods) if (m.Kind == ConsumerMethodKind.Fold) return m;
        return null;
    }

    static int LaneBytes(SystemConsumer c)
    {
        var f = FoldOf(c);
        if (f is null) return 0;
        var b = 0;
        foreach (var sz in f.FoldSizes) b += sz;
        return b;
    }

    static int LaneOffset(List<(SystemConsumer consumer, int assignment, int index)> folds, int at)
    {
        var sum = 0;
        for (var k = 0; k < at; k++)
            if (folds[k].consumer.PairKey == folds[at].consumer.PairKey) sum += LaneBytes(folds[k].consumer);
        return sum;
    }

    static void EmitFrameHelper(StringBuilder w, SystemConsumer c, int index)
    {
        W(w, $"internal static void Frame_{index}(byte* trackPtr, byte* firstPtr, byte* secondPtr, float blend, ushort tick, ushort windowLength, ushort withinClip, ushort trackIndex, ushort duration, sbyte direction, Tl.FrameFlags extra, out {c.TrackTypeName} track, out {c.ClipTypeName} clip, out Tl.Frame<{c.TrackTypeName}, {c.ClipTypeName}> frame)\n{{\ntrack = *({c.TrackTypeName}*)trackPtr;\nclip = *({c.ClipTypeName}*)firstPtr;\nif (secondPtr != null)\n{{\n{c.ClipTypeName} __second = *({c.ClipTypeName}*)secondPtr;");
        if (c.ClipBlendable)
            W(w, "static T __Blend<T>(T first, in T second, float factor) where T : unmanaged, Tl.IBlend<T> { first.Blend(in first, in second, factor, out var result); return result; }\nclip = __Blend(clip, in __second, blend);");
        else if (c.TrackBlendable)
            W(w, "track.Blend(in clip, in __second, blend, out clip);");
        else
            W(w, $"throw new System.InvalidOperationException(\"{c.ConsumerTypeName}: blended window without IBlend.\");");
        W(w, $"}}\nvar __flags = (direction < 0 ? __FF.Reverse : __FF.None) | extra;\nif (withinClip == 0) __flags |= __FF.ClipStart;\nif (withinClip == (ushort)(windowLength - 1)) __flags |= __FF.ClipEnd;\nif (tick == 0) __flags |= __FF.TimelineStart;\nif (tick == (ushort)(duration - 1)) __flags |= __FF.TimelineEnd;\nframe = new Tl.Frame<{c.TrackTypeName}, {c.ClipTypeName}>(in track, in clip, tick, windowLength, withinClip, trackIndex, __flags);\n}}");
    }

    static string Sanitize(string t)
    {
        var b = new StringBuilder();
        foreach (var ch in t) b.Append(char.IsLetterOrDigit(ch) ? ch : '_');
        return b.ToString();
    }

    static string Bare(string t) => t.StartsWith("global::", StringComparison.Ordinal) ? t.Substring(8) : t;

    static string NamespaceOf(string t)
    {
        var b = Bare(t);
        var d = b.LastIndexOf('.');
        return d < 0 ? "" : b.Substring(0, d);
    }

    static string ShortNameOf(string t)
    {
        var b = Bare(t);
        var d = b.LastIndexOf('.');
        var p = b.LastIndexOf('+');
        var cut = d > p ? d : p;
        return cut < 0 ? b : b.Substring(cut + 1);
    }

    sealed class KernelShape
    {
        public List<SystemField> Columns = new();
        public List<SystemField> Contexts = new();
        public List<SystemField> Requests = new();
        public List<SystemField> Events = new();
        public bool[] UsedColumns = Array.Empty<bool>();
        public bool[] UsedContexts = Array.Empty<bool>();
        public string Safe = "";
        public Dictionary<ConsumerMethod, string> TlFrames = new(MethodIdentity.Instance);
    }

    sealed class MethodIdentity : IEqualityComparer<ConsumerMethod>
    {
        public static readonly MethodIdentity Instance = new();
        public bool Equals(ConsumerMethod? x, ConsumerMethod? y) => ReferenceEquals(x, y);
        public int GetHashCode(ConsumerMethod obj) => System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode(obj);
    }

    static KernelShape ShapeOf(SystemAssignment a, string id)
    {
        var s = new KernelShape { Safe = $"{id}_{Sanitize(a.System.TypeName)}" };
        foreach (var f in a.System.Fields)
        {
            switch (f.Kind)
            {
                case SystemFieldKind.Column:
                case SystemFieldKind.ColumnReadOnly: s.Columns.Add(f); break;
                case SystemFieldKind.Context: s.Contexts.Add(f); break;
                case SystemFieldKind.Requests: s.Requests.Add(f); break;
                case SystemFieldKind.Events: s.Events.Add(f); break;
            }
        }
        s.UsedColumns = new bool[s.Columns.Count];
        s.UsedContexts = new bool[s.Contexts.Count];
        var ps = new List<ConsumerParam>();
        foreach (var c in a.Consumers) foreach (var m in c.Methods) ps.AddRange(m.Params);
        foreach (var k in a.Kinds) { ps.AddRange(k.ApplyParams); if (k.IdleParams is not null) ps.AddRange(k.IdleParams); }
        foreach (var p in ps)
        {
            if (p.Kind is ConsumerParamKind.Column or ConsumerParamKind.ColumnReadOnly)
            {
                var at = s.Columns.FindIndex(f => f.ElementTypeName == p.TypeName);
                if (at >= 0 && (p.Kind == ConsumerParamKind.ColumnReadOnly || s.Columns[at].Kind == SystemFieldKind.Column)) s.UsedColumns[at] = true;
                else { var ctx = s.Contexts.FindIndex(f => f.ElementTypeName == p.TypeName); if (ctx >= 0) s.UsedContexts[ctx] = true; }
            }
        }
        return s;
    }

    static int ColumnOf(KernelShape s, string el, bool writable)
    {
        for (var i = 0; i < s.Columns.Count; i++)
        {
            if (!s.UsedColumns[i] || s.Columns[i].ElementTypeName != el) continue;
            if (!writable || s.Columns[i].Kind == SystemFieldKind.Column) return i;
        }
        return -1;
    }

    static int ContextOf(KernelShape s, string el)
    {
        for (var i = 0; i < s.Contexts.Count; i++) if (s.UsedContexts[i] && s.Contexts[i].ElementTypeName == el) return i;
        return -1;
    }

    static int RequestOf(KernelShape s) => s.Requests.Count > 0 ? 0 : -1;

    static int EventOf(KernelShape s, string el)
    {
        for (var i = 0; i < s.Events.Count; i++) if (s.Events[i].ElementTypeName == el) return i;
        return -1;
    }

    static bool IsTlFrame(ConsumerMethod m)
        => m.Params.Count > 0 && m.Params[0].Kind == ConsumerParamKind.Frame && m.Params[0].TypeName.StartsWith("global::Tl.TlFrame<", StringComparison.Ordinal);

    static void EmitSystem(StringBuilder w, SystemAssignment a, string id, int feedKey)
    {
        var s = ShapeOf(a, id);
        var cs = a.Consumers;
        foreach (var c in cs)
            foreach (var m in c.Methods)
                if (m.Kind is ConsumerMethodKind.OnClipStart or ConsumerMethodKind.OnClipEnd && IsTlFrame(m))
                    s.TlFrames[m] = c.ClipTypeName;
        W(w, $"internal static unsafe class TlSystem_{s.Safe}\n{{\ninternal const ulong SystemKey = {a.System.SystemKey}UL;\ninternal static readonly ulong[] PairKeys = new ulong[]\n{{");
        foreach (var c in cs) W(w, $"{(IsLegacy(c) ? c.PairKey : 0UL)}UL,");
        W(w, "};");
        for (var c = 0; c < cs.Count; c++) if (!cs[c].IsMarker) EmitFrameHelper(w, cs[c], c);
        W(w, $"{BaseSig(s, "Run", false)}\n{{\nif (world is null) throw new System.ArgumentNullException(nameof(world)); if (players is null) throw new System.ArgumentNullException(nameof(players));");
        if (HasLegacy(a)) W(w, $"RunClose(world, players, forward{FullArgs(s, false)}); RunLegacyRange(world, players, forward{FullArgs(s, true)});");
        EmitKindLoops(w, a, s);
        W(w, "}");
        EmitKindMethods(w, a, s, feedKey);
        if (HasLegacy(a)) { EmitCloseMethod(w, a, s); EmitLegacyRangeMethod(w, a, s); EmitFusedKernel(w, a, s, id); }
        W(w, "}");
    }

    static void EmitEntityScanOpen(StringBuilder w)
        => W(w, "var __pl = players.Playing; var __w1 = __endWord < players.PlayingWords ? __endWord : players.PlayingWords;\nfor (var __w = __firstWord; __w < __w1; __w++)\n{\nfor (var __b = __pl[__w]; __b != 0; __b &= __b - 1)\n{\nvar __e = (__w << 6) + Tl.KindStore.TrailingZeros(__b);\nif (__e >= __n) continue;\n#if TL_CHECKED\nTl.Checked.Visited();\n#endif");

    static void EmitLegacyFrameHead(StringBuilder w, SystemAssignment a, KernelShape s, string pbVar, string eVar, string sVar, bool guardStage)
    {
        W(w, $"var __tick = {pbVar}->Tick;\nvar __stage = Tl.LibraryViewReader.StageAt(__tl, __tick);\n{(guardStage ? "if (__stage != null)" : "if (__stage is null) continue;")}");
        if (guardStage) W(w, "{");
        W(w, $"var __steps = Tl.SystemDispatch.FilteredSteps(world, SystemKey, __tl->Id, (int)(__stage - __tl->Stages), PairKeys);\nvar __backward = forward ? ({pbVar}->Flags & __PF.Reverse) != 0 : ({pbVar}->Flags & __PF.Reverse) == 0;\nvar __base = __backward ? __FF.Reverse : __FF.None;\nif ((({pbVar}->Flags & __PF.StartPending) != 0 && __tick > 0) || ({pbVar}->Flags & __PF.ReenterPending) != 0) __base |= __FF.Synthetic;\nif (__tick == 0) __base |= __FF.TimelineStart;\nif (__tick == (ushort)(__tl->Duration - 1)) __base |= __FF.TimelineEnd;");
        EmitBind(w, s, eVar, sVar);
        EmitEntryLoop(w, a, s, "__steps", "__stage", "__tl", "__tick", "__base", "__backward", eVar, sVar, false);
        EmitMarkers(w, a, s, "__tl", "__tick", "__base", eVar, sVar);
        if (guardStage) W(w, "}");
    }

    static void EmitLegacyLoop(StringBuilder w, SystemAssignment a, KernelShape s)
    {
        EmitLocalDecls(w, s);
        EmitEntityScanOpen(w);
        W(w, "var __count = __e < __pview.EntityCount ? __pview.Counts[__e] : 0;\nif (__count == 0) continue;\nfor (var __s = 0; __s < __count; __s++)\n{\nvar __ps = __pview.SlotOf(__e, __s);\nif (__ps->Timeline == 0 || ((__ps->Flags & (__PF.Ended | __PF.Paused | __PF.Stopping)) != 0 && !Tl.PlaybackRules.Resumes(__ps->Flags, forward))) continue;\nvar __pcopy = *__ps;\nvar __pb = __ps->Rate == 0 ? __ps : &__pcopy;\nvar __pk = Tl.PlaybackRules.Crossings(in *__ps);\nfor (var __j = 0; __j < __pk; __j++)\n{\nif (__j > 0 && (Tl.PlaybackRules.Advance(ref __pcopy, __view.Timelines, __view.TimelineCount, forward) != Tl.AdvanceResult.Kept || (__pcopy.Flags & (__PF.Ended | __PF.Paused)) != 0)) break;\nvar __tl = Tl.LibraryViewReader.GetTimeline(in __view, new Tl.TimelineId(__pb->Timeline));\nif (__tl is null || __tl->Duration == 0) continue;");
        EmitLegacyFrameHead(w, a, s, "__pb", "__e", "__s", false);
        W(w, "}\n}\n}\n}");
    }

    static void EmitClearPulses(StringBuilder w, SystemAssignment a, string ks, string limit)
    {
        foreach (var pk in a.Kinds) if (pk.PrecombinedPulses) W(w, $"{ks}.ClearPulseHits({ks}.IndexOf(\"{pk.Id}\"), {limit});");
    }

    static void EmitKindLoops(StringBuilder w, SystemAssignment a, KernelShape s)
    {
        if (a.Kinds.Count == 0) return;
        W(w, $"var __ks = players.Kinds;\nif (__ks != null)\n{{\nKinds(world, players, __ks, forward{KindArgs(s, false)});");
        EmitClearPulses(w, a, "__ks", "__n");
        W(w, "}");
    }

    static string ListArgs(KernelShape s, Func<int, string> col, string mid, Func<int, string> ctx, Func<int, string>? req = null, Func<int, string>? ev = null)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < s.Columns.Count; i++) if (s.UsedColumns[i]) sb.Append(", ").Append(col(i));
        sb.Append(", ").Append(mid);
        for (var i = 0; i < s.Contexts.Count; i++) if (s.UsedContexts[i]) sb.Append(", ").Append(ctx(i));
        if (req != null) for (var i = 0; i < s.Requests.Count; i++) sb.Append(", ").Append(req(i));
        if (ev != null) for (var i = 0; i < s.Events.Count; i++) sb.Append(", ").Append(ev(i));
        return sb.ToString();
    }

    static string KindArgs(KernelShape s, bool typed, string words = "0, 2147483647")
        => ListArgs(s, i => typed ? $"{s.Columns[i].ElementTypeName}* __c{i}" : $"__c{i}", typed ? "int __n, int __firstWord, int __endWord" : $"__n, {words}", i => $"ref {(typed ? s.Contexts[i].ElementTypeName + " " : "")}__ctx{i}");

    static void EmitCloseMethod(StringBuilder w, SystemAssignment a, KernelShape s)
    {
        W(w, $"{BaseSig(s, "RunClose", false)}\n{{\nvar __view = world.View; var __pview = players.View;");
        EmitLocalDecls(w, s); EmitCloseLoop(w, a, s); W(w, "}");
    }

    static void EmitLegacyRangeMethod(StringBuilder w, SystemAssignment a, KernelShape s)
    {
        W(w, $"{BaseSig(s, "RunLegacyRange", true)}\n{{\nvar __view = world.View; var __pview = players.View;");
        EmitLegacyLoop(w, a, s); W(w, "}");
    }

    static string PArgs(KernelShape s, bool tail = true)
        => ListArgs(s, i => $"__s->__c{i}", "__s->__n, __fw, __ew", i => $"ref *({s.Contexts[i].ElementTypeName}*)__s->__x{i}", tail ? i => "__sr" + i : null, tail ? i => $"__se{i}" : null);

    static void EmitKindMethods(StringBuilder w, SystemAssignment a, KernelShape s, int feedKey)
    {
        var values = new List<int>();
        for (var i = 0; i < a.Kinds.Count && values.Count < 10; i++)
            if (a.Kinds[i].Precombined) values.Add(i);
        var runs = new List<List<int>>();
        var run = new List<int>();
        for (var i = 0; i < a.Kinds.Count; i++)
        {
            var k = a.Kinds[i];
            var ctx = BindsContext(s, k.ApplyParams);
            if (!ctx) foreach (var f in FeedersOf(a, k)) if (BindsContext(s, f.feeder.Method.Params)) { ctx = true; break; }
            if (values.Contains(i) && k.Group.Length == 0 && k.IdleParams is null && !ctx) run.Add(i);
            else { if (run.Count >= 2) runs.Add(run); run = new List<int>(); }
        }
        if (run.Count >= 2) runs.Add(run);
        var head = $"(Tl.TimelineWorld world, Tl.PlaybackTable players, Tl.KindStore __ks, bool forward{KindArgs(s, true)})";
        W(w, $"internal static void Kinds{head}\n{{");
        var rAt = 0;
        for (var i = 0; i < a.Kinds.Count; i++)
        {
            var cur = rAt < runs.Count ? runs[rAt] : null;
            var name = runs.Count == 1 ? "Fused" : $"Fused_{rAt}";
            if (cur != null && i == cur[0]) W(w, $"if (!{name}(world, players, __ks, forward{KindArgs(s, false, "__firstWord, __endWord")}))\n{{");
            W(w, $"Kind_{i}(world, players, __ks, forward{KindArgs(s, false, "__firstWord, __endWord")});");
            if (cur != null && i == cur[cur.Count - 1]) { W(w, "}"); rAt++; }
        }
        W(w, "}");
        for (var i = 0; i < a.Kinds.Count; i++)
        {
            W(w, $"internal static void Kind_{i}{head}\n{{\nvar __view = world.View;\nvar __pview = players.View;");
            EmitKind(w, a, s, a.Kinds[i], feedKey, i, values.Contains(i));
            W(w, "}");
            if (values.Contains(i)) EmitValuesStruct(w, a, s, a.Kinds[i], i, true);
            else if (a.Kinds[i].PrecombinedPulses) EmitValuesStruct(w, a, s, a.Kinds[i], i, false);
        }
        if (values.Count == 0) return;
        W(w, "internal struct KindFill : Tl.IKindFill\n{\npublic Tl.KindStore Store;\npublic void Add(ref Tl.KindBuild __b)\n{");
        foreach (var i in values)
        {
            var k = a.Kinds[i];
            W(w, $"{{ var __r = Store.Join(\"{k.Id}\", sizeof({k.ValueTypeName}), \"{Signature(a, k)}\", 0, out var __me); var __s = default(KindSpans_{i}); __b.Add<{k.ValueTypeName}, KindSpans_{i}>(Store.IndexOf(\"{k.Id}\"), __me, __r, ref __s); }}");
        }
        W(w, "}\n}");
        for (var r = 0; r < runs.Count; r++) EmitFused(w, a, s, runs[r], head, runs.Count == 1 ? "Fused" : $"Fused_{r}");
    }

    static bool BindsContext(KernelShape s, IReadOnlyList<ConsumerParam> ps)
    {
        foreach (var p in ps)
            if (p.Kind == ConsumerParamKind.Context || (p.Kind is (ConsumerParamKind.Column or ConsumerParamKind.ColumnReadOnly) && ColumnOf(s, p.TypeName, p.Kind == ConsumerParamKind.Column) < 0 && ContextOf(s, p.TypeName) >= 0))
                return true;
        return false;
    }

    static string ApplyTail(KernelShape s, KindDecl k)
    {
        var args = CallArgs(s, new ConsumerMethod(ConsumerMethodKind.ExecuteActive, k.ApplyParams, [], []), 0, "", "__e", "");
        return args.Length == 0 ? "" : ", " + args;
    }

    static string Signature(SystemAssignment a, KindDecl k)
    {
        var parts = FeedersOf(a, k).ConvertAll(static f => $"{f.feeder.ConsumerMetadata}.{f.feeder.MethodName}:{(int)f.feeder.Trigger}");
        if (k.Group.Length > 0) parts.Insert(0, "@" + k.Group);
        return string.Join("\\n", parts);
    }

    static string Acc(KindDecl k, string item, string total = "__total", string has = "__has", string sep = "\n")
        => $"if ({has}) {k.TypeName}.Combine(ref {total}, in {item});{sep}else {{ {total} = {item}; {has} = true; }}";

    static void EmitFused(StringBuilder w, SystemAssignment a, KernelShape s, List<int> fused, string head, string name)
    {
        var f0 = fused[0];
        W(w, $"internal static bool {name}{head}\n{{\nvar __view = world.View; var __pview = players.View; var __kfill = new KindFill {{ Store = __ks }}; var __pl = __ks.Playing;");
        foreach (var i in fused)
        {
            var k = a.Kinds[i];
            W(w, $"var __routes{i} = __ks.Join(\"{k.Id}\", sizeof({k.ValueTypeName}), \"{Signature(a, k)}\", 0, out var __me{i}); var __kid{i} = __ks.IndexOf(\"{k.Id}\"); var __kt{i} = __ks.Table(__kid{i});\nif (__kt{i} == null || __routes{i} == null || !__ks.RowsAreEntities(__kid{i})) return false;\nvar __kv{i} = __ks.SpanValues(__kid{i}, __me{i}, ref __kfill); if (__kv{i} == null || __kv{i}->Data != __kv{f0}->Data) return false;");
        }
        W(w, $"var __vrow = __kv{f0}->Row; var __vdata = __kv{f0}->Data; var __vstride = (nuint)__kv{f0}->Stride; var __vtc = (uint)__kv{f0}->TimelineCount;\nvar __pslots = __pview.Slots; var __pcounts = __pview.Counts; var __pspilled = __pview.Spilled; var __pblocks = __pview.Blocks; var __pspe = (nuint)__pview.SlotsPerEntity; var __hasSamples = __ks.HasSamples;");
        foreach (var i in fused)
            W(w, $"var __vsh{i} = __kv{i}->Shift; var __vfr{i} = __kv{i}->Front; var __vbk{i} = __kv{i}->Back; var __vf{i} = forward ? __vfr{i} : __vbk{i}; var __vm{i} = 1u << (__vsh{i} + (forward ? 1 : 2));");
        W(w, $"for (var __kw = __firstWord < 0 ? 0 : __firstWord; __kw < __endWord && __kw < __kt{f0}->Words; __kw++)\n{{\nvar __plw = __pl[__kw];");
        foreach (var i in fused) W(w, $"var __ka{i} = __kt{i}->Active[__kw]; var __kb{i} = __kt{i}->Enabled[__kw] & (__ka{i} | __plw);");
