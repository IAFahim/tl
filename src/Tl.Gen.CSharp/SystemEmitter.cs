    }

    static void EmitCases(StringBuilder w, SystemAssignment a, KernelShape s, List<(int consumer, FeederDecl feeder)> fs, bool spans, string skip = "continue", bool preEval = false)
    {
        var any = false;
        for (var i = 0; i < fs.Count; i++)
        {
            var (c, feeder) = fs[i];
            if ((feeder.Trigger == FeederTrigger.Span) != spans) continue;
            if (!any) { W(w, "switch (__r & 0xff)\n{"); any = true; }
            var consumer = a.Consumers[c];
            W(w, $"case {i}:\n{{");
            if (feeder.Trigger == FeederTrigger.Marker)
                W(w, $"byte* __mptr{c};\nif (!Tl.MarkerTableRegistry.TryResolve(world, __tl->Id, __ks.MarkerOf(__en->Timeline, __en->Step), sizeof({consumer.MarkerTypeName}), out __mptr{c})) throw new System.InvalidOperationException(\"Tl: marker values are not published for this library.\");\n{consumer.MarkerTypeName} __m{c} = *({consumer.MarkerTypeName}*)__mptr{c};\nvar __mf{c} = new Tl.MarkerFrame<{consumer.MarkerTypeName}>(in __m{c}, __tick, 0, __kflags);\n__v = {consumer.ConsumerTypeName}.{feeder.MethodName}({CallArgs(s, feeder.Method, c, $"__mf{c}", "__e", "")});");
            else
            {
                if (!spans && !preEval) W(w, "var __def = __ks.StepOf(__en->Timeline, __en->Step, __tick);\nif (__def == null || __tick < __def->WindowStart || __tick >= __def->WindowEnd) break;");
                EmitMaterialize(w, consumer, c, "__tl", "__tick", "__backward", "__kflags");
                if (FoldOf(consumer) is not null) EmitFeeds(w, consumer, c);
                var frameVar = $"__f{c}";
                if (IsTlFrame(feeder.Method)) { frameVar = $"__tf{c}"; W(w, $"var {frameVar} = new Tl.TlFrame<{consumer.ClipTypeName}>(in __f{c});"); }
                W(w, $"__v = {consumer.ConsumerTypeName}.{feeder.MethodName}({CallArgs(s, feeder.Method, c, frameVar, "__e", $"__fd{c}_")});");
            }
            W(w, "__ok = true;\nbreak;\n}");
        }
        if (any) W(w, "}");
        W(w, $"if (!__ok) {skip};");
    }

    static void EmitEntryWalk(StringBuilder w, SystemAssignment a, KernelShape s, KindDecl k, List<(int consumer, FeederDecl feeder)> fs, string value, int valueAt, string tail)
    {
        W(w, "for (var __j = 0; __j < __len; __j++)\n{\nvar __en = (Tl.KindEntry*)(__data + (nuint)__j * (nuint)__stride);");
        if (k.Group.Length > 0) W(w, "if (*(ushort*)((byte*)__en + 8) != __kid) continue;");
        W(w, $"if (__sampled && !Tl.KindRules.Due(__en, __sj, __run, __cnt)) continue;\n{value} __v = default;\n__pulses++;\nif (__en->Timeline == 0)\n__v = System.Runtime.CompilerServices.Unsafe.ReadUnaligned<{value}>((byte*)__en + {valueAt});\nelse\n{{\nvar __r = __routes[__en->Feeder];\nif ((__r >> 8) != __me)\n{{\nif ((__en->Flags & Tl.KindEntryFlags.Ready) == 0) continue;\n__v = System.Runtime.CompilerServices.Unsafe.ReadUnaligned<{value}>((byte*)__en + {valueAt});\n__en->Flags &= ~Tl.KindEntryFlags.Ready;\n}}\nelse\n{{");
        EmitEntryHead(w);
        EmitCases(w, a, s, fs, false);
        W(w, "}\n}");
        if (k.Each) W(w, $"{k.TypeName}.Apply(in __v{tail});");
        else W(w, Acc(k, "__v"));
        W(w, "}");
    }

    static void EmitFeedEntries(StringBuilder w, SystemAssignment a, KernelShape s, KindDecl k, List<(int consumer, FeederDecl feeder)> fs, string value, int valueAt)
    {
        W(w, "for (var __j = 0; __j < __len; __j++)\n{\nvar __en = (Tl.KindEntry*)(__data + (nuint)__j * (nuint)__stride);");
        if (k.Group.Length > 0) W(w, "if (*(ushort*)((byte*)__en + 8) != __kid) continue;");
