    static void EmitFusedKernel(StringBuilder w, SystemAssignment a, KernelShape s, string id)
    {
        W(w, $"{BaseSig(s, "RunFusedRange", true)}\n{{\nvar __view = world.View; var __pview = players.View;");
        EmitLocalDecls(w, s);
        EmitEntityScanOpen(w);
        W(w, "var __cnt = __e < __pview.EntityCount ? __pview.Counts[__e] : 0;\nfor (var __s = 0; __s < __cnt; __s++)\n{\nvar __pb = __pview.SlotOf(__e, __s);\nif (__pb->Timeline == 0) continue;\nvar __pfl = __pb->Flags;\nif ((__pfl & (__PF.Ended | __PF.Paused)) != 0 && !Tl.PlaybackRules.Unpark(ref *__pb, forward)) { if (!Tl.PlaybackRules.IsParked(__pfl)) __pb->Flags = __pfl & ~__PF.StartPending; }\nelse\n{\nvar __pk = Tl.PlaybackRules.Cross(ref *__pb);\nfor (var __j = 0; __j < __pk; __j++)\n{\nif (__pb->Timeline == 0 || (uint)(__pb->Timeline - 1) >= (uint)__view.TimelineCount) throw new System.ArgumentException($\"Playback slot {__s} of entity {__e} names no timeline in the loaded library.\");\nvar __tl = __view.Timelines + (__pb->Timeline - 1);\nvar __dur = __tl->Duration;\nif (__dur != 0)\n{");
        EmitLegacyFrameHead(w, a, s, "__pb", "__e", "__s", true);
        W(w, "}\nvar __advance = Tl.PlaybackRules.Advance(ref *__pb, __view.Timelines, __view.TimelineCount, forward);\nif (__advance == Tl.AdvanceResult.Removed)\n{\n__pb[0] = default;\nvar __hw = __pview.Counts[__e];\nwhile (__hw > 0 && __pview.SlotOf(__e, __hw - 1)->Timeline == 0) __hw--;\n__pview.Counts[__e] = __hw;\nbreak;\n}\nif ((__pb->Flags & (__PF.Ended | __PF.Paused)) != 0) break;\n}\n}\n}\n}\n}\n}");
    }

    static void EmitLocalDecls(StringBuilder w, KernelShape s)
    {
        for (var i = 0; i < s.Requests.Count; i++) W(w, "Tl.Requests __rq" + i + ";");
        for (var i = 0; i < s.Events.Count; i++) W(w, $"{s.Events[i].TypeName} __eb{i};");
    }

    static void EmitBind(StringBuilder w, KernelShape s, string entity, string slot)
    {
        for (var i = 0; i < s.Requests.Count; i++) W(w, $"__rq{i} = __req{i}.For({entity}, {slot});");
        for (var i = 0; i < s.Events.Count; i++) W(w, $"__eb{i} = __ev{i}; __eb{i}.Bind({entity}, {slot});");
    }

    static void EmitCloseLoop(StringBuilder w, SystemAssignment a, KernelShape s)
    {
        W(w, "var __closing = players.Closing;\nfor (var __ci = 0; __ci < __closing->Count; __ci++)\n{\n__closing->Get(__ci, out var __ce, out var __cs, out var __cpb);\nvar __ctl = Tl.LibraryViewReader.GetTimeline(in __view, new Tl.TimelineId(__cpb.Timeline));\nif (__ctl is null || __ctl->Duration == 0) continue;\nvar __ctick = __cpb.Tick < __ctl->Duration ? __cpb.Tick : (ushort)(__ctl->Duration - 1);\nvar __cstage = Tl.LibraryViewReader.StageAt(__ctl, __ctick);\nif (__cstage is null) continue;\nvar __csteps = Tl.SystemDispatch.FilteredSteps(world, SystemKey, __ctl->Id, (int)(__cstage - __ctl->Stages), PairKeys);\nvar __cbackward = forward ? (__cpb.Flags & __PF.Reverse) != 0 : (__cpb.Flags & __PF.Reverse) == 0;\nvar __cbase = (__cbackward ? __FF.Reverse : __FF.None) | __FF.Interrupted;\nif (__ctick == 0) __cbase |= __FF.TimelineStart;\nif (__ctick == (ushort)(__ctl->Duration - 1)) __cbase |= __FF.TimelineEnd;");
        EmitBind(w, s, "__ce", "__cs");
        EmitEntryLoop(w, a, s, "__csteps", "__cstage", "__ctl", "__ctick", "__cbase", "__cbackward", "__ce", "__cs", true);
        W(w, "}");
    }

    static void EmitEntryLoop(StringBuilder w, SystemAssignment a, KernelShape s, string steps, string stage, string tl, string tick, string flags, string backward, string entity, string slot, bool closing)
    {
        var cs = a.Consumers;
        W(w, $"for (var __i = 0; __i < {steps}.Length; __i++)\n{{\nvar __entry = {steps}[__i];\nswitch (__entry.Consumer)\n{{");
        for (var c = 0; c < cs.Count; c++)
        {
            var x = cs[c];
            if (x.IsMarker || !IsLegacy(x)) continue;
            W(w, $"case {c}:\n{{\nvar __def = {stage}->Steps + __entry.Step;\nif ({tick} < __def->WindowStart || {tick} >= __def->WindowEnd) break;");
            if (closing) EmitCloseCase(w, a, s, x, c, flags, entity, tick, tl);
            else EmitStepCase(w, a, s, x, c, flags, backward, entity, tl, tick);
            W(w, "break;\n}");
        }
        W(w, "}\n}");
    }

    static void EmitMaterialize(StringBuilder w, SystemConsumer c, int index, string tl, string tick, string backward, string flags)
        => W(w, $"byte* __row{index} = (byte*)__def->FrameRow;\nbyte* __first{index} = __row{index} + sizeof({c.TrackTypeName});\nbyte* __second{index} = __def->FactorSpan == 0 ? null : __first{index} + sizeof({c.ClipTypeName});\nfloat __blend{index} = __def->FactorSpan == 0 ? 0f : (__def->FactorSpan <= 1 ? 0.5f : ({tick} - __def->FactorStart) / (float)(__def->FactorSpan - 1));\nushort __len{index} = (ushort)(__def->WindowEnd - __def->WindowStart);\nushort __within{index} = (ushort)({tick} - __def->WindowStart);\nsbyte __dir{index} = {backward} ? (sbyte)-1 : (sbyte)1;\nFrame_{index}(__row{index}, __first{index}, __second{index}, __blend{index}, {tick}, __len{index}, __within{index}, (ushort)__def->TrackIndex, (ushort){tl}->Duration, __dir{index}, {flags}, out var __t{index}, out var __cc{index}, out var __f{index});");

    static void EmitFeeds(StringBuilder w, SystemConsumer c, int index)
    {
        var fold = FoldOf(c);
        if (fold is null || LaneBytes(c) == 0) return;
        W(w, $"byte* __lane{index} = (byte*)__def->FoldLane + (((uint)__tick - __def->WindowStart) * 2u + (__backward ? 1u : 0u)) * (uint){LaneBytes(c)};");
        for (var o = 0; o < fold.Params.Count; o++) W(w, $"{fold.Params[o].TypeName} __fd{index}_{o} = default;");
        W(w, "if (__def->FoldLane == null)\n{");
        var args = new StringBuilder($"in __f{index}");
        for (var o = 0; o < fold.Params.Count; o++) args.Append($", {fold.Params[o].Modifier}__fd{index}_{o}");
        W(w, $"{c.ConsumerTypeName}.Fold({args});\n}}\nelse\n{{");
        var off = 0;
        for (var o = 0; o < fold.Params.Count; o++)
        {
            W(w, $"__fd{index}_{o} = *({fold.Params[o].TypeName}*)(__lane{index} + {off});");
            off += fold.FoldSizes[o];
        }
        W(w, "}");
    }

    static string CallArgs(KernelShape s, ConsumerMethod m, int index, string frameVar, string rowVar, string feedPrefix)
    {
        var args = new List<string>();
        var start = 0;
        if (m.Params.Count > 0 && m.Params[0].Kind is ConsumerParamKind.Frame or ConsumerParamKind.MarkerFrame)
        {
            args.Add(s.TlFrames.TryGetValue(m, out var clip) ? $"new global::Tl.TlFrame<{clip}>(in {frameVar})" : $"in {frameVar}");
            start = 1;
        }
        for (var i = start; i < m.Params.Count; i++)
        {
            var p = m.Params[i];
            switch (p.Kind)
            {
                case ConsumerParamKind.FoldFeed: args.Add($"in {feedPrefix}{p.FoldIndex}"); break;
                case ConsumerParamKind.Column:
                {
                    var at = ColumnOf(s, p.TypeName, true);
                    args.Add(at >= 0 ? $"ref __c{at}[{rowVar}]" : $"{p.Modifier}__ctx{ContextOf(s, p.TypeName)}");
                    break;
                }
                case ConsumerParamKind.ColumnReadOnly:
                {
                    var at = ColumnOf(s, p.TypeName, false);
                    args.Add(at >= 0 ? $"in __c{at}[{rowVar}]" : $"{p.Modifier}__ctx{ContextOf(s, p.TypeName)}");
                    break;
                }
                case ConsumerParamKind.Context: args.Add($"{p.Modifier}__ctx{ContextOf(s, p.TypeName)}"); break;
                case ConsumerParamKind.Requests: args.Add($"ref __rq{RequestOf(s)}"); break;
                case ConsumerParamKind.Events: args.Add($"ref __eb{EventOf(s, Tl.Gen.CSharp.Analysis.SystemReader.EventElement(p.TypeName))}"); break;
            }
        }
        return string.Join(", ", args);
    }

    static void EmitCloseCase(StringBuilder w, SystemAssignment a, KernelShape s, SystemConsumer c, int index, string flags, string entity, string tick, string tl)
    {
        ConsumerMethod? end = null;
        foreach (var m in c.Methods) if (m.Kind == ConsumerMethodKind.OnClipEnd) end = m;
        if (end is null) return;
        EmitMaterialize(w, c, index, tl, tick, "__cbackward", flags);
        W(w, $"{c.ConsumerTypeName}.OnClipEnd({CallArgs(s, end, index, $"__f{index}", entity, $"__fd{index}_")});");
    }

    static void EmitStepCase(StringBuilder w, SystemAssignment a, KernelShape s, SystemConsumer c, int index, string flags, string backward, string entity, string tl, string tick)
    {
        ConsumerMethod? active = null, start = null, end = null;
        foreach (var m in c.Methods)
        {
            if (m.Kind == ConsumerMethodKind.ExecuteActive) active = m;
            if (m.Kind == ConsumerMethodKind.OnClipStart) start = m;
            if (m.Kind == ConsumerMethodKind.OnClipEnd) end = m;
        }
        var direct = active is not null && start is null && active.Direct.Eligible;
        if (!direct)
        {
            EmitMaterialize(w, c, index, tl, tick, backward, flags);
            if (FoldOf(c) is not null) EmitFeeds(w, c, index);
        }
        if (active is not null)
        {
            if (direct)
            {
                W(w, "if (__def->FoldLane == null)\n{");
                EmitMaterialize(w, c, index, tl, tick, backward, flags);
                if (FoldOf(c) is not null) EmitFeeds(w, c, index);
                W(w, $"{c.ConsumerTypeName}.ExecuteActive({CallArgs(s, active, index, $"__f{index}", entity, $"__fd{index}_")});\n}}\nelse\n{{");
                EmitDirectStep(w, s, c, active, index, entity, tick, backward);
                W(w, "}");
            }
            else W(w, $"{c.ConsumerTypeName}.ExecuteActive({CallArgs(s, active, index, $"__f{index}", entity, $"__fd{index}_")});");
        }
        if (start is not null) W(w, $"if ({tick} == __def->WindowStart && (__pb->Flags & __PF.ReenterPending) == 0) {c.ConsumerTypeName}.OnClipStart({CallArgs(s, start, index, $"__f{index}", entity, $"__fd{index}_")});");
        if (end is not null && !direct) W(w, $"if ({tick} == __def->WindowEnd - 1 && (__pb->Flags & __PF.ReenterPending) == 0) {c.ConsumerTypeName}.OnClipEnd({CallArgs(s, end, index, $"__f{index}", entity, $"__fd{index}_")});");
    }

    static void EmitDirectStep(StringBuilder w, KernelShape s, SystemConsumer c, ConsumerMethod active, int index, string entity, string tick, string backward)
    {
        var d = active.Direct;
        var fold = FoldOf(c);
        var stride = fold is null ? 4 : LaneBytes(c);
        var written = ColumnOf(s, d.WrittenType, true);
        var writtenRef = d.WrittenMember.Length == 0 ? $"__c{written}[{entity}]" : $"__c{written}[{entity}].{d.WrittenMember}";
        if (d.FoldOffsets.Count > 0) W(w, $"byte* __lane{index} = (byte*)__def->FoldLane + (((uint){tick} - __def->WindowStart) * 2u + ({backward} ? 1u : 0u)) * (uint){stride};");
        var parts = new List<string>();
        for (var k = 0; k < d.FoldOffsets.Count; k++)
        {
            W(w, $"float __fd{index}_{k} = *(float*)((byte*)__lane{index} + {d.FoldOffsets[k]});");
            parts.Add($"__fd{index}_{k}");
        }
        foreach (var r in d.ReadTypes) parts.Add($"__c{ColumnOf(s, r, false)}[{entity}]");
        W(w, $"{writtenRef} {d.Op} {string.Join(" * ", parts)};");
    }

    static void EmitMarkers(StringBuilder w, SystemAssignment a, KernelShape s, string tl, string tick, string flags, string entity, string slot)
    {
        var markers = new List<(SystemConsumer consumer, int index, ConsumerMethod? method)>();
        for (var i = 0; i < a.Consumers.Count; i++)
        {
            if (!a.Consumers[i].IsMarker) continue;
            ConsumerMethod? method = null;
            foreach (var cand in a.Consumers[i].Methods) if (cand.Kind == ConsumerMethodKind.OnMarker) method = cand;
            if (method is not null) markers.Add((a.Consumers[i], i, method));
        }
        if (markers.Count == 0) return;
        W(w, $"if ((__pb->Flags & __PF.ReenterPending) == 0 && Tl.LibraryViewReader.HasEvent({tl}, {tick}))\n{{\nvar __mev = Tl.LibraryViewReader.Events({tl});\nfor (var __mk = 0; __mk < __mev.Length; __mk++)\n{{\nif (__mev[__mk].Tick != {tick} || __mev[__mk].Kind != 2) continue;");
        foreach (var mk in markers)
        {
            var c = mk.consumer;
            W(w, $"byte* __mptr{mk.index};\nif (!Tl.MarkerTableRegistry.TryResolve(world, {tl}->Id, __mev[__mk].Marker, sizeof({c.MarkerTypeName}), out __mptr{mk.index})) throw new System.InvalidOperationException(\"Tl: marker values are not published for this library.\");\n{c.MarkerTypeName} __m{mk.index} = *({c.MarkerTypeName}*)__mptr{mk.index};\nvar __mf{mk.index} = new Tl.MarkerFrame<{c.MarkerTypeName}>(in __m{mk.index}, {tick}, 0, {flags});\n{c.ConsumerTypeName}.OnMarker({CallArgs(s, mk.method!, mk.index, $"__mf{mk.index}", entity, "")});");
        }
        W(w, "}\n}");
    }

    static void EmitRun(StringBuilder w, SystemAssignment a, string id) => EmitRunCore(w, a, id, false);
    static void EmitRunFused(StringBuilder w, SystemAssignment a, string id) => EmitRunCore(w, a, id, true);

    static void EmitRunCore(StringBuilder w, SystemAssignment a, string id, bool fused)
    {
        var sys = a.System;
        var s = ShapeOf(a, id);
        var ns = NamespaceOf(sys.TypeName);
        var shortName = ShortNameOf(sys.TypeName);
        var safe = $"{id}_{Sanitize(sys.TypeName)}";
        var name = fused ? "RunFused" : "Run";
        void LenCheck()
        {
            W(w, "int __len = players.EntityCapacity;");
            var first = true;
            foreach (var f in sys.Fields)
            {
                if (f.Kind is not (SystemFieldKind.Column or SystemFieldKind.ColumnReadOnly)) continue;
                if (first) { W(w, $"__len = this.{f.Name}.Length;"); first = false; }
                else W(w, $"if (this.{f.Name}.Length != __len) throw new System.ArgumentException(\"{sys.TypeName}: column {f.Name} lengths differ.\");");
            }
            W(w, $"if (__len > players.EntityCapacity) throw new System.ArgumentException(\"{sys.TypeName}: column length exceeds table capacity.\");");
        }
        var pins = new List<string>();
        for (var i = 0; i < s.Columns.Count; i++) if (s.UsedColumns[i]) pins.Add($"fixed ({s.Columns[i].ElementTypeName}* __p{i} = this.{s.Columns[i].Name})");
        void WithPins(Action body) { if (pins.Count == 0) body(); else { foreach (var pin in pins) { W(w, pin); W(w, "{"); } body(); foreach (var pin in pins) W(w, "}"); } }
        string Args(bool range)
            => ListArgs(s, i => $"__p{i}", range ? "__len, 0, 2147483647" : "__len", i => $"ref this.{s.Contexts[i].Name}", i => $"this.{s.Requests[i].Name}", i => $"this.{s.Events[i].Name}");
        if (ns.Length > 0) { W(w, $"namespace {ns}"); W(w, "{"); }
        W(w, $"partial struct {shortName}\n{{\npublic unsafe void {name}(Tl.TimelineWorld world, Tl.PlaybackTable players, bool forward = true)\n{{\nif (world is null) throw new System.ArgumentNullException(nameof(world));\nif (players is null) throw new System.ArgumentNullException(nameof(players));");
        LenCheck();
        WithPins(() => W(w, fused
            ? $"if (players.Kinds != null) throw new System.InvalidOperationException(\"RunFused advances playbacks itself; use TimelineWorld.Tick with Run when a KindStore is attached.\"); TlSystems.TlSystem_{safe}.RunClose(world, players, forward{Args(false)}); TlSystems.TlSystem_{safe}.RunFusedRange(world, players, forward{Args(true)}); Tl.ClosingList.Clear(players.Closing);"
            : $"TlSystems.TlSystem_{safe}.{name}(world, players, forward{Args(false)});"));
        W(w, "}");
        if (!fused && a.Parallel)
        {
            var hasLegacy = HasLegacy(a);
            var init = new StringBuilder("var __st = new __PS { ");
            W(w, "unsafe struct __PS { public System.IntPtr __w; public System.IntPtr __p;");
            for (var i = 0; i < s.Columns.Count; i++) if (s.UsedColumns[i]) { W(w, $"public {s.Columns[i].ElementTypeName}* __c{i};"); init.Append($"__c{i} = __p{i}, "); }
            W(w, "public int __n; public int __forward;");
            for (var i = 0; i < s.Contexts.Count; i++) if (s.UsedContexts[i]) W(w, $"public void* __x{i};");
            for (var i = 0; i < s.Requests.Count; i++) W(w, "public Tl.RequestQueue** __rq;");
            for (var i = 0; i < s.Events.Count; i++) W(w, $"public {s.Events[i].TypeName}* __ev{i};");
            W(w, "}\nstatic unsafe void __PChunk(void* __p, int __fw, int __ew, int __chunk) { var __s = (__PS*)__p; var world = (Tl.TimelineWorld)Tl.TlWorkers.Target(__s->__w); var players = (Tl.PlaybackTable)Tl.TlWorkers.Target(__s->__p); var forward = __s->__forward != 0;");
            for (var i = 0; i < s.Requests.Count; i++) W(w, $"Tl.Requests __sr{i} = new Tl.Requests(__s->__rq[__chunk], 0, 0);");
            for (var i = 0; i < s.Events.Count; i++) W(w, $"{s.Events[i].TypeName} __se{i} = __s->__ev{i}[__chunk].Writer;");
            if (hasLegacy) W(w, $"TlSystems.TlSystem_{safe}.RunLegacyRange(world, players, forward{PArgs(s)});");
            if (a.Kinds.Count > 0) W(w, $"var __ks = players.Kinds; if (__ks != null) TlSystems.TlSystem_{safe}.Kinds(world, players, __ks, forward{PArgs(s, false)});");
            W(w, "}\npublic unsafe void Run(Tl.TimelineWorld world, Tl.PlaybackTable players, bool forward, Tl.TlWorkers workers)\n{\nif (world is null) throw new System.ArgumentNullException(nameof(world)); if (players is null) throw new System.ArgumentNullException(nameof(players)); if (workers is null) throw new System.ArgumentNullException(nameof(workers));");
            LenCheck();
            WithPins(() =>
            {
                W(w, $"if (workers.WorkerCount == 1) {{ TlSystems.TlSystem_{safe}.Run(world, players, forward{Args(false)}); return; }}");
                if (hasLegacy) W(w, $"TlSystems.TlSystem_{safe}.RunClose(world, players, forward{Args(false)});");
                W(w, "var __words = players.PlayingWords; var __chunks = System.Math.Min(workers.WorkerCount * 8, __words); if (__chunks <= 0) return; var __ends = stackalloc int[__chunks]; Tl.TlWorkers.Split(players.Playing, __words, __ends, __chunks);");
                for (var i = 0; i < s.Requests.Count; i++) { W(w, "var __rq = stackalloc Tl.RequestQueue*[__chunks]; for (var __i = 0; __i < __chunks; __i++) __rq[__i] = Tl.RequestQueue.Create();"); init.Append("__rq = __rq, "); }
                for (var i = 0; i < s.Events.Count; i++) { W(w, $"var __segs{i} = stackalloc {s.Events[i].TypeName}[__chunks]; for (var __i = 0; __i < __chunks; __i++) __segs{i}[__i] = new {s.Events[i].TypeName}(128);"); init.Append($"__ev{i} = __segs{i}, "); }
                for (var i = 0; i < s.Contexts.Count; i++) if (s.UsedContexts[i]) init.Append($"__x{i} = System.Runtime.CompilerServices.Unsafe.AsPointer(ref this.{s.Contexts[i].Name}), ");
                init.Append("__n = __len, __forward = forward ? 1 : 0 };");
                W(w, $"{init}\nvar __wh = Tl.TlWorkers.Pin(world); var __ph = Tl.TlWorkers.Pin(players); __st.__w = __wh; __st.__p = __ph; try {{ workers.Run(&__PChunk, &__st, __ends, __chunks); }} finally {{ Tl.TlWorkers.Free(__wh); Tl.TlWorkers.Free(__ph); }}");
                if (a.Kinds.Any(static k => k.PrecombinedPulses))
                {
                    W(w, "if (players.Kinds != null)\n{");
                    EmitClearPulses(w, a, "players.Kinds", "__len");
                    W(w, "}");
                }
                for (var i = 0; i < s.Requests.Count; i++) W(w, $"this.{s.Requests[i].Name}.ConcatSegments(__rq, __chunks); for (var __i = 0; __i < __chunks; __i++) Tl.RequestQueue.Free(__rq[__i]);");
                for (var i = 0; i < s.Events.Count; i++) W(w, $"this.{s.Events[i].Name}.ConcatSegments(__segs{i}, __chunks); for (var __j = 0; __j < __chunks; __j++) __segs{i}[__j].Dispose();");
            });
            W(w, "}");
        }
        W(w, "}");
        if (ns.Length > 0) W(w, "}");
    }
