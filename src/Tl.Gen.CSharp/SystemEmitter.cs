        => W(w, $"var __tl = Tl.LibraryViewReader.GetTimeline(in __view, new Tl.TimelineId({timeline}));\nushort __tick = __pb->Tick;\nvar __backward = forward ? (__pb->Flags & __PF.Reverse) != 0 : (__pb->Flags & __PF.Reverse) == 0;");

    static void EmitFrameFlags(StringBuilder w, string? synthetic, string? interrupted)
    {
        void Flag(string? t, string f) { if (t != null) W(w, $"if ({t}) __kflags |= __FF.{f};"); }
        W(w, "var __kflags = __FF.None;");
        Flag("__backward", "Reverse"); Flag(synthetic, "Synthetic"); Flag(interrupted, "Interrupted");
        Flag("__tick == 0", "TimelineStart"); Flag("__tick == (ushort)(__tl->Duration - 1)", "TimelineEnd");
