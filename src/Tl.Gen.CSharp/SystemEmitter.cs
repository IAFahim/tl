    }

    static void EmitKind(StringBuilder w, SystemAssignment a, KernelShape s, KindDecl k, int feedKey, int index, bool values)
    {
        var fs = FeedersOf(a, k);
        var valueAt = k.Group.Length > 0 ? 12 : 8;
        var value = k.ValueTypeName;
        var tail = ApplyTail(s, k);
        var feed = k.Foreign;
        var spanless = !feed && k.Accepts == 1;
        W(w, $"{{\nvar __routes = __ks.Join(\"{k.Id}\", sizeof({value}), \"{Signature(a, k)}\", {(feed ? feedKey : 0)}, out var __me);\nvar __kid = __ks.IndexOf(\"{k.Id}\");\nvar __kt = __ks.Table(__kid);\nif (__kt != null && __routes != null)\n{{\nif (__firstWord < 0) __firstWord = 0;\nif (__endWord > __kt->Words) __endWord = __kt->Words;\nif (__firstWord > __endWord) __firstWord = __endWord;\nvar __stride = __kt->Stride;");
        if (!spanless) W(w, "var __score = __ks.Score;\nvar __pl = __ks.Playing;\nvar __whole = __ks.RowsAreEntities(__kid);");
        W(w, "var __lst = __ks.ListedOf(__kid);");
        if (values) W(w, "var __kfill = new KindFill { Store = __ks }; var __kv = __ks.SpanValues(__kid, __me, ref __kfill);");
        if (k.PrecombinedPulses)
        {
            W(w, $"var __kpe = default(KindPulses_{index}); var __kpv = __ks.PulseValues<{value}, KindPulses_{index}>(__kid, __me, ref __kpe);\nif (__kpv != null)\n{{\nvar __ph = __ks.PulseHitsOf(__kid);\nvar __lo = __firstWord == 0 ? 0 : __ph->LowerBound(__firstWord << 6);\nvar __hi = __endWord >= __kt->Words ? __ph->Count : __ph->LowerBound(__endWord << 6);\nvar __hits = __ph->Items; var __ps = __kpv->Start; var __pv = ({value}*)__kpv->Data; var __ken = __kt->Enabled; var __kac = __kt->Active;\nfor (var __idx = __lo; __idx < __hi; )\n{{\nvar __e = __hits[__idx].Entity;\nif (__e >= __n) break;\nvar __ew = __e >> 6; var __eb = 1ul << (__e & 63);\nif ((__ken[__ew] & __eb) == 0) {{ while (__idx < __hi && __hits[__idx].Entity == __e) __idx++; continue; }}");
            if (!k.Each) W(w, $"{value} __total = default; var __has = false;");
            W(w, "do\n{\nvar __cell = __hits[__idx++].Cell;\nfor (var __p = __ps[__cell]; __p < __ps[__cell + 1]; __p++)");
            if (k.Each) W(w, $"{k.TypeName}.Apply(in __pv[__p]{tail});");
            else W(w, Acc(k, "__pv[__p]", sep: " "));
            W(w, "} while (__idx < __hi && __hits[__idx].Entity == __e);\nif ((__kac[__ew] & __eb) != 0)\n{\nvar __row = __e; var __len = (int)__kt->Length[__row]; byte* __data = __kt->Data(__row); var __run = __pview.RunOf(__e); var __cnt = __pview.CountOf(__e); var __sampled = false; var __sj = 0; var __pulses = 0;");
            EmitEntryWalk(w, a, s, k, fs, value, valueAt, tail);
            W(w, "if (__len != 0) __kt->Clear(__row);\n}");
            if (!k.Each) W(w, $"if (__has) {k.TypeName}.Apply(in __total{tail});");
            W(w, "}\n}");
        }
        W(w, $"for (var __kw = __firstWord; __kw < __endWord; __kw++)\n{{\n{(spanless ? "var __kb = __kt->Enabled[__kw] & __kt->Active[__kw];" : "var __kb = __kt->Enabled[__kw] & (__whole ? __kt->Active[__kw] | __lst[__kw] | __pl[__kw] : ~0ul);")}\nwhile (__kb != 0)\n{{\nvar __row = (__kw << 6) + Tl.KindStore.TrailingZeros(__kb);\n__kb &= __kb - 1;\nvar __e = __kt->Entity[__row];\nif (__e >= __n) continue;\nvar __len = (int)__kt->Length[__row];\nbyte* __data = __kt->Data(__row);\nvar __run = __pview.RunOf(__e);\nvar __cnt = __pview.CountOf(__e);\nvar __smp = __ks.SamplesOf(__e);");
        if (!feed)
        {
            W(w, "var __pulses = 0;");
            if (!spanless) W(w, "var __listed = false;");
            W(w, "var __sampled = __smp != 0;\nvar __sk = __sampled ? Tl.KindRules.Depth(__run + __cnt, __smp) : 1;\nfor (var __sj = 0; __sj < __sk; __sj++)\n{");
            if (!k.Each) W(w, $"{value} __total = default;\nvar __has = false;");
        }
        if (feed)
        {
            EmitDrop(w, "(__q->Flags & Tl.KindEntryFlags.Span) != 0" + (k.Group.Length > 0 ? " && *(ushort*)((byte*)__q + 8) == __kid" : "") + " && (__routes[__q->Feeder] >> 8) == __me");
            EmitFeedEntries(w, a, s, k, fs, value, valueAt);
        }
        if (values)
        {
            W(w, "if (__kv != null)\n{");
            EmitValueWalk(w, k);
            W(w, "}\nelse\n{");
        }
        if (!spanless) EmitSpanWalk(w, a, s, k, fs, feed, value, valueAt, tail);
        if (values) W(w, "}");
        if (!feed) EmitEntryWalk(w, a, s, k, fs, value, valueAt, tail);
        if (!feed)
        {
            if (!k.Each) W(w, $"if (__has) {k.TypeName}.Apply(in __total{tail});");
            W(w, "}");
            W(w, spanless ? "__lst[__row >> 6] &= ~(1ul << (__row & 63));" : "if (__listed) __lst[__row >> 6] |= 1ul << (__row & 63); else __lst[__row >> 6] &= ~(1ul << (__row & 63));");
            if (k.Group.Length == 0) W(w, "if (__len != 0) __kt->Clear(__row);");
            else
            {
                W(w, "if (__sampled || __pulses != 0)\n{");
                EmitDrop(w, "*(ushort*)((byte*)__q + 8) == __kid");
                W(w, "}");
            }
        }
        W(w, "}\n}");
        if (k.IdleParams is not null) EmitIdle(w, s, k);
        W(w, "}\n}");
    }

    static void EmitDrop(StringBuilder w, string drop)
        => W(w, $"var __kept = 0;\nfor (var __j = 0; __j < __len; __j++)\n{{\nvar __q = (Tl.KindEntry*)(__data + (nuint)__j * (nuint)__stride);\nif ({drop}) continue;\nif (__kept != __j) System.Buffer.MemoryCopy(__q, __data + (nuint)__kept * (nuint)__stride, __stride, __stride);\n__kept++;\n}}\n__len = __kept;\nif (__kept == 0) __kt->Clear(__row); else __kt->Length[__row] = (ushort)__kept;");

    static void EmitSpanWalk(StringBuilder w, SystemAssignment a, KernelShape s, KindDecl k, List<(int consumer, FeederDecl feeder)> fs, bool feed, string value, int valueAt, string tail)
    {
        W(w, "for (var __q = 0; __q < __cnt + __smp; __q++)\n{\nvar __i = __q < __smp ? __cnt + __q : __q - __smp;\nvar __pb = __run + __i;\nif (__pb->Timeline == 0 || !Tl.KindScore.Listed(__pb->Flags)) continue;\nvar __cell = __score.CellOf(__pb->Timeline, __pb->Tick, __kid);\nif (__cell < 0 || __score.Start[__cell] == __score.Start[__cell + 1]) continue;");
