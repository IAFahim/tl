using System;
using System.Collections.Generic;
using System.Text;
using Tl.Gen.CSharp.Model;

namespace Tl.Gen.CSharp;

internal static class SystemEmitter
{
    internal static string Emit(IReadOnlyList<SystemAssignment> assignments, string id)
    {
        var writer = new StringBuilder();
        writer.Append("// <auto-generated/>\n");
        writer.Append("namespace TlSystems\n");
        writer.Append("{\n");
        foreach (var assignment in assignments)
            EmitSystem(writer, assignment, id);
        writer.Append("}\n");
        foreach (var assignment in assignments)
            EmitRun(writer, assignment, id);
        return writer.ToString().Replace("\r\n", "\n");
    }

    static void W(StringBuilder writer, string text)
    {
        writer.Append(text).Append('\n');
    }

    static string Sanitize(string typeName)
    {
        var builder = new StringBuilder();
        foreach (var c in typeName) builder.Append(char.IsLetterOrDigit(c) ? c : '_');
        return builder.ToString();
    }

    static string NamespaceOf(string typeName)
    {
        var bare = typeName.StartsWith("global::", StringComparison.Ordinal) ? typeName.Substring(8) : typeName;
        var dot = bare.LastIndexOf('.');
        return dot < 0 ? "" : bare.Substring(0, dot);
    }

    static string ShortNameOf(string typeName)
    {
        var bare = typeName.StartsWith("global::", StringComparison.Ordinal) ? typeName.Substring(8) : typeName;
        var dot = bare.LastIndexOf('.');
        var plus = bare.LastIndexOf('+');
        var cut = dot > plus ? dot : plus;
        return cut < 0 ? bare : bare.Substring(cut + 1);
    }

    sealed class KernelShape
    {
        public List<SystemField> Columns = new();
        public List<SystemField> Contexts = new();
        public bool[] UsedColumns = Array.Empty<bool>();
        public bool[] UsedContexts = Array.Empty<bool>();
        public string Safe = "";
    }

    static KernelShape ShapeOf(SystemAssignment assignment, string id)
    {
        var shape = new KernelShape { Safe = $"{id}_{Sanitize(assignment.System.TypeName)}" };
        foreach (var field in assignment.System.Fields)
        {
            switch (field.Kind)
            {
                case SystemFieldKind.Column:
                case SystemFieldKind.ColumnReadOnly: shape.Columns.Add(field); break;
                case SystemFieldKind.Context: shape.Contexts.Add(field); break;
            }
        }
        shape.UsedColumns = new bool[shape.Columns.Count];
        shape.UsedContexts = new bool[shape.Contexts.Count];
        var parameters = new List<ConsumerParam>();
        foreach (var consumer in assignment.Consumers)
            foreach (var method in consumer.Methods)
                parameters.AddRange(method.Params);
        foreach (var kind in assignment.Kinds)
        {
            parameters.AddRange(kind.ApplyParams);
            if (kind.IdleParams is not null) parameters.AddRange(kind.IdleParams);
        }
        foreach (var parameter in parameters)
        {
            if (parameter.Kind is ConsumerParamKind.Column or ConsumerParamKind.ColumnReadOnly)
            {
                var at = shape.Columns.FindIndex(field => field.ElementTypeName == parameter.TypeName);
                if (at >= 0 && (parameter.Kind == ConsumerParamKind.ColumnReadOnly || shape.Columns[at].Kind == SystemFieldKind.Column)) shape.UsedColumns[at] = true;
                else
                {
                    var ctx = shape.Contexts.FindIndex(field => field.ElementTypeName == parameter.TypeName);
                    if (ctx >= 0) shape.UsedContexts[ctx] = true;
                }
            }
        }
        return shape;
    }

    static int ColumnOf(KernelShape shape, string element, bool writable)
    {
        for (var i = 0; i < shape.Columns.Count; i++)
        {
            if (!shape.UsedColumns[i] || shape.Columns[i].ElementTypeName != element) continue;
            if (!writable || shape.Columns[i].Kind == SystemFieldKind.Column) return i;
        }
        return -1;
    }

    static int ContextOf(KernelShape shape, string element)
    {
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i] && shape.Contexts[i].ElementTypeName == element) return i;
        return -1;
    }

    static string SpanParams(KernelShape shape)
    {
        var signature = new StringBuilder();
        for (var i = 0; i < shape.Columns.Count; i++)
            if (shape.UsedColumns[i]) signature.Append($", global::System.Span<{shape.Columns[i].ElementTypeName}> __c{i}");
        signature.Append(", int __n");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) signature.Append($", ref {shape.Contexts[i].ElementTypeName} __ctx{i}");
        return signature.ToString();
    }

    static string SpanArgs(KernelShape shape)
    {
        var args = new StringBuilder();
        for (var i = 0; i < shape.Columns.Count; i++)
            if (shape.UsedColumns[i]) args.Append($", __c{i}");
        args.Append(", __n");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) args.Append($", ref __ctx{i}");
        return args.ToString();
    }

    static void EmitSystem(StringBuilder writer, SystemAssignment assignment, string id)
    {
        var shape = ShapeOf(assignment, id);
        W(writer, $"internal static class TlSystem_{shape.Safe}");
        W(writer, "{");
        W(writer, $"internal static void Run(global::Tl.World world, global::Tl.Direction __direction{SpanParams(shape)})");
        W(writer, "{");
        W(writer, "if (world is null) throw new global::System.ArgumentNullException(nameof(world));");
        for (var i = 0; i < assignment.Kinds.Count; i++)
            if (UsesTable(assignment.Kinds[i], shape))
                W(writer, $"if (!world.TryKindTable<{assignment.Kinds[i].ValueTypeName}>({BinderIdOf(assignment.Kinds[i])}, out _)) world.RegisterKind<{assignment.Kinds[i].ValueTypeName}>(new TlKindBinder_{i}());");
        W(writer, "world.Tick(__direction);");
        for (var i = 0; i < assignment.Kinds.Count; i++)
            W(writer, $"Kind_{i}(world{SpanArgs(shape)});");
        W(writer, "}");
        EmitKindBinders(writer, assignment);
        for (var i = 0; i < assignment.Kinds.Count; i++)
            EmitKind(writer, assignment, shape, assignment.Kinds[i], i);
        W(writer, "}");
    }

    static int BinderIdOf(KindDecl kind)
        => kind.ValueTypeName is "int" or "global::System.Int32" ? 0
            : kind.ValueTypeName is "float" or "global::System.Single" ? 1
            : kind.Order;

    static bool UsesTable(KindDecl kind, KernelShape shape)
    {
        if (kind.Each || kind.Foreign) return false;
        if (kind.CombineKind != IrKind.Monoid || kind.ApplyKind != IrKind.Affine) return false;
        return kind.ApplyParams.Count == 1 && kind.ApplyParams[0].Kind == ConsumerParamKind.Column
            && kind.ApplyParams[0].TypeName == kind.ValueTypeName
            && ColumnOf(shape, kind.ApplyParams[0].TypeName, true) >= 0;
    }

    static void EmitKindBinders(StringBuilder writer, SystemAssignment assignment)
    {
        for (var i = 0; i < assignment.Kinds.Count; i++)
        {
            var kind = assignment.Kinds[i];
            var hasCombine = !kind.Each && kind.CombineKind == IrKind.Monoid && !kind.Foreign;
            var hasAffine = kind.ApplyKind == IrKind.Affine && !kind.Foreign;
            if (!hasCombine && !hasAffine) continue;
            if (hasCombine)
            {
                W(writer, $"internal static {kind.ValueTypeName} TlKind_{i}_Combine({kind.ValueTypeName} __total, {kind.ValueTypeName} __v)");
                W(writer, "{");
                W(writer, $"{kind.TypeName}.Combine(ref __total, in __v);");
                W(writer, "return __total;");
                W(writer, "}");
            }
            if (hasAffine)
            {
                W(writer, $"internal static void TlKind_{i}_ApplyAffine(in {kind.ValueTypeName} __value, ref {kind.ValueTypeName} __column)");
                W(writer, "{");
                W(writer, $"__column = {AffineExpression(kind.ApplyOp, "__column", "__value")};");
                W(writer, "}");
            }
            if (hasCombine && hasAffine)
            {
                W(writer, $"internal sealed class TlKindBinder_{i} : global::Tl.Kind<{kind.ValueTypeName}>");
                W(writer, "{");
                W(writer, $"public override int Id => {BinderIdOf(kind)};");
                W(writer, $"public override int Order => {kind.Order};");
                W(writer, $"public override {kind.ValueTypeName} Idle => default;");
                W(writer, $"public override {kind.ValueTypeName} Combine({kind.ValueTypeName} acc, {kind.ValueTypeName} value) => TlKind_{i}_Combine(acc, value);");
                W(writer, $"public override void Apply(in {kind.ValueTypeName} value, ref {kind.ValueTypeName} column) => TlKind_{i}_ApplyAffine(in value, ref column);");
                W(writer, "}");
            }
        }
    }

    static string AffineExpression(string op, string left, string right) => op switch
    {
        "+" => left + " + " + right,
        "*" => left + " * " + right,
        "|" => left + " | " + right,
        "&" => left + " & " + right,
        "min" => "global::System.Math.Min(" + left + ", " + right + ")",
        "max" => "global::System.Math.Max(" + left + ", " + right + ")",
        _ => left + " + " + right,
    };

    static string LaneValue(string valueType, string rowVar)
    {
        if (valueType is "float" or "global::System.Single") return $"__acc[{rowVar}]";
        if (valueType is "int" or "global::System.Int32") return $"(int)__acc[{rowVar}]";
        return null!;
    }

    static void EmitKind(StringBuilder writer, SystemAssignment assignment, KernelShape shape, KindDecl kind, int kindIndex)
    {
        W(writer, $"internal static void Kind_{kindIndex}(global::Tl.World world{SpanParams(shape)})");
        W(writer, "{");
        if (UsesTable(kind, shape))
        {
            var at = ColumnOf(shape, kind.ApplyParams[0].TypeName, true);
            W(writer, $"var __table = world.KindTable<{kind.ValueTypeName}>({BinderIdOf(kind)});");
            W(writer, "var __acc = world.Accumulator;");
            var tableFeed = LaneValue(kind.ValueTypeName, "__r");
            if (tableFeed is not null)
            {
                W(writer, "for (var __r = 0; __r < __n; ++__r)");
                W(writer, "{");
                W(writer, "if (__r >= __table.Rows) break;");
                W(writer, $"__table.Add(__r, {tableFeed});");
                W(writer, "}");
            }
            W(writer, $"__table.ApplyAll(__c{at});");
            W(writer, "__table.Reset();");
            W(writer, "}");
            return;
        }
        var apply = new ConsumerMethod(ConsumerMethodKind.ExecuteActive, kind.ApplyParams, [], []);
        var tail = CallArgs(shape, apply, "__e");
        var value = kind.ValueTypeName;
        var affineAt = -1;
        if (kind.ApplyKind == IrKind.Affine && !kind.Foreign && kind.ApplyParams.Count == 1 && kind.ApplyParams[0].Kind == ConsumerParamKind.Column && kind.ApplyParams[0].TypeName == value)
            affineAt = ColumnOf(shape, value, true);
        W(writer, "var __acc = world.Accumulator;");
        W(writer, "for (var __e = 0; __e < __n; ++__e)");
        W(writer, "{");
        W(writer, "if (__e >= __acc.Length) break;");
        var feed = LaneValue(value, "__e");
        if (feed is null) W(writer, $"{value} __v = default;");
        else W(writer, $"{value} __v = {feed};");
        if (kind.Each)
        {
            if (affineAt >= 0) W(writer, $"TlKind_{kindIndex}_ApplyAffine(in __v, ref __c{affineAt}[__e]);");
            else W(writer, $"{kind.TypeName}.Apply(in __v{tail});");
        }
        else
        {
            W(writer, $"{value} __total = __v;");
            if (affineAt >= 0) W(writer, $"TlKind_{kindIndex}_ApplyAffine(in __total, ref __c{affineAt}[__e]);");
            else W(writer, $"{kind.TypeName}.Apply(in __total{tail});");
        }
        W(writer, "}");
        W(writer, "}");
    }

    static string CallArgs(KernelShape shape, ConsumerMethod method, string rowVar)
    {
        var args = new List<string>();
        foreach (var parameter in method.Params)
        {
            switch (parameter.Kind)
            {
                case ConsumerParamKind.Column:
                {
                    var at = ColumnOf(shape, parameter.TypeName, true);
                    if (at >= 0) args.Add($"ref __c{at}[{rowVar}]");
                    else args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
                }
                case ConsumerParamKind.ColumnReadOnly:
                {
                    var at = ColumnOf(shape, parameter.TypeName, false);
                    if (at >= 0) args.Add($"in __c{at}[{rowVar}]");
                    else args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
                }
                case ConsumerParamKind.Context:
                    args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
            }
        }
        return args.Count == 0 ? "" : ", " + string.Join(", ", args);
    }

    static void EmitRun(StringBuilder writer, SystemAssignment assignment, string id)
    {
        var system = assignment.System;
        var shape = ShapeOf(assignment, id);
        var ns = NamespaceOf(system.TypeName);
        var shortName = ShortNameOf(system.TypeName);
        var safe = $"{id}_{Sanitize(system.TypeName)}";
        if (ns.Length > 0)
        {
            W(writer, $"namespace {ns}");
            W(writer, "{");
        }
        W(writer, $"partial struct {shortName}");
        W(writer, "{");
        W(writer, "public void Run(global::Tl.World world, global::Tl.Direction direction = global::Tl.Direction.Forward)");
        W(writer, "{");
        W(writer, "if (world is null) throw new global::System.ArgumentNullException(nameof(world));");
        W(writer, "int __len = world.RowCapacity;");
        foreach (var field in system.Fields)
        {
            if (field.Kind is not (SystemFieldKind.Column or SystemFieldKind.ColumnReadOnly)) continue;
            W(writer, $"if (this.{field.Name}.Length != __len) throw new global::System.ArgumentException(\"{system.TypeName}: column {field.Name} lengths differ.\");");
        }
        var call = new StringBuilder();
        call.Append($"global::TlSystems.TlSystem_{safe}.Run(world, direction");
        foreach (var field in system.Fields)
        {
            if (field.Kind is not (SystemFieldKind.Column or SystemFieldKind.ColumnReadOnly)) continue;
            var at = shape.Columns.FindIndex(f => f.Name == field.Name);
            if (at < 0 || !shape.UsedColumns[at]) continue;
            call.Append($", this.{field.Name}");
        }
        call.Append(", __len");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) call.Append($", ref this.{shape.Contexts[i].Name}");
        call.Append(");");
        W(writer, call.ToString());
        W(writer, "}");
        W(writer, "}");
        if (ns.Length > 0) W(writer, "}");
    }
}
