namespace Tl.Gen.CSharp;

internal static class SystemEmitter
{
    internal static string Emit(IReadOnlyList<SystemAssignment> assignments, string id, ISet<string>? tlFrames = null, int feedKey = 0)
    {
        var writer = new StringBuilder();
        writer.Append("// <auto-generated/>\n");
        writer.Append("namespace TlSystems\n");
        writer.Append("{\n");
        EmitModule(writer, assignments, id);
        foreach (var assignment in assignments)
            EmitSystem(writer, assignment, id, tlFrames, feedKey);
        writer.Append("}\n");
        foreach (var assignment in assignments)
            EmitRun(writer, assignment, id);
        foreach (var assignment in assignments)
            if (HasLegacy(assignment)) EmitRunFused(writer, assignment, id);
        return writer.ToString().Replace("\r\n", "\n");
    }

    static bool IsLegacy(SystemConsumer consumer)
    {
        foreach (var method in consumer.Methods)
            if (method.Kind != ConsumerMethodKind.Feeder) return true;
        return false;
    }

    static bool HasLegacy(SystemAssignment assignment)
    {
        foreach (var consumer in assignment.Consumers)
            if (IsLegacy(consumer)) return true;
        return false;
    }

    static void W(StringBuilder writer, string text)
    {
        writer.Append(text).Append('\n');
    }

    static void EmitModule(StringBuilder writer, IReadOnlyList<SystemAssignment> assignments, string id)
    {
        var folds = new List<(SystemConsumer consumer, int assignment, int index)>();
        for (var a = 0; a < assignments.Count; a++)
            for (var c = 0; c < assignments[a].Consumers.Count; c++)
            {
                var has = false;
                foreach (var method in assignments[a].Consumers[c].Methods)
                    if (method.Kind == ConsumerMethodKind.Fold) has = true;
                if (has && !assignments[a].Consumers[c].IsMarker) folds.Add((assignments[a].Consumers[c], a, c));
            }
        W(writer, $"internal sealed class TlModule_{id} : global::Tl.ITlModule");
        W(writer, "{");
        W(writer, $"public int PairCount => {folds.Count};");
        W(writer, "public ulong PairKey(int index)");
        W(writer, "{");
        W(writer, "switch (index)");
        W(writer, "{");
        for (var i = 0; i < folds.Count; i++) W(writer, $"case {i}: return {folds[i].consumer.PairKey}UL;");
        W(writer, "default: return 0UL;");
        W(writer, "}");
        W(writer, "}");
        W(writer, "public int FoldLaneBytes(int index)");
        W(writer, "{");
        W(writer, "switch (index)");
        W(writer, "{");
        for (var i = 0; i < folds.Count; i++) W(writer, $"case {i}: return {LaneBytes(folds[i].consumer)};");
        W(writer, "default: return 0;");
        W(writer, "}");
        W(writer, "}");
        W(writer, "public int FoldLaneOffset(int index)");
        W(writer, "{");
        W(writer, "switch (index)");
        W(writer, "{");
        for (var i = 0; i < folds.Count; i++) W(writer, $"case {i}: return {LaneOffset(folds, i)};");
        W(writer, "default: return 0;");
        W(writer, "}");
        W(writer, "}");
        W(writer, "public unsafe void FoldStep(int index, byte* track, byte* first, byte* second, float blend, ushort tick, ushort windowLength, ushort withinClip, ushort trackIndex, ushort duration, sbyte direction, byte* lane)");
        W(writer, "{");
        W(writer, "switch (index)");
        W(writer, "{");
        for (var i = 0; i < folds.Count; i++)
        {
            var fold = folds[i];
            W(writer, $"case {i}:");
            W(writer, "{");
            W(writer, $"TlSystem_{id}_{Sanitize(assignments[fold.assignment].System.TypeName)}.Frame_{fold.index}(track, first, second == first ? null : second, blend, tick, windowLength, withinClip, trackIndex, duration, direction, global::Tl.FrameFlags.None, out var __t, out var __c, out var __frame);");
            var method = FoldOf(fold.consumer)!;
            for (var o = 0; o < method.Params.Count; o++)
                W(writer, $"{method.Params[o].TypeName} __out{o} = default;");
            var outs = new List<string>();
            for (var o = 0; o < method.Params.Count; o++) outs.Add($"out __out{o}");
            W(writer, $"{fold.consumer.ConsumerTypeName}.Fold(in __frame, {string.Join(", ", outs)});");
            var offset = 0;
            for (var o = 0; o < method.Params.Count; o++)
            {
                W(writer, $"*({method.Params[o].TypeName}*)(lane + {offset}) = __out{o};");
                offset += method.FoldSizes[o];
            }
            W(writer, "return;");
            W(writer, "}");
        }
        W(writer, "default: return;");
        W(writer, "}");
        W(writer, "}");
        W(writer, "internal static void Install()");
        W(writer, "{");
        W(writer, $"global::Tl.TlGenerated.Install(new TlModule_{id}());");
        W(writer, "}");
        W(writer, "#if NET");
        W(writer, "[global::System.Runtime.CompilerServices.ModuleInitializer]");
        W(writer, "internal static void InstallModule() => Install();");
        W(writer, "#endif");
        W(writer, "}");
    }

    static ConsumerMethod? FoldOf(SystemConsumer consumer)
    {
        foreach (var method in consumer.Methods)
            if (method.Kind == ConsumerMethodKind.Fold) return method;
        return null;
    }

    static int LaneBytes(SystemConsumer consumer)
    {
        var fold = FoldOf(consumer);
        if (fold is null) return 0;
        var bytes = 0;
        foreach (var size in fold.FoldSizes) bytes += size;
        return bytes;
    }

    static int LaneOffset(List<(SystemConsumer consumer, int assignment, int index)> folds, int at)
    {
        var sum = 0;
        for (var k = 0; k < at; k++)
            if (folds[k].consumer.PairKey == folds[at].consumer.PairKey) sum += LaneBytes(folds[k].consumer);
        return sum;
    }

    static int FoldOutOffset(SystemConsumer consumer, string element)
    {
        var fold = FoldOf(consumer);
        if (fold is null) return 0;
        var offset = 0;
        for (var o = 0; o < fold.Params.Count; o++)
        {
            if (string.Equals(fold.Params[o].TypeName, element, StringComparison.Ordinal)) return offset;
            offset += fold.FoldSizes[o];
        }
        return offset;
    }

    static void EmitFrameHelper(StringBuilder writer, SystemConsumer consumer, int index)
    {
        W(writer, $"internal static void Frame_{index}(byte* trackPtr, byte* firstPtr, byte* secondPtr, float blend, ushort tick, ushort windowLength, ushort withinClip, ushort trackIndex, ushort duration, sbyte direction, global::Tl.FrameFlags extra, out {consumer.TrackTypeName} track, out {consumer.ClipTypeName} clip, out global::Tl.Frame<{consumer.TrackTypeName}, {consumer.ClipTypeName}> frame)");
        W(writer, "{");
        W(writer, $"track = *({consumer.TrackTypeName}*)trackPtr;");
        W(writer, $"clip = *({consumer.ClipTypeName}*)firstPtr;");
        W(writer, "if (secondPtr != null)");
        W(writer, "{");
        W(writer, $"{consumer.ClipTypeName} __second = *({consumer.ClipTypeName}*)secondPtr;");
        if (consumer.TrackBlendable)
            W(writer, "track.Blend(in clip, in __second, blend, out clip);");
        else
            W(writer, $"throw new global::System.InvalidOperationException(\"{consumer.ConsumerTypeName}: blended window without IBlend.\");");
        W(writer, "}");
        W(writer, "var __flags = (direction < 0 ? global::Tl.FrameFlags.Reverse : global::Tl.FrameFlags.None) | extra;");
        W(writer, "if (withinClip == 0) __flags |= global::Tl.FrameFlags.ClipStart;");
        W(writer, "if (withinClip == (ushort)(windowLength - 1)) __flags |= global::Tl.FrameFlags.ClipEnd;");
        W(writer, "if (tick == 0) __flags |= global::Tl.FrameFlags.TimelineStart;");
        W(writer, "if (tick == (ushort)(duration - 1)) __flags |= global::Tl.FrameFlags.TimelineEnd;");
        W(writer, $"frame = new global::Tl.Frame<{consumer.TrackTypeName}, {consumer.ClipTypeName}>(in track, in clip, tick, windowLength, withinClip, trackIndex, __flags);");
        W(writer, "}");
    }

    static string Sanitize(string typeName)
    {
        var builder = new StringBuilder();
        foreach (var c in typeName) builder.Append(char.IsLetterOrDigit(c) ? c : '_');
        return builder.ToString();
    }

    static string NamespaceOf(string typeName)
    {
        var bare = typeName.StartsWith("global::", StringComparison.Ordinal) ? typeName.Substring(8) : typeName;
        var dot = bare.LastIndexOf('.');
        return dot < 0 ? "" : bare.Substring(0, dot);
    }

    static string ShortNameOf(string typeName)
    {
        var bare = typeName.StartsWith("global::", StringComparison.Ordinal) ? typeName.Substring(8) : typeName;
        var dot = bare.LastIndexOf('.');
        var plus = bare.LastIndexOf('+');
        var cut = dot > plus ? dot : plus;
        return cut < 0 ? bare : bare.Substring(cut + 1);
    }

    sealed class KernelShape
    {
        public List<SystemField> Columns = new();
        public List<SystemField> Contexts = new();
        public List<SystemField> Requests = new();
        public List<SystemField> Events = new();
        public bool[] UsedColumns = Array.Empty<bool>();
        public bool[] UsedContexts = Array.Empty<bool>();
        public string Safe = "";
    }

    static KernelShape ShapeOf(SystemAssignment assignment, string id)
    {
        var shape = new KernelShape { Safe = $"{id}_{Sanitize(assignment.System.TypeName)}" };
        foreach (var field in assignment.System.Fields)
        {
            switch (field.Kind)
            {
                case SystemFieldKind.Column:
                case SystemFieldKind.ColumnReadOnly: shape.Columns.Add(field); break;
                case SystemFieldKind.Context: shape.Contexts.Add(field); break;
                case SystemFieldKind.Requests: shape.Requests.Add(field); break;
                case SystemFieldKind.Events: shape.Events.Add(field); break;
            }
        }
        shape.UsedColumns = new bool[shape.Columns.Count];
        shape.UsedContexts = new bool[shape.Contexts.Count];
        var parameters = new List<ConsumerParam>();
        foreach (var consumer in assignment.Consumers)
            foreach (var method in consumer.Methods)
                parameters.AddRange(method.Params);
        foreach (var kind in assignment.Kinds) parameters.AddRange(kind.ApplyParams);
        foreach (var parameter in parameters)
        {
            if (parameter.Kind is ConsumerParamKind.Column or ConsumerParamKind.ColumnReadOnly)
            {
                var at = shape.Columns.FindIndex(field => field.ElementTypeName == parameter.TypeName);
                if (at >= 0 && (parameter.Kind == ConsumerParamKind.ColumnReadOnly || shape.Columns[at].Kind == SystemFieldKind.Column)) shape.UsedColumns[at] = true;
                else
                {
                    var ctx = shape.Contexts.FindIndex(field => field.ElementTypeName == parameter.TypeName);
                    if (ctx >= 0) shape.UsedContexts[ctx] = true;
                }
            }
        }
        return shape;
    }

    static int ColumnOf(KernelShape shape, string element, bool writable)
    {
        for (var i = 0; i < shape.Columns.Count; i++)
        {
            if (!shape.UsedColumns[i] || shape.Columns[i].ElementTypeName != element) continue;
            if (!writable || shape.Columns[i].Kind == SystemFieldKind.Column) return i;
        }
        return -1;
    }

    static int ContextOf(KernelShape shape, string element)
    {
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i] && shape.Contexts[i].ElementTypeName == element) return i;
        return -1;
    }

    static int RequestOf(KernelShape shape)
    {
        return shape.Requests.Count > 0 ? 0 : -1;
    }

    static int EventOf(KernelShape shape, string element)
    {
        for (var i = 0; i < shape.Events.Count; i++)
            if (shape.Events[i].ElementTypeName == element) return i;
        return -1;
    }

    static void EmitSystem(StringBuilder writer, SystemAssignment assignment, string id, ISet<string>? tlFrames, int feedKey)
    {
        var shape = ShapeOf(assignment, id);
        var consumers = assignment.Consumers;
        W(writer, $"internal static unsafe class TlSystem_{shape.Safe}");
        W(writer, "{");
        W(writer, $"internal const ulong SystemKey = {assignment.System.SystemKey}UL;");
        W(writer, "internal static readonly ulong[] PairKeys = new ulong[]");
        W(writer, "{");
        foreach (var consumer in consumers) W(writer, $"{(IsLegacy(consumer) ? consumer.PairKey : 0UL)}UL,");
        W(writer, "};");
        for (var c = 0; c < consumers.Count; c++)
            if (!consumers[c].IsMarker) EmitFrameHelper(writer, consumers[c], c);
        var signature = new StringBuilder();
        signature.Append("internal static void Run(global::Tl.TimelineWorld world, global::Tl.PlaybackTable players, bool forward");
        for (var i = 0; i < shape.Columns.Count; i++)
            if (shape.UsedColumns[i]) signature.Append($", {shape.Columns[i].ElementTypeName}* __c{i}");
        signature.Append(", int __n");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) signature.Append($", ref {shape.Contexts[i].ElementTypeName} __ctx{i}");
        for (var i = 0; i < shape.Requests.Count; i++) signature.Append(", global::Tl.Requests __req" + i);
        for (var i = 0; i < shape.Events.Count; i++) signature.Append($", {shape.Events[i].TypeName} __ev{i}");
        signature.Append(')');
        W(writer, signature.ToString());
        W(writer, "{");
        W(writer, "if (world is null) throw new global::System.ArgumentNullException(nameof(world));");
        W(writer, "if (players is null) throw new global::System.ArgumentNullException(nameof(players));");
        if (HasLegacy(assignment))
        {
            W(writer, "var __view = world.View;");
            W(writer, "var __pview = players.View;");
            EmitLegacyLoop(writer, assignment, shape);
        }
        EmitKindLoops(writer, assignment, shape);
        W(writer, "}");
        foreach (var batch in BatchConsumers(consumers))
            EmitFlush(writer, assignment, shape, batch.consumer, batch.index);
        EmitKindMethods(writer, assignment, shape, tlFrames, feedKey);
        if (HasLegacy(assignment)) EmitFusedKernel(writer, assignment, shape, id);
        W(writer, "}");
    }

    static void EmitLegacyLoop(StringBuilder writer, SystemAssignment assignment, KernelShape shape)
    {
        EmitLocalDecls(writer, shape);
        EmitCloseLoop(writer, assignment, shape);
        EmitBatchDecls(writer, assignment);
        W(writer, "for (var __e = 0; __e < __n; __e++)");
        W(writer, "{");
        W(writer, "var __count = __e < __pview.EntityCount ? __pview.Counts[__e] : 0;");
        W(writer, "if (__count == 0) continue;");
        W(writer, "for (var __s = 0; __s < __count; __s++)");
        W(writer, "{");
        W(writer, "var __pb = __pview.SlotOf(__e, __s);");
        W(writer, "if (__pb->Timeline == 0 || (__pb->Flags & (global::Tl.PlaybackFlags.Ended | global::Tl.PlaybackFlags.Paused | global::Tl.PlaybackFlags.Stopping)) != 0) continue;");
        W(writer, "var __tl = global::Tl.LibraryViewReader.GetTimeline(in __view, new global::Tl.TimelineId(__pb->Timeline));");
        W(writer, "if (__tl is null || __tl->Duration == 0) continue;");
        W(writer, "var __tick = __pb->Tick;");
        W(writer, "var __stage = global::Tl.LibraryViewReader.StageAt(__tl, __tick);");
        W(writer, "if (__stage is null) continue;");
        W(writer, "var __steps = global::Tl.SystemDispatch.FilteredSteps(world, SystemKey, __tl->Id, (int)(__stage - __tl->Stages), PairKeys);");
        W(writer, "var __backward = forward ? (__pb->Flags & global::Tl.PlaybackFlags.Reverse) != 0 : (__pb->Flags & global::Tl.PlaybackFlags.Reverse) == 0;");
        W(writer, "var __base = __backward ? global::Tl.FrameFlags.Reverse : global::Tl.FrameFlags.None;");
        W(writer, "if ((__pb->Flags & global::Tl.PlaybackFlags.StartPending) != 0 && __tick > 0) __base |= global::Tl.FrameFlags.Synthetic;");
        W(writer, "if (__tick == 0) __base |= global::Tl.FrameFlags.TimelineStart;");
        W(writer, "if (__tick == (ushort)(__tl->Duration - 1)) __base |= global::Tl.FrameFlags.TimelineEnd;");
        EmitBind(writer, shape, "__e", "__s");
        EmitEntryLoop(writer, assignment, shape, "__steps", "__stage", "__tl", "__tick", "__base", "__backward", "__e", "__s", false);
        EmitMarkers(writer, assignment, shape, "__tl", "__tick", "__base", "__e", "__s");
        W(writer, "}");
        W(writer, "}");
        EmitBatchTails(writer, assignment, shape);
    }

    static void EmitKindLoops(StringBuilder writer, SystemAssignment assignment, KernelShape shape)
    {
        if (assignment.Kinds.Count == 0) return;
        W(writer, "var __ks = players.Kinds;");
        W(writer, "if (__ks != null)");
        W(writer, "{");
        for (var i = 0; i < assignment.Kinds.Count; i++) W(writer, $"Kind_{i}(world, players, __ks, forward{KindArgs(shape, false)});");
        W(writer, "}");
    }

    static string KindArgs(KernelShape shape, bool typed)
    {
        var args = new StringBuilder();
        for (var i = 0; i < shape.Columns.Count; i++)
            if (shape.UsedColumns[i]) args.Append(typed ? $", {shape.Columns[i].ElementTypeName}* __c{i}" : $", __c{i}");
        args.Append(typed ? ", int __n" : ", __n");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) args.Append(typed ? $", ref {shape.Contexts[i].ElementTypeName} __ctx{i}" : $", ref __ctx{i}");
        return args.ToString();
    }

    static void EmitKindMethods(StringBuilder writer, SystemAssignment assignment, KernelShape shape, ISet<string>? tlFrames, int feedKey)
    {
        for (var i = 0; i < assignment.Kinds.Count; i++)
        {
            W(writer, $"internal static void Kind_{i}(global::Tl.TimelineWorld world, global::Tl.PlaybackTable players, global::Tl.KindStore __ks, bool forward{KindArgs(shape, true)})");
            W(writer, "{");
            W(writer, "var __view = world.View;");
            W(writer, "var __pview = players.View;");
            EmitKind(writer, assignment, shape, assignment.Kinds[i], tlFrames, feedKey);
            W(writer, "}");
        }
    }

    static void EmitKind(StringBuilder writer, SystemAssignment assignment, KernelShape shape, KindDecl kind, ISet<string>? tlFrames, int feedKey)
    {
        var feeders = new List<(int consumer, FeederDecl feeder)>();
        for (var c = 0; c < assignment.Consumers.Count; c++)
            foreach (var feeder in assignment.Consumers[c].Feeders)
                if (feeder.KindName == kind.Name) feeders.Add((c, feeder));
        feeders.Sort(static (a, b) =>
        {
            var by = string.CompareOrdinal(a.feeder.ConsumerMetadata, b.feeder.ConsumerMetadata);
            return by != 0 ? by : string.CompareOrdinal(a.feeder.MethodName, b.feeder.MethodName);
        });
        var parts = feeders.ConvertAll(static f => $"{f.feeder.ConsumerMetadata}.{f.feeder.MethodName}:{(int)f.feeder.Trigger}");
        if (kind.Group.Length > 0) parts.Insert(0, "@" + kind.Group);
        var signature = string.Join("\\n", parts);
        var valueAt = kind.Group.Length > 0 ? 12 : 8;
        var value = kind.ValueTypeName;
        var apply = new ConsumerMethod(ConsumerMethodKind.ExecuteActive, kind.ApplyParams, [], []);
        var applyArgs = CallArgs(shape, apply, 0, "", "__e", "");
        var tail = applyArgs.Length == 0 ? "" : ", " + applyArgs;
        var feed = kind.Foreign;
        W(writer, "{");
        W(writer, $"var __routes = __ks.Join(\"{kind.Name}\", sizeof({value}), \"{signature}\", {(feed ? feedKey : 0)}, out var __me);");
        if (kind.Group.Length > 0)
        {
            W(writer, $"var __kid = __ks.IndexOf(\"{kind.Name}\");");
            W(writer, "var __kt = __ks.Table(__kid);");
        }
        else W(writer, $"var __kt = __ks.Table(__ks.IndexOf(\"{kind.Name}\"));");
        W(writer, "if (__kt != null && __routes != null)");
        W(writer, "{");
        W(writer, "var __stride = __kt->Stride;");
        W(writer, "for (var __kw = 0; __kw < __kt->Words; __kw++)");
        W(writer, "{");
        W(writer, "var __kb = __kt->Active[__kw] & __kt->Enabled[__kw];");
        W(writer, "while (__kb != 0)");
        W(writer, "{");
        W(writer, "var __row = (__kw << 6) + global::Tl.KindStore.TrailingZeros(__kb);");
        W(writer, "__kb &= __kb - 1;");
        W(writer, "var __e = __kt->Entity[__row];");
        W(writer, "if (__e >= __n) continue;");
        W(writer, "var __len = (int)__kt->Length[__row];");
        W(writer, "byte* __data = __kt->Data(__row);");
        if (!kind.Each && !feed)
        {
            W(writer, $"{value} __total = default;");
            W(writer, "var __has = false;");
        }
        if (!feed) W(writer, "var __pulses = 0;");
        W(writer, "for (var __j = 0; __j < __len; __j++)");
        W(writer, "{");
        W(writer, "var __en = (global::Tl.KindEntry*)(__data + (nuint)__j * (nuint)__stride);");
        if (kind.Group.Length > 0) W(writer, "if (*(ushort*)((byte*)__en + 8) != __kid) continue;");
        W(writer, $"{value} __v = default;");
        if (feed)
        {
            W(writer, "if (__en->Timeline == 0) continue;");
            W(writer, "var __r = __routes[__en->Feeder];");
            W(writer, "if ((__r >> 8) != __me) continue;");
            W(writer, "var __isPulse = (__en->Flags & global::Tl.KindEntryFlags.Pulse) != 0;");
        }
        else
        {
            W(writer, "if (__en->Timeline == 0)");
            W(writer, "{");
            W(writer, $"__v = global::System.Runtime.CompilerServices.Unsafe.ReadUnaligned<{value}>((byte*)__en + {valueAt});");
            W(writer, "__pulses++;");
            W(writer, "}");
            W(writer, "else");
            W(writer, "{");
            W(writer, "var __isPulse = (__en->Flags & global::Tl.KindEntryFlags.Pulse) != 0;");
            W(writer, "if (__isPulse) __pulses++;");
            W(writer, "var __r = __routes[__en->Feeder];");
            W(writer, "if ((__r >> 8) != __me)");
            W(writer, "{");
            W(writer, "if ((__en->Flags & global::Tl.KindEntryFlags.Ready) == 0) continue;");
            W(writer, $"__v = global::System.Runtime.CompilerServices.Unsafe.ReadUnaligned<{value}>((byte*)__en + {valueAt});");
            W(writer, "__en->Flags &= ~global::Tl.KindEntryFlags.Ready;");
            W(writer, "}");
            W(writer, "else");
            W(writer, "{");
        }
        W(writer, "var __pb = __pview.SlotOf(__e, __en->Slot);");
        W(writer, "if (!__isPulse && (__pb->Flags & global::Tl.PlaybackFlags.Paused) != 0) continue;");
        W(writer, "var __tl = global::Tl.LibraryViewReader.GetTimeline(in __view, new global::Tl.TimelineId(__en->Timeline));");
        W(writer, "ushort __tick = __pb->Tick;");
        W(writer, "var __backward = forward ? (__pb->Flags & global::Tl.PlaybackFlags.Reverse) != 0 : (__pb->Flags & global::Tl.PlaybackFlags.Reverse) == 0;");
        W(writer, "var __kflags = (__backward ? global::Tl.FrameFlags.Reverse : global::Tl.FrameFlags.None)");
        W(writer, "| ((__en->Flags & global::Tl.KindEntryFlags.Synthetic) != 0 ? global::Tl.FrameFlags.Synthetic : global::Tl.FrameFlags.None)");
        W(writer, "| ((__en->Flags & global::Tl.KindEntryFlags.Interrupted) != 0 ? global::Tl.FrameFlags.Interrupted : global::Tl.FrameFlags.None);");
        W(writer, "if (__tick == 0) __kflags |= global::Tl.FrameFlags.TimelineStart;");
        W(writer, "if (__tick == (ushort)(__tl->Duration - 1)) __kflags |= global::Tl.FrameFlags.TimelineEnd;");
        W(writer, "var __ok = false;");
        if (feeders.Count > 0)
        {
            W(writer, "switch (__r & 0xff)");
            W(writer, "{");
        }
        for (var i = 0; i < feeders.Count; i++)
        {
            var (c, feeder) = feeders[i];
            var consumer = assignment.Consumers[c];
            W(writer, $"case {i}:");
            W(writer, "{");
            if (feeder.Trigger == FeederTrigger.Marker)
            {
                W(writer, $"byte* __mptr{c};");
                W(writer, $"if (!global::Tl.MarkerTableRegistry.TryResolve(world, __tl->Id, __ks.MarkerOf(__en->Timeline, __en->Step), sizeof({consumer.MarkerTypeName}), out __mptr{c})) throw new global::System.InvalidOperationException(\"Tl: marker values are not published for this library.\");");
                W(writer, $"{consumer.MarkerTypeName} __m{c} = *({consumer.MarkerTypeName}*)__mptr{c};");
                W(writer, $"var __mf{c} = new global::Tl.MarkerFrame<{consumer.MarkerTypeName}>(in __m{c}, __tick, 0, __kflags);");
                W(writer, $"__v = {consumer.ConsumerTypeName}.{feeder.MethodName}({CallArgs(shape, feeder.Method, c, $"__mf{c}", "__e", "")});");
            }
            else
            {
                W(writer, "var __def = __ks.StepOf(__en->Timeline, __en->Step, __tick);");
                W(writer, "if (__def == null || __tick < __def->WindowStart || __tick >= __def->WindowEnd) break;");
                EmitMaterialize(writer, consumer, c, "__tl", "__tick", "__backward", "__kflags");
                if (FoldOf(consumer) is not null) EmitFeeds(writer, consumer, c);
                var frameVar = $"__f{c}";
                if (tlFrames is not null && tlFrames.Contains(NewStyle.FeederKey(consumer.ConsumerTypeName, feeder.MethodName)))
                {
                    frameVar = $"__tf{c}";
                    W(writer, $"var {frameVar} = new global::Tl.TlFrame<{consumer.ClipTypeName}>(in __f{c});");
                }
                W(writer, $"__v = {consumer.ConsumerTypeName}.{feeder.MethodName}({CallArgs(shape, feeder.Method, c, frameVar, "__e", $"__fd{c}_")});");
            }
            W(writer, "__ok = true;");
            W(writer, "break;");
            W(writer, "}");
        }
        if (feeders.Count > 0) W(writer, "}");
        W(writer, "if (!__ok) continue;");
        if (feed)
        {
            W(writer, $"global::System.Runtime.CompilerServices.Unsafe.WriteUnaligned((byte*)__en + {valueAt}, __v);");
            W(writer, "__en->Flags |= global::Tl.KindEntryFlags.Ready;");
            W(writer, "}");
        }
        else
        {
            W(writer, "}");
            W(writer, "}");
            if (kind.Each) W(writer, $"{kind.TypeName}.Apply(in __v{tail});");
            else
            {
                W(writer, $"if (__has) {kind.TypeName}.Combine(ref __total, in __v);");
                W(writer, "else { __total = __v; __has = true; }");
            }
            W(writer, "}");
            if (!kind.Each) W(writer, $"if (__has) {kind.TypeName}.Apply(in __total{tail});");
            W(writer, "if (__pulses == __len) __kt->Clear(__row);");
            W(writer, "else if (__pulses != 0) __kt->RemovePulses(__row);");
        }
        W(writer, "}");
        W(writer, "}");
        W(writer, "}");
        W(writer, "}");
    }

    static void EmitFusedKernel(StringBuilder writer, SystemAssignment assignment, KernelShape shape, string id)
    {
        var signature = new StringBuilder();
        signature.Append("internal static void RunFused(global::Tl.TimelineWorld world, global::Tl.PlaybackTable players, bool forward");
        for (var i = 0; i < shape.Columns.Count; i++)
            if (shape.UsedColumns[i]) signature.Append($", {shape.Columns[i].ElementTypeName}* __c{i}");
        signature.Append(", int __n");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) signature.Append($", ref {shape.Contexts[i].ElementTypeName} __ctx{i}");
        for (var i = 0; i < shape.Requests.Count; i++) signature.Append(", global::Tl.Requests __req" + i);
        for (var i = 0; i < shape.Events.Count; i++) signature.Append($", {shape.Events[i].TypeName} __ev{i}");
        signature.Append(')');
        W(writer, signature.ToString());
        W(writer, "{");
        W(writer, "if (world is null) throw new global::System.ArgumentNullException(nameof(world));");
        W(writer, "if (players is null) throw new global::System.ArgumentNullException(nameof(players));");
        W(writer, "if (players.Kinds != null) throw new global::System.InvalidOperationException(\"RunFused advances playbacks itself; use TimelineWorld.Tick with Run when a KindStore is attached.\");");
        W(writer, "var __view = world.View;");
        W(writer, "var __pview = players.View;");
        EmitLocalDecls(writer, shape);
        EmitCloseLoop(writer, assignment, shape);
        EmitBatchDecls(writer, assignment);
        W(writer, "for (var __e = 0; __e < __n; __e++)");
        W(writer, "{");
        W(writer, "var __cnt = __e < __pview.EntityCount ? __pview.Counts[__e] : 0;");
        W(writer, "for (var __s = 0; __s < __cnt; __s++)");
        W(writer, "{");
        W(writer, "var __pb = __pview.SlotOf(__e, __s);");
        W(writer, "if (__pb->Timeline == 0) continue;");
        W(writer, "var __pfl = __pb->Flags;");
        W(writer, "if ((__pfl & (global::Tl.PlaybackFlags.Ended | global::Tl.PlaybackFlags.Paused)) != 0) { __pb->Flags = __pfl & ~global::Tl.PlaybackFlags.StartPending; }");
        W(writer, "else");
        W(writer, "{");
        W(writer, "if (__pb->Timeline == 0 || (uint)(__pb->Timeline - 1) >= (uint)__view.TimelineCount) throw new global::System.ArgumentException($\"Playback slot {__s} of entity {__e} names no timeline in the loaded library.\");");
        W(writer, "var __tl = __view.Timelines + (__pb->Timeline - 1);");
        W(writer, "var __dur = __tl->Duration;");
        W(writer, "if (__dur != 0)");
        W(writer, "{");
        W(writer, "var __tick = __pb->Tick;");
        W(writer, "var __stage = global::Tl.LibraryViewReader.StageAt(__tl, __tick);");
        W(writer, "if (__stage != null)");
        W(writer, "{");
        W(writer, "var __steps = global::Tl.SystemDispatch.FilteredSteps(world, SystemKey, __tl->Id, (int)(__stage - __tl->Stages), PairKeys);");
        W(writer, "var __backward = forward ? (__pb->Flags & global::Tl.PlaybackFlags.Reverse) != 0 : (__pb->Flags & global::Tl.PlaybackFlags.Reverse) == 0;");
        W(writer, "var __base = __backward ? global::Tl.FrameFlags.Reverse : global::Tl.FrameFlags.None;");
        W(writer, "if ((__pb->Flags & global::Tl.PlaybackFlags.StartPending) != 0 && __tick > 0) __base |= global::Tl.FrameFlags.Synthetic;");
        W(writer, "if (__tick == 0) __base |= global::Tl.FrameFlags.TimelineStart;");
        W(writer, "if (__tick == (ushort)(__tl->Duration - 1)) __base |= global::Tl.FrameFlags.TimelineEnd;");
        EmitBind(writer, shape, "__e", "__s");
        EmitEntryLoop(writer, assignment, shape, "__steps", "__stage", "__tl", "__tick", "__base", "__backward", "__e", "__s", false);
        EmitMarkers(writer, assignment, shape, "__tl", "__tick", "__base", "__e", "__s");
        W(writer, "}");
        W(writer, "}");
        W(writer, "var __advance = global::Tl.PlaybackRules.Advance(ref *__pb, __view.Timelines, __view.TimelineCount, forward);");
        W(writer, "if (__advance == global::Tl.AdvanceResult.Removed)");
        W(writer, "{");
        W(writer, "__pb[0] = default;");
        W(writer, "var __hw = __pview.Counts[__e];");
        W(writer, "while (__hw > 0 && __pview.SlotOf(__e, __hw - 1)->Timeline == 0) __hw--;");
        W(writer, "__pview.Counts[__e] = __hw;");
        W(writer, "}");
        W(writer, "}");
        W(writer, "}");
        W(writer, "}");
        EmitBatchTails(writer, assignment, shape);
        W(writer, "global::Tl.ClosingList.Clear(players.Closing);");
        W(writer, "}");
    }

    static void EmitLocalDecls(StringBuilder writer, KernelShape shape)
    {
        for (var i = 0; i < shape.Requests.Count; i++)
            W(writer, "global::Tl.Requests __rq" + i + ";");
        for (var i = 0; i < shape.Events.Count; i++)
            W(writer, $"{shape.Events[i].TypeName} __eb{i};");
    }

    static void EmitBind(StringBuilder writer, KernelShape shape, string entity, string slot)
    {
        for (var i = 0; i < shape.Requests.Count; i++)
            W(writer, $"__rq{i} = __req{i}.For({entity}, {slot});");
        for (var i = 0; i < shape.Events.Count; i++)
            W(writer, $"__eb{i} = __ev{i}; __eb{i}.Bind({entity}, {slot});");
    }

    static void EmitCloseLoop(StringBuilder writer, SystemAssignment assignment, KernelShape shape)
    {
        W(writer, "var __closing = players.Closing;");
        W(writer, "for (var __ci = 0; __ci < __closing->Count; __ci++)");
        W(writer, "{");
        W(writer, "__closing->Get(__ci, out var __ce, out var __cs, out var __cpb);");
        W(writer, "var __ctl = global::Tl.LibraryViewReader.GetTimeline(in __view, new global::Tl.TimelineId(__cpb.Timeline));");
        W(writer, "if (__ctl is null || __ctl->Duration == 0) continue;");
        W(writer, "var __ctick = __cpb.Tick < __ctl->Duration ? __cpb.Tick : (ushort)(__ctl->Duration - 1);");
        W(writer, "var __cstage = global::Tl.LibraryViewReader.StageAt(__ctl, __ctick);");
        W(writer, "if (__cstage is null) continue;");
        W(writer, "var __csteps = global::Tl.SystemDispatch.FilteredSteps(world, SystemKey, __ctl->Id, (int)(__cstage - __ctl->Stages), PairKeys);");
        W(writer, "var __cbackward = forward ? (__cpb.Flags & global::Tl.PlaybackFlags.Reverse) != 0 : (__cpb.Flags & global::Tl.PlaybackFlags.Reverse) == 0;");
        W(writer, "var __cbase = (__cbackward ? global::Tl.FrameFlags.Reverse : global::Tl.FrameFlags.None) | global::Tl.FrameFlags.Interrupted;");
        W(writer, "if (__ctick == 0) __cbase |= global::Tl.FrameFlags.TimelineStart;");
        W(writer, "if (__ctick == (ushort)(__ctl->Duration - 1)) __cbase |= global::Tl.FrameFlags.TimelineEnd;");
        EmitBind(writer, shape, "__ce", "__cs");
        EmitEntryLoop(writer, assignment, shape, "__csteps", "__cstage", "__ctl", "__ctick", "__cbase", "__cbackward", "__ce", "__cs", true);
        W(writer, "}");
    }

    static void EmitEntryLoop(StringBuilder writer, SystemAssignment assignment, KernelShape shape, string steps, string stage, string tl, string tick, string flags, string backward, string entity, string slot, bool closing)
    {
        var consumers = assignment.Consumers;
        W(writer, $"for (var __i = 0; __i < {steps}.Length; __i++)");
        W(writer, "{");
        W(writer, $"var __entry = {steps}[__i];");
        W(writer, "switch (__entry.Consumer)");
        W(writer, "{");
        for (var c = 0; c < consumers.Count; c++)
        {
            var consumer = consumers[c];
            if (consumer.IsMarker || !IsLegacy(consumer)) continue;
            W(writer, $"case {c}:");
            W(writer, "{");
            W(writer, $"var __def = {stage}->Steps + __entry.Step;");
            W(writer, $"if ({tick} < __def->WindowStart || {tick} >= __def->WindowEnd) break;");
            if (closing)
                EmitCloseCase(writer, assignment, shape, consumer, c, flags, entity, tick, tl);
            else
                EmitStepCase(writer, assignment, shape, consumer, c, flags, backward, entity, slot, tl, tick);
            W(writer, "break;");
            W(writer, "}");
        }
        W(writer, "}");
        W(writer, "}");
    }

    static void EmitMaterialize(StringBuilder writer, SystemConsumer consumer, int index, string tl, string tick, string backward, string flags)
    {
        W(writer, $"byte* __row{index} = (byte*)__def->FrameRow;");
        W(writer, $"byte* __first{index} = __row{index} + sizeof({consumer.TrackTypeName});");
        W(writer, $"byte* __second{index} = __def->FactorSpan == 0 ? null : __first{index} + sizeof({consumer.ClipTypeName});");
        W(writer, $"float __blend{index} = __def->FactorSpan == 0 ? 0f : (__def->FactorSpan <= 1 ? 0.5f : ({tick} - __def->FactorStart) / (float)(__def->FactorSpan - 1));");
        W(writer, $"ushort __len{index} = (ushort)(__def->WindowEnd - __def->WindowStart);");
        W(writer, $"ushort __within{index} = (ushort)({tick} - __def->WindowStart);");
        W(writer, $"sbyte __dir{index} = {backward} ? (sbyte)-1 : (sbyte)1;");
        W(writer, $"Frame_{index}(__row{index}, __first{index}, __second{index}, __blend{index}, {tick}, __len{index}, __within{index}, (ushort)__def->TrackIndex, (ushort){tl}->Duration, __dir{index}, {flags}, out var __t{index}, out var __cc{index}, out var __f{index});");
    }

    static void EmitFeeds(StringBuilder writer, SystemConsumer consumer, int index)
    {
        var fold = FoldOf(consumer);
        if (fold is null || LaneBytes(consumer) == 0) return;
        W(writer, $"byte* __lane{index} = (byte*)__def->FoldLane + (((uint)__tick - __def->WindowStart) * 2u + (__backward ? 1u : 0u)) * (uint){LaneBytes(consumer)};");
        var offset = 0;
        for (var o = 0; o < fold.Params.Count; o++)
        {
            W(writer, $"{fold.Params[o].TypeName} __fd{index}_{o} = default;");
            offset += fold.FoldSizes[o];
        }
        W(writer, $"if (__def->FoldLane == null)");
        W(writer, "{");
        var foldArgs = new StringBuilder();
        foldArgs.Append($"in __f{index}");
        for (var o = 0; o < fold.Params.Count; o++)
            foldArgs.Append($", {fold.Params[o].Modifier}__fd{index}_{o}");
        W(writer, $"{consumer.ConsumerTypeName}.Fold({foldArgs});");
        W(writer, "}");
        W(writer, "else");
        W(writer, "{");
        offset = 0;
        for (var o = 0; o < fold.Params.Count; o++)
        {
            W(writer, $"__fd{index}_{o} = *({fold.Params[o].TypeName}*)(__lane{index} + {offset});");
            offset += fold.FoldSizes[o];
        }
        W(writer, "}");
    }

    static string CallArgs(KernelShape shape, ConsumerMethod method, int index, string frameVar, string rowVar, string feedPrefix)
    {
        var args = new List<string>();
        var start = 0;
        if (method.Params.Count > 0 && method.Params[0].Kind is ConsumerParamKind.Frame or ConsumerParamKind.MarkerFrame)
        {
            args.Add($"in {frameVar}");
            start = 1;
        }
        for (var p = start; p < method.Params.Count; p++)
        {
            var parameter = method.Params[p];
            switch (parameter.Kind)
            {
                case ConsumerParamKind.FoldFeed:
                    args.Add($"in {feedPrefix}{parameter.FoldIndex}");
                    break;
                case ConsumerParamKind.BatchItems:
                    args.Add($"__items{index}");
                    break;
                case ConsumerParamKind.Column:
                {
                    var at = ColumnOf(shape, parameter.TypeName, true);
                    if (at >= 0) args.Add($"ref __c{at}[{rowVar}]");
                    else args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
                }
                case ConsumerParamKind.ColumnReadOnly:
                {
                    var at = ColumnOf(shape, parameter.TypeName, false);
                    if (at >= 0) args.Add($"in __c{at}[{rowVar}]");
                    else args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
                }
                case ConsumerParamKind.Context:
                    args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
                case ConsumerParamKind.Requests:
                    args.Add($"ref __rq{RequestOf(shape)}");
                    break;
                case ConsumerParamKind.Events:
                    args.Add($"ref __eb{EventOf(shape, EventElement(parameter.TypeName))}");
                    break;
            }
        }
        return string.Join(", ", args);
    }

    static void EmitCloseCase(StringBuilder writer, SystemAssignment assignment, KernelShape shape, SystemConsumer consumer, int index, string flags, string entity, string tick, string tl)
    {
        var end = null as ConsumerMethod;
        foreach (var method in consumer.Methods)
            if (method.Kind == ConsumerMethodKind.OnClipEnd) end = method;
        if (end is null) return;
        EmitMaterialize(writer, consumer, index, tl, tick, "__cbackward", flags);
        W(writer, $"{consumer.ConsumerTypeName}.OnClipEnd({CallArgs(shape, end, index, $"__f{index}", entity, $"__fd{index}_")});");
    }

    static void EmitStepCase(StringBuilder writer, SystemAssignment assignment, KernelShape shape, SystemConsumer consumer, int index, string flags, string backward, string entity, string slot, string tl, string tick)
    {
        ConsumerMethod? active = null, batch = null, start = null, end = null;
        foreach (var method in consumer.Methods)
        {
            if (method.Kind == ConsumerMethodKind.ExecuteActive) active = method;
            if (method.Kind == ConsumerMethodKind.ExecuteBatch) batch = method;
            if (method.Kind == ConsumerMethodKind.OnClipStart) start = method;
            if (method.Kind == ConsumerMethodKind.OnClipEnd) end = method;
        }
        var direct = active is not null && batch is null && start is null && active.Direct.Eligible;
        if (!direct)
        {
            EmitMaterialize(writer, consumer, index, tl, tick, backward, flags);
            if (FoldOf(consumer) is not null) EmitFeeds(writer, consumer, index);
        }
        if (batch is not null)
        {
            var element = batch.Params[1].BatchElement;
            var elementOffset = FoldOutOffset(consumer, element);
            W(writer, $"if (__def->FoldLane == null) throw new global::System.InvalidOperationException(\"{consumer.ConsumerTypeName}: fold lane is not loaded.\");");
            W(writer, $"int __syn{index} = ((__pb->Flags & global::Tl.PlaybackFlags.StartPending) != 0 && {tick} > 0) ? 1 : 0;");
            W(writer, $"if (__bn{index} >= 128 || __bstage{index} != __stage || __bstep{index} != __entry.Step || __btick{index} != {tick} || __bdir{index} != (__backward ? 1 : 0) || __bsyn{index} != __syn{index}) {{ Flush_{index}(__bb{index}, __bsl{index}, __bn{index}, __bstage{index}, __bstep{index}, __btick{index}, __bdir{index}, __bsyn{index}, __bdur{index}, {FlushCallArgs(shape)}); __bn{index} = 0; __bstep{index} = -1; }}");
            W(writer, $"__bstage{index} = __stage; __bstep{index} = __entry.Step; __btick{index} = {tick}; __bdir{index} = __backward ? 1 : 0; __bsyn{index} = __syn{index}; __bdur{index} = (ushort)__tl->Duration;");
            W(writer, $"__bb{index}[__bn{index}] = new global::Tl.BatchItem<{element}>({entity}, {tick}, *({element}*)((byte*)__def->FoldLane + (((uint){tick} - __def->WindowStart) * 2u + (__backward ? 1u : 0u)) * (uint){LaneBytes(consumer)} + {elementOffset}));");
            W(writer, $"__bsl{index}[__bn{index}] = {slot};");
            W(writer, $"__bn{index}++;");
        }
        else if (active is not null)
        {
            if (direct)
            {
                W(writer, $"if (__def->FoldLane == null)");
                W(writer, "{");
                EmitMaterialize(writer, consumer, index, tl, tick, backward, flags);
                if (FoldOf(consumer) is not null) EmitFeeds(writer, consumer, index);
                W(writer, $"{consumer.ConsumerTypeName}.ExecuteActive({CallArgs(shape, active, index, $"__f{index}", entity, $"__fd{index}_")});");
                W(writer, "}");
                W(writer, "else");
                W(writer, "{");
                EmitDirectStep(writer, shape, consumer, active, index, entity, tick, backward);
                W(writer, "}");
            }
            else W(writer, $"{consumer.ConsumerTypeName}.ExecuteActive({CallArgs(shape, active, index, $"__f{index}", entity, $"__fd{index}_")});");
        }
        if (start is not null)
            W(writer, $"if ({tick} == __def->WindowStart) {consumer.ConsumerTypeName}.OnClipStart({CallArgs(shape, start, index, $"__f{index}", entity, $"__fd{index}_")});");
        if (end is not null && batch is null && !direct)
            W(writer, $"if ({tick} == __def->WindowEnd - 1) {consumer.ConsumerTypeName}.OnClipEnd({CallArgs(shape, end, index, $"__f{index}", entity, $"__fd{index}_")});");
    }

    // Direct-lane step: no Frame construction, no switch dispatch beyond the
    // entry table, no consumer call. Loads the precomputed lane value(s) and
    // adds them straight into the written column (times read columns).
    static void EmitDirectStep(StringBuilder writer, KernelShape shape, SystemConsumer consumer, ConsumerMethod active, int index, string entity, string tick, string backward)
    {
        var direct = active.Direct;
        var fold = FoldOf(consumer);
        var stride = fold is null ? 4 : LaneBytes(consumer);
        var written = ColumnOf(shape, direct.WrittenType, true);
        var writtenRef = direct.WrittenMember.Length == 0 ? $"__c{written}[{entity}]" : $"__c{written}[{entity}].{direct.WrittenMember}";
        if (direct.FoldOffsets.Count > 0)
        {
            W(writer, $"byte* __lane{index} = (byte*)__def->FoldLane + (((uint){tick} - __def->WindowStart) * 2u + ({backward} ? 1u : 0u)) * (uint){stride};");
        }
        var parts = new List<string>();
        for (var k = 0; k < direct.FoldOffsets.Count; k++)
        {
            W(writer, $"float __fd{index}_{k} = *(float*)((byte*)__lane{index} + {direct.FoldOffsets[k]});");
            parts.Add($"__fd{index}_{k}");
        }
        foreach (var read in direct.ReadTypes)
            parts.Add($"__c{ColumnOf(shape, read, false)}[{entity}]");
        W(writer, $"{writtenRef} {direct.Op} {string.Join(" * ", parts)};");
    }

    static void EmitBatchDecls(StringBuilder writer, SystemAssignment assignment)
    {
        foreach (var batch in BatchConsumers(assignment.Consumers))
        {
            var element = "";
            foreach (var method in batch.consumer.Methods)
                if (method.Kind == ConsumerMethodKind.ExecuteBatch) element = method.Params[1].BatchElement;
            W(writer, $"global::Tl.BatchItem<{element}>* __bb{batch.index} = stackalloc global::Tl.BatchItem<{element}>[128];");
            W(writer, $"int* __bsl{batch.index} = stackalloc int[128];");
            W(writer, $"int __bn{batch.index} = 0;");
            W(writer, $"global::Tl.LibraryStage* __bstage{batch.index} = null;");
            W(writer, $"int __bstep{batch.index} = -1; ushort __btick{batch.index} = 0; int __bdir{batch.index} = 0; int __bsyn{batch.index} = 0; ushort __bdur{batch.index} = 0;");
        }
    }

    static string FlushCallArgs(KernelShape shape)
    {
        var sb = new StringBuilder();
        var first = true;
        for (var i = 0; i < shape.Columns.Count; i++)
            if (shape.UsedColumns[i]) { if (!first) sb.Append(", "); sb.Append($"__c{i}"); first = false; }
        sb.Append(", __n");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) sb.Append($", ref __ctx{i}");
        for (var i = 0; i < shape.Requests.Count; i++) sb.Append($", __req{i}");
        for (var i = 0; i < shape.Events.Count; i++) sb.Append($", __ev{i}");
        return sb.ToString();
    }
    static string EventElement(string typeName)
    {
        var start = typeName.IndexOf('<');
        var end = typeName.LastIndexOf('>');
        return start >= 0 && end > start ? typeName.Substring(start + 1, end - start - 1) : typeName;
    }

    static void EmitBatchTails(StringBuilder writer, SystemAssignment assignment, KernelShape shape)
    {
        foreach (var batch in BatchConsumers(assignment.Consumers))
            W(writer, $"if (__bn{batch.index} > 0 && __bstage{batch.index} != null) {{ Flush_{batch.index}(__bb{batch.index}, __bsl{batch.index}, __bn{batch.index}, __bstage{batch.index}, __bstep{batch.index}, __btick{batch.index}, __bdir{batch.index}, __bsyn{batch.index}, __bdur{batch.index}, {FlushCallArgs(shape)}); __bn{batch.index} = 0; }}");
    }

    static void EmitFlush(StringBuilder writer, SystemAssignment assignment, KernelShape shape, SystemConsumer consumer, int index)
    {
        var batch = null as ConsumerMethod;
        foreach (var method in consumer.Methods)
            if (method.Kind == ConsumerMethodKind.ExecuteBatch) batch = method;
        if (batch is null) return;
        var element = batch.Params[1].BatchElement;
        ConsumerMethod? end = null;
        foreach (var method in consumer.Methods)
            if (method.Kind == ConsumerMethodKind.OnClipEnd) end = method;
        var signature = new StringBuilder();
        signature.Append($"internal static void Flush_{index}(global::Tl.BatchItem<{element}>* items, int* slots, int count, global::Tl.LibraryStage* stageBase, int stepIndex, ushort tick, int dir, int syn, ushort duration");
        var colIds = new List<int>();
        for (var i = 0; i < shape.Columns.Count; i++)
            if (shape.UsedColumns[i]) colIds.Add(i);
        foreach (var id in colIds) signature.Append($", {shape.Columns[id].ElementTypeName}* __fc{id}");
        signature.Append(", int __fn");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) signature.Append($", ref {shape.Contexts[i].ElementTypeName} __fx{i}");
        for (var i = 0; i < shape.Requests.Count; i++) signature.Append(", global::Tl.Requests __rx" + i);
        for (var i = 0; i < shape.Events.Count; i++) signature.Append($", {shape.Events[i].TypeName} __ex{i}");
        signature.Append(')');
        W(writer, signature.ToString());
        W(writer, "{");
        W(writer, "if (count == 0 || stepIndex < 0 || stageBase == null) return;");
        W(writer, "var __def = stageBase->Steps + stepIndex;");
        W(writer, "if (tick < __def->WindowStart || tick >= __def->WindowEnd) return;");
        W(writer, $"byte* __row = (byte*)__def->FrameRow;");
        W(writer, $"byte* __first = __row + sizeof({consumer.TrackTypeName});");
        W(writer, $"byte* __second = __def->FactorSpan == 0 ? null : __first + sizeof({consumer.ClipTypeName});");
        W(writer, $"float __blend = __def->FactorSpan == 0 ? 0f : (__def->FactorSpan <= 1 ? 0.5f : (tick - __def->FactorStart) / (float)(__def->FactorSpan - 1));");
        W(writer, $"ushort __len = (ushort)(__def->WindowEnd - __def->WindowStart);");
        W(writer, $"ushort __within = (ushort)(tick - __def->WindowStart);");
        W(writer, "sbyte __dir = dir != 0 ? (sbyte)-1 : (sbyte)1;");
        W(writer, "var __fbase = (__dir != 0 ? global::Tl.FrameFlags.Reverse : global::Tl.FrameFlags.None) | (syn != 0 ? global::Tl.FrameFlags.Synthetic : global::Tl.FrameFlags.None);");
        W(writer, "if (tick == 0) __fbase |= global::Tl.FrameFlags.TimelineStart;");
        W(writer, "if (tick == (ushort)(duration - 1)) __fbase |= global::Tl.FrameFlags.TimelineEnd;");
        W(writer, $"Frame_{index}(__row, __first, __second, __blend, tick, __len, __within, (ushort)__def->TrackIndex, duration, __dir, __fbase, out var __t, out var __c, out var __frame);");
        W(writer, $"var __items = new global::System.ReadOnlySpan<global::Tl.BatchItem<{element}>>(items, count);");
        var call = new StringBuilder();
        call.Append($"{consumer.ConsumerTypeName}.ExecuteBatch(in __frame, __items");
        foreach (var parameter in batch.Params)
        {
            if (parameter.Kind == ConsumerParamKind.Frame || parameter.Kind == ConsumerParamKind.BatchItems) continue;
            call.Append(", " + FlushArg(shape, parameter));
        }
        call.Append(");");
        W(writer, call.ToString());
        if (end is not null)
        {
            W(writer, "if (tick == __def->WindowEnd - 1)");
            W(writer, "{");
            W(writer, "for (var __k = 0; __k < count; __k++)");
            W(writer, "{");
            var ordinal = 0;
            foreach (var parameter in end.Params)
            {
                if (parameter.Kind == ConsumerParamKind.Frame) continue;
                var bind = EndBind(shape, parameter, ordinal);
                if (bind.Length > 0) W(writer, bind);
                ordinal++;
            }
            W(writer, $"{consumer.ConsumerTypeName}.OnClipEnd({EndArgs(shape, end)});");
            W(writer, "}");
            W(writer, "}");
        }
        W(writer, "}");
    }

    static string FlushArg(KernelShape shape, ConsumerParam parameter)
    {
        switch (parameter.Kind)
        {
            case ConsumerParamKind.Column:
            {
                var at = ColumnOf(shape, parameter.TypeName, true);
                return at >= 0 ? $"new global::System.Span<{parameter.TypeName}>(__fc{at}, __fn)" : "default";
            }
            case ConsumerParamKind.ColumnReadOnly:
            {
                var at = ColumnOf(shape, parameter.TypeName, false);
                return at >= 0 ? $"new global::System.ReadOnlySpan<{parameter.TypeName}>(__fc{at}, __fn)" : "default";
            }
            case ConsumerParamKind.Context:
            {
                var at = ContextOf(shape, parameter.TypeName);
                return at >= 0 ? $"{parameter.Modifier}__fx{at}" : "default";
            }
            case ConsumerParamKind.Requests:
                return "ref __rr";
            case ConsumerParamKind.Events:
                return "ref __er";
            default:
                return "default";
        }
    }

    static string EndBind(KernelShape shape, ConsumerParam parameter, int ordinal)
    {
        switch (parameter.Kind)
        {
            case ConsumerParamKind.Column:
            {
                var at = ColumnOf(shape, parameter.TypeName, true);
                return at >= 0 ? $"ref var __erow{ordinal} = ref __fc{at}[items[__k].Row];" : "";
            }
            case ConsumerParamKind.ColumnReadOnly:
                return "";
            case ConsumerParamKind.Requests:
                return $"var __rr{ordinal} = __rx0.For(items[__k].Row, slots[__k]);";
            case ConsumerParamKind.Events:
                return $"var __er{ordinal} = __ex{EventOf(shape, EventElement(parameter.TypeName))}; __er{ordinal}.Bind(items[__k].Row, slots[__k]);";
            default:
                return "";
        }
    }

    static string EndArgs(KernelShape shape, ConsumerMethod end)
    {
        var args = new List<string> { "in __frame" };
        var ordinal = 0;
        foreach (var parameter in end.Params)
        {
            if (parameter.Kind == ConsumerParamKind.Frame) continue;
            switch (parameter.Kind)
            {
                case ConsumerParamKind.Column:
                    args.Add($"ref __erow{ordinal}");
                    break;
                case ConsumerParamKind.ColumnReadOnly:
                {
                    var at = ColumnOf(shape, parameter.TypeName, false);
                    args.Add(at >= 0 ? $"in __fc{at}[items[__k].Row]" : "in __unused");
                    break;
                }
                case ConsumerParamKind.Context:
                {
                    var at = ContextOf(shape, parameter.TypeName);
                    args.Add(at >= 0 ? $"{parameter.Modifier}__fx{at}" : $"{parameter.Modifier}__unused");
                    break;
                }
                case ConsumerParamKind.Requests:
                    args.Add($"ref __rr{ordinal}");
                    break;
                case ConsumerParamKind.Events:
                    args.Add($"ref __er{ordinal}");
                    break;
            }
            ordinal++;
        }
        return string.Join(", ", args);
    }

    static List<(SystemConsumer consumer, int index)> BatchConsumers(IReadOnlyList<SystemConsumer> consumers)
    {
        var list = new List<(SystemConsumer consumer, int index)>();
        for (var i = 0; i < consumers.Count; i++)
            foreach (var method in consumers[i].Methods)
                if (method.Kind == ConsumerMethodKind.ExecuteBatch) { list.Add((consumers[i], i)); break; }
        return list;
    }

    static void EmitMarkers(StringBuilder writer, SystemAssignment assignment, KernelShape shape, string tl, string tick, string flags, string entity, string slot)
    {
        var markers = new List<(SystemConsumer consumer, int index, ConsumerMethod? method)>();
        for (var i = 0; i < assignment.Consumers.Count; i++)
        {
            if (!assignment.Consumers[i].IsMarker) continue;
            ConsumerMethod? method = null;
            foreach (var candidate in assignment.Consumers[i].Methods)
                if (candidate.Kind == ConsumerMethodKind.OnMarker) method = candidate;
            if (method is not null) markers.Add((assignment.Consumers[i], i, method));
        }
        if (markers.Count == 0) return;
        W(writer, $"if (global::Tl.LibraryViewReader.HasEvent({tl}, {tick}))");
        W(writer, "{");
        W(writer, $"var __mev = global::Tl.LibraryViewReader.Events({tl});");
        W(writer, "for (var __mk = 0; __mk < __mev.Length; __mk++)");
        W(writer, "{");
        W(writer, $"if (__mev[__mk].Tick != {tick} || __mev[__mk].Kind != 2) continue;");
        foreach (var marker in markers)
        {
            var consumer = marker.consumer;
            W(writer, $"byte* __mptr{marker.index};");
            W(writer, $"if (!global::Tl.MarkerTableRegistry.TryResolve(world, {tl}->Id, __mev[__mk].Marker, sizeof({consumer.MarkerTypeName}), out __mptr{marker.index})) throw new global::System.InvalidOperationException(\"Tl: marker values are not published for this library.\");");
            W(writer, $"{consumer.MarkerTypeName} __m{marker.index} = *({consumer.MarkerTypeName}*)__mptr{marker.index};");
            W(writer, $"var __mf{marker.index} = new global::Tl.MarkerFrame<{consumer.MarkerTypeName}>(in __m{marker.index}, {tick}, 0, {flags});");
            W(writer, $"{consumer.ConsumerTypeName}.OnMarker({CallArgs(shape, marker.method!, marker.index, $"__mf{marker.index}", entity, "")});");
        }
        W(writer, "}");
        W(writer, "}");
    }

    static void EmitRun(StringBuilder writer, SystemAssignment assignment, string id)
    {
        var system = assignment.System;
        var shape = ShapeOf(assignment, id);
        var ns = NamespaceOf(system.TypeName);
        var shortName = ShortNameOf(system.TypeName);
        var safe = $"{id}_{Sanitize(system.TypeName)}";
        if (ns.Length > 0)
        {
            W(writer, $"namespace {ns}");
            W(writer, "{");
        }
        W(writer, $"partial struct {shortName}");
        W(writer, "{");
        W(writer, "public unsafe void Run(global::Tl.TimelineWorld world, global::Tl.PlaybackTable players, bool forward = true)");
        W(writer, "{");
        W(writer, "if (world is null) throw new global::System.ArgumentNullException(nameof(world));");
        W(writer, "if (players is null) throw new global::System.ArgumentNullException(nameof(players));");
        W(writer, "int __len = players.EntityCapacity;");
        var first = true;
        foreach (var field in system.Fields)
        {
            if (field.Kind is not (SystemFieldKind.Column or SystemFieldKind.ColumnReadOnly)) continue;
            if (first) { W(writer, $"__len = this.{field.Name}.Length;"); first = false; }
            else W(writer, $"if (this.{field.Name}.Length != __len) throw new global::System.ArgumentException(\"{system.TypeName}: column {field.Name} lengths differ.\");");
        }
        W(writer, $"if (__len > players.EntityCapacity) throw new global::System.ArgumentException(\"{system.TypeName}: column length exceeds table capacity.\");");
        var pins = new List<string>();
        var ptrs = new List<string>();
        for (var i = 0; i < shape.Columns.Count; i++)
        {
            if (!shape.UsedColumns[i]) continue;
            pins.Add($"fixed ({shape.Columns[i].ElementTypeName}* __p{i} = this.{shape.Columns[i].Name})");
            ptrs.Add($"__p{i}");
        }
        var call = new StringBuilder();
        call.Append($"global::TlSystems.TlSystem_{safe}.Run(world, players, forward");
        foreach (var ptr in ptrs) call.Append($", {ptr}");
        call.Append(", __len");
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i]) call.Append($", ref this.{shape.Contexts[i].Name}");
        foreach (var field in system.Fields)
        {
            if (field.Kind == SystemFieldKind.Requests) call.Append($", this.{field.Name}");
            if (field.Kind == SystemFieldKind.Events) call.Append($", this.{field.Name}");
        }
        call.Append(");");
        if (pins.Count == 0)
        {
            W(writer, call.ToString());
        }
        else
        {
            foreach (var pin in pins)
            {
                W(writer, pin);
                W(writer, "{");
            }
            W(writer, call.ToString());
            foreach (var pin in pins) W(writer, "}");
        }
        W(writer, "}");
        W(writer, "}");
        if (ns.Length > 0) W(writer, "}");
    }

