            if (k.Group.Length > 0) W(w, "*(ushort*)((byte*)__add + 8) = (ushort)__kid;");
            W(w, $"System.Runtime.CompilerServices.Unsafe.WriteUnaligned((byte*)__add + {valueAt}, __v);");
        }
        else if (k.Each) W(w, $"{k.TypeName}.Apply(in __v{tail});");
        else W(w, Acc(k, "__v"));
        W(w, "}\n}");
    }

