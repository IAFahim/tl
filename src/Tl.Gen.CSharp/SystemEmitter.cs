internal static class SystemEmitter
{
    internal static string Emit(IReadOnlyList<SystemAssignment> assignments, string id, int feedKey = 0)
    {
        var writer = new StringBuilder();
        writer.Append("// <auto-generated/>\nusing __PF = Tl.PlaybackFlags;\nusing __FF = Tl.FrameFlags;\n");
        writer.Append("namespace TlSystems\n");
        writer.Append("{\n");
        W(writer, $"internal sealed class TlCompiled_{id} {{ }}");
        foreach (var assignment in assignments)
            EmitSystem(writer, assignment, id, feedKey);
        writer.Append("}\n");
        foreach (var assignment in assignments)
            EmitRun(writer, assignment, id);
        return writer.ToString().Replace("\r\n", "\n");
    }

    static void W(StringBuilder writer, string text)
    {
        writer.Append(text.Replace("global::Tl.", "Tl.").Replace("global::System.", "System.").Replace("global::TlSystems.", "TlSystems.").Replace("Tl.PlaybackFlags.", "__PF.").Replace("Tl.FrameFlags.", "__FF.")).Append('\n');
    }

    static ConsumerMethod? FoldOf(SystemConsumer consumer)
    {
        foreach (var method in consumer.Methods)
            if (method.Kind == ConsumerMethodKind.Fold) return method;
        return null;
    }

    static void EmitFrameHelper(StringBuilder writer, SystemConsumer consumer, int index)
    {
        W(writer, $"internal static void Frame_{index}(byte* trackPtr, byte* firstPtr, byte* secondPtr, float blend, ushort tick, ushort windowLength, ushort withinClip, ushort trackIndex, ushort duration, sbyte direction, Tl.FrameFlags extra, out {consumer.TrackTypeName} track, out {consumer.ClipTypeName} clip, out Tl.Frame<{consumer.TrackTypeName}, {consumer.ClipTypeName}> frame)");
        W(writer, "{");
        W(writer, $"track = *({consumer.TrackTypeName}*)trackPtr;");
        W(writer, $"clip = *({consumer.ClipTypeName}*)firstPtr;");
        W(writer, "if (secondPtr != null)");
        W(writer, "{");
        W(writer, $"{consumer.ClipTypeName} __second = *({consumer.ClipTypeName}*)secondPtr;");
        if (consumer.ClipBlendable)
        {
            W(writer, "static T __Blend<T>(T first, in T second, float factor) where T : unmanaged, Tl.IBlend<T> { first.Blend(in first, in second, factor, out var result); return result; }");
            W(writer, "clip = __Blend(clip, in __second, blend);");
        }
        else if (consumer.TrackBlendable)
            W(writer, "track.Blend(in clip, in __second, blend, out clip);");
        else
            W(writer, $"throw new System.InvalidOperationException(\"{consumer.ConsumerTypeName}: blended window without IBlend.\");");
        W(writer, "}");
        W(writer, "var __flags = (direction < 0 ? Tl.FrameFlags.Reverse : Tl.FrameFlags.None) | extra;");
        W(writer, "if (withinClip == 0) __flags |= Tl.FrameFlags.ClipStart;");
        W(writer, "if (withinClip == (ushort)(windowLength - 1)) __flags |= Tl.FrameFlags.ClipEnd;");
        W(writer, "if (tick == 0) __flags |= Tl.FrameFlags.TimelineStart;");
        W(writer, "if (tick == (ushort)(duration - 1)) __flags |= Tl.FrameFlags.TimelineEnd;");
        W(writer, $"frame = new Tl.Frame<{consumer.TrackTypeName}, {consumer.ClipTypeName}>(in track, in clip, tick, windowLength, withinClip, trackIndex, __flags);");
        W(writer, "}");
    }

    static string Sanitize(string typeName)
    {
        var builder = new StringBuilder();
        foreach (var c in typeName) builder.Append(char.IsLetterOrDigit(c) ? c : '_');
        return builder.ToString();
    }

    static string Bare(string typeName) => typeName.StartsWith("global::", StringComparison.Ordinal) ? typeName.Substring(8) : typeName;

    static string NamespaceOf(string typeName)
    {
        var bare = Bare(typeName);
        var dot = bare.LastIndexOf('.');
        return dot < 0 ? "" : bare.Substring(0, dot);
    }

    static string ShortNameOf(string typeName)
    {
        var bare = Bare(typeName);
        var dot = bare.LastIndexOf('.');
        var plus = bare.LastIndexOf('+');
        var cut = dot > plus ? dot : plus;
        return cut < 0 ? bare : bare.Substring(cut + 1);
    }

    sealed class KernelShape
    {
        public List<SystemField> Columns = new();
        public List<SystemField> Contexts = new();
        public List<SystemField> Events = new();
        public bool[] UsedColumns = Array.Empty<bool>();
        public bool[] UsedContexts = Array.Empty<bool>();
        public string Safe = "";
    }

    static KernelShape ShapeOf(SystemAssignment assignment, string id)
    {
        var shape = new KernelShape { Safe = $"{id}_{Sanitize(assignment.System.TypeName)}" };
        foreach (var field in assignment.System.Fields)
        {
            switch (field.Kind)
            {
                case SystemFieldKind.Column:
                case SystemFieldKind.ColumnReadOnly: shape.Columns.Add(field); break;
                case SystemFieldKind.Context: shape.Contexts.Add(field); break;
                case SystemFieldKind.Events: shape.Events.Add(field); break;
            }
        }
        shape.UsedColumns = new bool[shape.Columns.Count];
        shape.UsedContexts = new bool[shape.Contexts.Count];
        var parameters = new List<ConsumerParam>();
        foreach (var consumer in assignment.Consumers)
            foreach (var method in consumer.Methods)
                parameters.AddRange(method.Params);
        foreach (var kind in assignment.Kinds)
        {
            parameters.AddRange(kind.ApplyParams);
            if (kind.IdleParams is not null) parameters.AddRange(kind.IdleParams);
        }
        foreach (var parameter in parameters)
        {
            if (parameter.Kind is ConsumerParamKind.Column or ConsumerParamKind.ColumnReadOnly)
            {
                var at = shape.Columns.FindIndex(field => field.ElementTypeName == parameter.TypeName);
                if (at >= 0 && (parameter.Kind == ConsumerParamKind.ColumnReadOnly || shape.Columns[at].Kind == SystemFieldKind.Column)) shape.UsedColumns[at] = true;
                else
                {
                    var ctx = shape.Contexts.FindIndex(field => field.ElementTypeName == parameter.TypeName);
                    if (ctx >= 0) shape.UsedContexts[ctx] = true;
                }
            }
        }
        return shape;
    }

    static int ColumnOf(KernelShape shape, string element, bool writable)
    {
        for (var i = 0; i < shape.Columns.Count; i++)
        {
            if (!shape.UsedColumns[i] || shape.Columns[i].ElementTypeName != element) continue;
            if (!writable || shape.Columns[i].Kind == SystemFieldKind.Column) return i;
        }
        return -1;
    }

    static int ContextOf(KernelShape shape, string element)
    {
        for (var i = 0; i < shape.Contexts.Count; i++)
            if (shape.UsedContexts[i] && shape.Contexts[i].ElementTypeName == element) return i;
        return -1;
    }

    static int EventOf(KernelShape shape, string element)
    {
        for (var i = 0; i < shape.Events.Count; i++)
            if (shape.Events[i].ElementTypeName == element) return i;
        return -1;
    }

    static bool IsTlFrame(ConsumerMethod method)
        => method.Params.Count > 0
            && method.Params[0].Kind == ConsumerParamKind.Frame
            && method.Params[0].TypeName.StartsWith("global::Tl.TlFrame<", StringComparison.Ordinal);

    static bool HasEvents(SystemAssignment assignment)
        => assignment.Consumers.Any(static consumer => consumer.Methods.Any(IsEvent));

    static bool IsEvent(ConsumerMethod method) => method.Kind is ConsumerMethodKind.ExecuteActive or ConsumerMethodKind.OnClipStart or ConsumerMethodKind.OnClipEnd;

    static void EmitSystem(StringBuilder writer, SystemAssignment assignment, string id, int feedKey)
    {
        var shape = ShapeOf(assignment, id);
        var consumers = assignment.Consumers;
        W(writer, $"internal static unsafe class TlSystem_{shape.Safe}");
        W(writer, "{");
        for (var c = 0; c < consumers.Count; c++)
            if (!consumers[c].IsMarker) EmitFrameHelper(writer, consumers[c], c);
        W(writer, BaseSig(shape, "Run", false));
        W(writer, "{");
        if (HasEvents(assignment)) { W(writer, $"RunClose(world, players, forward{FullArgs(shape, false)}); RunEventRange(world, players, forward{FullArgs(shape, true)});"); }
        EmitKindLoops(writer, assignment, shape);
        W(writer, "}");
        EmitKindMethods(writer, assignment, shape, feedKey);
        if (HasEvents(assignment)) { EmitCloseMethod(writer, assignment, shape); EmitEventRangeMethod(writer, assignment, shape); }
        W(writer, "}");
    }

    static void EmitEntityScanOpen(StringBuilder writer)
    {
        W(writer, "var __pl = players.Playing; var __w1 = __endWord < players.PlayingWords ? __endWord : players.PlayingWords;");
        W(writer, "for (var __w = __firstWord; __w < __w1; __w++)");
        W(writer, "{");
        W(writer, "for (var __b = __pl[__w]; __b != 0; __b &= __b - 1)");
        W(writer, "{");
        W(writer, "var __e = (__w << 6) + Tl.KindStore.TrailingZeros(__b);");
        W(writer, "if (__e >= __n) continue;");
        W(writer, "#if TL_CHECKED");
        W(writer, "Tl.Checked.Visited();");
        W(writer, "#endif");
    }

    static void EmitEventLoop(StringBuilder writer, SystemAssignment assignment, KernelShape shape)
    {
        EmitLocalDecls(writer, shape);
        EmitEntityScanOpen(writer);
        W(writer, "var __count = __e < __pview.EntityCount ? __pview.Counts[__e] : 0;");
        W(writer, "for (var __s = 0; __s < __count; __s++)");
        W(writer, "{");
        W(writer, "var __ps = __pview.SlotOf(__e, __s);");
        W(writer, "if (__ps->Timeline == 0 || ((__ps->Flags & (Tl.PlaybackFlags.Ended | Tl.PlaybackFlags.Paused | Tl.PlaybackFlags.Stopping)) != 0 && !Tl.PlaybackRules.Resumes(__ps->Flags, forward))) continue;");
        W(writer, "var __pcopy = *__ps;");
        W(writer, "var __pb = __ps->Rate == 0 ? __ps : &__pcopy;");
        W(writer, "var __pk = Tl.PlaybackRules.Crossings(in *__ps);");
        W(writer, "for (var __j = 0; __j < __pk; __j++)");
        W(writer, "{");
        W(writer, "if (__j > 0 && (Tl.PlaybackRules.Advance(ref __pcopy, __view.Timelines, __view.TimelineCount, forward) != Tl.AdvanceResult.Kept || (__pcopy.Flags & (Tl.PlaybackFlags.Ended | Tl.PlaybackFlags.Paused)) != 0)) break;");
        W(writer, "var __tl = Tl.LibraryViewReader.GetTimeline(in __view, new Tl.TimelineId(__pb->Timeline));");
        W(writer, "if (__tl is null || __tl->Duration == 0) continue;");
        W(writer, "var __tick = __pb->Tick; var __stage = Tl.LibraryViewReader.StageAt(__tl, __tick); if (__stage == null) continue;");
        W(writer, "var __backward = forward ? (__pb->Flags & Tl.PlaybackFlags.Reverse) != 0 : (__pb->Flags & Tl.PlaybackFlags.Reverse) == 0;");
        W(writer, "var __base = ((__pb->Flags & Tl.PlaybackFlags.StartPending) != 0 && __tick > 0) || (__pb->Flags & Tl.PlaybackFlags.ReenterPending) != 0 ? Tl.FrameFlags.Synthetic : Tl.FrameFlags.None;");
        EmitBind(writer, shape, "__e", "__s");
        EmitEventSteps(writer, assignment, shape, "__stage", "__tl", "__tick", "__base", "__backward", "__e", closing: false);
        W(writer, "}");
        W(writer, "}");
        W(writer, "}");
        W(writer, "}");
    }

    static void EmitClearPulses(StringBuilder w, SystemAssignment a, string ks, string limit)
    {
        foreach (var pk in a.Kinds) if (pk.PrecombinedPulses) W(w, $"{ks}.ClearPulseHits({ks}.IndexOf(\"{pk.Id}\"), {limit});");
    }

    static void EmitKindLoops(StringBuilder writer, SystemAssignment assignment, KernelShape shape)
    {
        if (assignment.Kinds.Count == 0) return;
        W(writer, "var __ks = players.Kinds;");
        W(writer, "if (__ks != null)");
        W(writer, "{");
        W(writer, $"Kinds(world, players, __ks, forward{KindArgs(shape, false)});");
        EmitClearPulses(writer, assignment, "__ks", "__n");
        W(writer, "}");
    }

    static string ListArgs(KernelShape s, Func<int, string> col, string mid, Func<int, string> ctx, Func<int, string>? ev = null)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < s.Columns.Count; i++) if (s.UsedColumns[i]) sb.Append(", ").Append(col(i));
        sb.Append(", ").Append(mid);
        for (var i = 0; i < s.Contexts.Count; i++) if (s.UsedContexts[i]) sb.Append(", ").Append(ctx(i));
        if (ev != null) for (var i = 0; i < s.Events.Count; i++) sb.Append(", ").Append(ev(i));
        return sb.ToString();
    }

    static string KindArgs(KernelShape shape, bool typed, string words = "0, 2147483647")
        => ListArgs(shape, i => typed ? $"{shape.Columns[i].ElementTypeName}* __c{i}" : $"__c{i}", typed ? "int __n, int __firstWord, int __endWord" : $"__n, {words}", i => $"ref {(typed ? shape.Contexts[i].ElementTypeName + " " : "")}__ctx{i}");

    static void EmitCloseMethod(StringBuilder w, SystemAssignment a, KernelShape s) { W(w, BaseSig(s, "RunClose", false)); W(w, "{"); W(w, "var __view = world.View; _ = players.View;"); EmitLocalDecls(w, s); EmitCloseLoop(w, a, s); W(w, "}"); }
    static void EmitEventRangeMethod(StringBuilder w, SystemAssignment a, KernelShape s) { W(w, BaseSig(s, "RunEventRange", true)); W(w, "{"); W(w, "var __view = world.View; var __pview = players.SystemView;"); EmitEventLoop(w, a, s); W(w, "}"); }
    static string PArgs(KernelShape s, bool tail = true)
        => ListArgs(s, i => $"__s->__c{i}", "__s->__n, __fw, __ew", i => $"ref *({s.Contexts[i].ElementTypeName}*)__s->__x{i}", tail ? i => $"__se{i}" : null);
    static void EmitKindMethods(StringBuilder writer, SystemAssignment assignment, KernelShape shape, int feedKey)
    {
        var values = new List<int>();
        for (var i = 0; i < assignment.Kinds.Count && values.Count < 10; i++)
            if (assignment.Kinds[i].Precombined) values.Add(i);
        var runs = new List<List<int>>();
        var run = new List<int>();
        for (var i = 0; i < assignment.Kinds.Count; i++)
        {
            var kind = assignment.Kinds[i];
            var ctx = BindsContext(shape, kind.ApplyParams);
            if (!ctx) foreach (var f in FeedersOf(assignment, kind)) if (BindsContext(shape, f.feeder.Method.Params)) { ctx = true; break; }
            if (values.Contains(i) && kind.Group.Length == 0 && kind.IdleParams is null && !ctx)
                run.Add(i);
            else
            {
                if (run.Count >= 2) runs.Add(run);
                run = new List<int>();
            }
        }
        if (run.Count >= 2) runs.Add(run);
        var head = $"(Tl.TimelineWorld world, Tl.PlaybackTable players, Tl.KindStore __ks, bool forward{KindArgs(shape, true)})";
        W(writer, "internal static void Kinds" + head);
        W(writer, "{");
        var rAt = 0;
        for (var i = 0; i < assignment.Kinds.Count; i++)
        {
            var cur = rAt < runs.Count ? runs[rAt] : null;
            var name = runs.Count == 1 ? "Fused" : $"Fused_{rAt}";
            if (cur != null && i == cur[0]) W(writer, $"if (!{name}(world, players, __ks, forward{KindArgs(shape, false, "__firstWord, __endWord")}))\n{{");
            W(writer, $"Kind_{i}(world, players, __ks, forward{KindArgs(shape, false, "__firstWord, __endWord")});");
            if (cur != null && i == cur[cur.Count - 1]) { W(writer, "}"); rAt++; }
        }
        W(writer, "}");
        for (var i = 0; i < assignment.Kinds.Count; i++)
        {
            W(writer, $"internal static void Kind_{i}" + head);
            W(writer, "{");
            W(writer, "var __view = world.View;");
            W(writer, "var __pview = players.SystemView;");
            EmitKind(writer, assignment, shape, assignment.Kinds[i], feedKey, i, values.Contains(i));
            W(writer, "}");
            if (values.Contains(i)) EmitValuesStruct(writer, assignment, shape, assignment.Kinds[i], i, true);
            else if (assignment.Kinds[i].PrecombinedPulses) EmitValuesStruct(writer, assignment, shape, assignment.Kinds[i], i, false);
        }
        if (values.Count == 0) return;
        W(writer, "internal struct KindFill : Tl.IKindFill");
        W(writer, "{");
        W(writer, "public Tl.KindStore Store;");
        W(writer, "public void Add(ref Tl.KindBuild __b)");
        W(writer, "{");
        foreach (var i in values)
        {
            var kind = assignment.Kinds[i];
            W(writer, $"{{ var __r = Store.Join(\"{kind.Id}\", sizeof({kind.ValueTypeName}), \"{Signature(assignment, kind)}\", 0, out var __me); var __s = default(KindSpans_{i}); {kind.ValueTypeName} __id; {Identity(kind, "__id")}__b.Add<{kind.ValueTypeName}, KindSpans_{i}>(Store.IndexOf(\"{kind.Id}\"), __me, __r, ref __s, __id); }}");
        }
        W(writer, "}");
        W(writer, "}");
        for (var r = 0; r < runs.Count; r++) EmitFused(writer, assignment, shape, runs[r], head, runs.Count == 1 ? "Fused" : $"Fused_{r}");
    }

    static bool BindsContext(KernelShape shape, IReadOnlyList<ConsumerParam> ps)
    {
        foreach (var p in ps)
            if (p.Kind == ConsumerParamKind.Context || (p.Kind is (ConsumerParamKind.Column or ConsumerParamKind.ColumnReadOnly) && ColumnOf(shape, p.TypeName, p.Kind == ConsumerParamKind.Column) < 0 && ContextOf(shape, p.TypeName) >= 0))
                return true;
        return false;
    }

    static string ApplyTail(KernelShape shape, KindDecl kind)
    {
        var args = CallArgs(shape, new ConsumerMethod(ConsumerMethodKind.ExecuteActive, kind.ApplyParams, [], []), "", "__e", "");
        return args.Length == 0 ? "" : ", " + args;
    }

    static string Signature(SystemAssignment assignment, KindDecl kind)
    {
        var parts = FeedersOf(assignment, kind).ConvertAll(static f => $"{f.feeder.ConsumerMetadata}.{f.feeder.MethodName}:{(int)f.feeder.Trigger}");
        if (kind.Group.Length > 0) parts.Insert(0, "@" + kind.Group);
        return string.Join("\\n", parts);
    }

    static string LanePath(string root, string path) => path.Length == 0 ? root : root + "." + path;

    static string Identity(KindDecl k, string target)
    {
        var sb = new StringBuilder($"{target} = default; ");
        if (k.Monoid is > 0 and < 5)
            foreach (var f in k.LaneFields)
                sb.Append($"{LanePath(target, f.Path)} = {k.Monoid switch { 1 => f.Type == "float" ? "-0f" : f.Type == "double" ? "-0d" : "0", 2 => f.Type + ".MinValue", 3 => f.Type + ".MaxValue", _ => f.Type == "bool" ? "false" : "0" }}; ");
        return sb.ToString();
    }

    static bool Lanes(KindDecl k) => k.Monoid is > 0 and < 5;

    static string LaneOp(KindDecl k, string total, string next)
    {
        if (k.Monoid == 5) return $"if ({next}.{k.LaneFields[0].Path} >= {total}.{k.LaneFields[0].Path}) {total} = {next}; ";
        var sb = new StringBuilder();
        foreach (var f in k.LaneFields)
        {
            var t = LanePath(total, f.Path);
            var n = LanePath(next, f.Path);
            sb.Append(k.Monoid switch { 1 => $"{t} += {n}; ", 2 => $"{t} = System.Math.Max({t}, {n}); ", 3 => $"{t} = System.Math.Min({t}, {n}); ", _ => $"{t} |= {n}; " });
        }
        return sb.ToString();
    }

    static void EmitLaw(StringBuilder writer, KindDecl k)
    {
        var t = k.ValueTypeName;
        W(writer, $"{t} __last; bool __seen;");
        W(writer, $"void __Law(in {t} __v)\n{{\n{t} __a, __b;");
        if (k.Monoid != 5) W(writer, $"{Identity(k, "__a")}__b = __a; {LaneOp(k, "__a", "__v")}{k.TypeName}.Combine(ref __b, in __v); __Same(__a, __b);");
        W(writer, $"__a = __v; __b = __v; {LaneOp(k, "__a", "__v")}{k.TypeName}.Combine(ref __b, in __v); __Same(__a, __b);");
        W(writer, $"if (__seen) {{ __a = __last; __b = __last; {LaneOp(k, "__a", "__v")}{k.TypeName}.Combine(ref __b, in __v); __Same(__a, __b); }}");
        W(writer, "__last = __v; __seen = true;\n}");
        var differs = "if (" + string.Join(" || ", k.LaneFields.Skip(k.Monoid == 5 ? 1 : 0).Select(f => f.Type switch
            {
                "float" => $"System.BitConverter.SingleToInt32Bits({LanePath("__a", f.Path)}) != System.BitConverter.SingleToInt32Bits({LanePath("__b", f.Path)})",
                "double" => $"System.BitConverter.DoubleToInt64Bits({LanePath("__a", f.Path)}) != System.BitConverter.DoubleToInt64Bits({LanePath("__b", f.Path)})",
                _ => $"{LanePath("__a", f.Path)} != {LanePath("__b", f.Path)}",
            })) + ") ";
        W(writer, $"static void __Same({t} __a, {t} __b)\n{{\n{differs}throw new System.InvalidOperationException(\"Tl: kind '{k.Id}' declares Combine = {SystemReader.MonoidName(k.Monoid)}, but {k.TypeName.Replace("global::", "")}.Combine gives a different result on values from the library; fix Combine or the declaration.\");\n}}");
    }

    static string Acc(KindDecl k, string item, string total = "__total", string has = "__has", string sep = "\n")
        => $"if ({has}) {k.TypeName}.Combine(ref {total}, in {item});{sep}else {{ {total} = {item}; {has} = true; }}";

    static void EmitFused(StringBuilder writer, SystemAssignment assignment, KernelShape shape, List<int> fused, string head, string name)
    {
        var f0 = fused[0];
        W(writer, $"internal static bool {name}{head}\n{{\nvar __view = world.View; var __pview = players.SystemView; var __kfill = new KindFill {{ Store = __ks }}; var __pl = __ks.Playing;");
        foreach (var i in fused)
        {
            var kind = assignment.Kinds[i];
            W(writer, $"var __routes{i} = __ks.Join(\"{kind.Id}\", sizeof({kind.ValueTypeName}), \"{Signature(assignment, kind)}\", 0, out var __me{i}); var __kid{i} = __ks.IndexOf(\"{kind.Id}\"); var __kt{i} = __ks.Table(__kid{i});");
            W(writer, $"if (__kt{i} == null || __routes{i} == null || !__ks.RowsAreEntities(__kid{i})) return false;");
            W(writer, $"var __kv{i} = __ks.SpanValues(__kid{i}, __me{i}, ref __kfill); if (__kv{i} == null || __kv{i}->Data != __kv{f0}->Data) return false;");
        }
        W(writer, $"var __vrow = __kv{f0}->Row; var __vdata = __kv{f0}->Data; var __vstride = (nuint)__kv{f0}->Stride; var __vtc = (uint)__kv{f0}->TimelineCount; var __vhead = __vdata + (forward ? 0 : __kv{f0}->Back - __kv{f0}->Front);");
        W(writer, "var __pslots = __pview.Slots; var __pcounts = __pview.Counts; var __pspilled = __pview.Spilled; var __pblocks = __pview.Blocks; var __pspe = (nuint)__pview.SlotsPerEntity; var __hasSamples = __ks.HasSamples;");
        W(writer, $"var __pdn = __pview.Dense; var __porg = __pview.Origins; var __pborg = __pview.BlockOrigins; var __clk = __pview.Clock; var __dh = stackalloc ulong[{fused.Count}];");
        foreach (var i in fused) W(writer, $"var __dt{i} = stackalloc {assignment.Kinds[i].ValueTypeName}[64];");
        foreach (var i in fused)
            W(writer, $"var __vsh{i} = __kv{i}->Shift; var __vfr{i} = __kv{i}->Front; var __vbk{i} = __kv{i}->Back; var __vf{i} = forward ? __vfr{i} : __vbk{i}; var __vb{i} = __vsh{i} + (forward ? 1 : 2); var __vm{i} = 1u << __vb{i};");
        W(writer, $"for (var __kw = __firstWord < 0 ? 0 : __firstWord; __kw < __endWord && __kw < __kt{f0}->Words; __kw++)\n{{");
        W(writer, "var __plw = __pl[__kw];");
        foreach (var i in fused) W(writer, $"var __ka{i} = __kt{i}->Active[__kw]; var __kb{i} = __kt{i}->Enabled[__kw] & (__ka{i} | __plw);");
        W(writer, $"var __kba = {string.Join(" | ", fused.ConvertAll(static i => $"__kb{i}"))};");
        W(writer, "if (__kba == 0) continue;");
        var columns = new List<string>();
        for (var c = 0; c < shape.Columns.Count; c++) if (shape.UsedColumns[c]) columns.Add($"__c{c}");
        W(writer, "var __spw = __pspilled[__kw]; var __dnw = __pdn == null ? 0ul : __pdn[__kw] & __kba; var __lim = __n - (__kw << 6);");
        W(writer, $"var __dna = __dnw & ~({string.Join(" | ", fused.ConvertAll(static i => $"__ka{i}"))}) & (__lim >= 64 ? ~0ul : __lim <= 0 ? 0ul : (1ul << __lim) - 1);");
        var rest = $"__dna, __kw << 6, __porg, __pborg, __pslots, __pcounts, __spw, __pspe, __clk, __vdata, __vhead, __vstride, {string.Join(", ", fused.ConvertAll(static i => $"__kb{i}, __vb{i}, __vf{i}, __dt{i}"))}, __dh{string.Concat(columns.ConvertAll(static c => ", " + c))}";
        W(writer, $"if (__dnw != 0) {{ System.Runtime.CompilerServices.Unsafe.InitBlock(__dh, 0, {fused.Count * 8}); var __left = __pspe > 4 ? __dnw : {name}Small(__dnw, {rest}); if (__left != 0) {name}Dense(__left, {rest}); }}");
        W(writer, "for (var __kb = __kba & ~__dna; __kb != 0; __kb &= __kb - 1)\n{\nvar __bit = Tl.KindStore.TrailingZeros(__kb); var __row = (__kw << 6) + __bit; var __e = __row;\nif (__e >= __n) break;");
        W(writer, "var __inline = __pslots + (nuint)__e * __pspe; var __run = (__spw >> __bit & 1) == 0 ? __inline : __pblocks + *(int*)__inline; var __cnt = __pcounts[__e]; var __smp = __hasSamples ? __ks.SamplesOf(__e) : 0; var __sampled = __smp != 0; var __sk = __sampled ? Tl.KindRules.Depth(__run + __cnt, __smp) : 1;");
        foreach (var i in fused) W(writer, $"{assignment.Kinds[i].ValueTypeName} __ft{i} = default; var __fh{i} = false;");
        W(writer, "if ((__dnw >> __bit & 1) != 0)");
        W(writer, "{");
        for (var j = 0; j < fused.Count; j++) W(writer, $"__ft{fused[j]} = __dt{fused[j]}[__bit]; __fh{fused[j]} = (__dh[{j}] >> __bit & 1) != 0;");
        W(writer, "}");
        W(writer, "else if (!__sampled)");
        W(writer, "{");
        W(writer, "for (var __i = 0; __i < __cnt; __i++)");
        W(writer, "{");
        W(writer, "var __pb = __run + __i; var __tid = __pb->Timeline; if (__tid == 0) continue;");
        W(writer, "if (((byte)__pb->Flags | __pb->Rate) == 0)");
        W(writer, "{");
        W(writer, "var __t0 = (uint)(__tid - 1); if (__t0 >= __vtc) continue; var __vr0 = __vrow[__t0]; if (__vr0 < 0) continue;");
        W(writer, "var __at = __vdata + (nuint)(__vr0 + __pb->Tick) * __vstride; var __m = *(uint*)__at;");
        foreach (var i in fused)
            W(writer, $"if ((__m & __vm{i}) != 0) {{ ref readonly var __sv = ref *({assignment.Kinds[i].ValueTypeName}*)(__at + __vf{i}); {Acc(assignment.Kinds[i], "__sv", $"__ft{i}", $"__fh{i}", " ")} }}");
        W(writer, "}");
        W(writer, "else if (__pb->Rate == 0 && Tl.KindScore.Listed(__pb->Flags) && (__pb->Flags & __PF.Paused) == 0)");
        W(writer, "{");
        W(writer, $"var __hd = __kv{f0}->HeadOf(__tid, __pb->Tick); if (__hd == null) continue; var __m = *__hd; var __bk = forward ? (__pb->Flags & __PF.Reverse) != 0 : (__pb->Flags & __PF.Reverse) == 0; var __d = __bk ? 2 : 1;");
        foreach (var i in fused)
            W(writer, $"if ((__m >> (__vsh{i} + __d) & 1) != 0) {{ ref readonly var __sv = ref *({assignment.Kinds[i].ValueTypeName}*)((byte*)__hd + (__bk ? __vbk{i} : __vfr{i})); {Acc(assignment.Kinds[i], "__sv", $"__ft{i}", $"__fh{i}", " ")} }}");
        W(writer, "}");
        W(writer, "}");
        W(writer, "}");
        foreach (var i in fused)
        {
            var kind = assignment.Kinds[i];
            var tail = ApplyTail(shape, kind);
            W(writer, $"if ((__kb{i} >> __bit & 1) != 0)\n{{");
            W(writer, $"if (!__sampled && (__ka{i} >> __bit & 1) == 0) {{ if (__fh{i}) {kind.TypeName}.Apply(in __ft{i}{tail}); }}");
            W(writer, "else\n{");
            W(writer, "if ((__dnw >> __bit & 1) != 0) players.Settle(__e);");
            W(writer, $"var __kt = __kt{i}; var __kv = __kv{i}; var __routes = __routes{i}; var __me = __me{i}; var __stride = __kt->Stride; var __len = (int)__kt->Length[__row]; byte* __data = __kt->Data(__row); var __pulses = 0;");
            W(writer, $"for (var __sj = 0; __sj < __sk; __sj++)\n{{\nvar __total = __ft{i}; var __has = __fh{i};\nif (__sampled)\n{{");
            EmitValueWalk(writer, kind, false);
            W(writer, "}");
            EmitEntryWalk(writer, assignment, shape, kind, FeedersOf(assignment, kind), kind.ValueTypeName, 8, tail);
            W(writer, $"if (__has) {kind.TypeName}.Apply(in __total{tail});\n}}\nif (__len != 0) __kt->Clear(__row);\n}}\n}}");
        }
        W(writer, "}\n}\nreturn true;\n}");
        var typed = new List<string>();
        for (var c = 0; c < shape.Columns.Count; c++) if (shape.UsedColumns[c]) typed.Add($", {shape.Columns[c].ElementTypeName}* __c{c}");
        var sig = $"(ulong __bits, ulong __apply, int __base, ushort* __porg, ushort* __pborg, Tl.Playback* __pslots, int* __pcounts, ulong __spw, nuint __pspe, ushort __clk, byte* __vdata, byte* __vhead, nuint __vstride, {string.Join(", ", fused.ConvertAll(i => $"ulong __kb{i}, int __vb{i}, int __vf{i}, {assignment.Kinds[i].ValueTypeName}* __dt{i}"))}, ulong* __dh{string.Concat(typed)})\n{{{string.Concat(fused.ConvertAll(i => $"\nvar __vm{i} = 1u << __vb{i}; var __vd{i} = __vdata + __vf{i};"))}";
        var hot = "[System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveOptimization)]\nstatic ";
        var lanes = fused.Exists(i => Lanes(assignment.Kinds[i]));
        W(writer, $"{hot}ulong {name}Small{sig}");
        W(writer, $"var __hot = __bits & __apply & ~__spw & {string.Join(" & ", fused.ConvertAll(static i => $"__kb{i}"))}; __bits &= ~__hot;");
        W(writer, "for (; __hot != 0; __hot &= __hot - 1)\n{\nvar __bit = Tl.KindStore.TrailingZeros(__hot); var __e = __base + __bit; var __org = __porg + (nuint)__e * __pspe;");
        DenseTotals(writer, assignment, fused, lanes, false);
        W(writer, "switch (__pcounts[__e])\n{");
        for (var c = 1; c <= 4; c++)
        {
            W(writer, $"case {c}:");
            for (var s = 0; s < c; s++) DenseSlot(writer, assignment, fused, lanes, s.ToString());
            W(writer, "break;");
        }
        W(writer, "default:\n__bits |= 1ul << __bit;\ncontinue;\n}");
        DenseHas(writer, assignment, fused, false);
        foreach (var i in fused) W(writer, $"if (__fh{i}) {assignment.Kinds[i].TypeName}.Apply(in __ft{i}{ApplyTail(shape, assignment.Kinds[i])});");
        W(writer, "}\nreturn __bits;\n}");
        W(writer, $"{hot}void {name}Dense{sig}");
        W(writer, "for (; __bits != 0; __bits &= __bits - 1)\n{\nvar __bit = Tl.KindStore.TrailingZeros(__bits); var __e = __base + __bit;");
        W(writer, "var __org = (__spw >> __bit & 1) == 0 ? __porg + (nuint)__e * __pspe : __pborg + *(int*)(__pslots + (nuint)__e * __pspe);");
        DenseTotals(writer, assignment, fused, lanes, true);
        W(writer, "for (nint __i = 0, __cnt = __pcounts[__e]; __i < __cnt; __i++)");
        DenseSlot(writer, assignment, fused, lanes, "__i");
        DenseHas(writer, assignment, fused, true);
        W(writer, "if ((__apply >> __bit & 1) != 0)\n{");
        foreach (var i in fused) W(writer, $"if ((__kb{i} >> __bit & 1) != 0 && __fh{i}) {assignment.Kinds[i].TypeName}.Apply(in __ft{i}{ApplyTail(shape, assignment.Kinds[i])});");
        W(writer, "continue;\n}");
        for (var j = 0; j < fused.Count; j++) W(writer, $"__dt{fused[j]}[__bit] = __ft{fused[j]}; if (__fh{fused[j]}) __dh[{j}] |= 1ul << __bit;");
        W(writer, "}\n}");
    }

    static void DenseTotals(StringBuilder writer, SystemAssignment assignment, List<int> fused, bool lanes, bool pick)
    {
        foreach (var i in fused)
        {
            var k = assignment.Kinds[i];
            W(writer, Lanes(k) ? $"{k.ValueTypeName} __ft{i}; {Identity(k, $"__ft{i}")}" : $"{k.ValueTypeName} __ft{i} = default; " + (pick && k.Monoid == 5 ? $"nuint __bo{i} = 0; long __bp{i} = -1L << 40;" : $"var __fh{i} = false;"));
        }
        if (lanes) W(writer, "var __any = 0u;");
    }

    static void DenseSlot(StringBuilder writer, SystemAssignment assignment, List<int> fused, bool lanes, string slot)
    {
        var pick = slot == "__i";
        W(writer, $"{{\nvar __ro = (nuint)(ushort)(__org[{slot}] + __clk) * __vstride; var __m = *(uint*)(__vhead + __ro);" + (lanes ? " __any |= __m;" : ""));
        foreach (var i in fused)
        {
            var k = assignment.Kinds[i];
            W(writer, Lanes(k) ? $"{{ var __rv{i} = ({k.ValueTypeName}*)(__vd{i} + __ro); {LaneOp(k, $"__ft{i}", $"(*__rv{i})")}}}"
                : pick && k.Monoid == 5 ? $"Tl.KindStore.Pick(ref __bo{i}, ref __bp{i}, __m >> __vb{i}, (({k.ValueTypeName}*)(__vd{i} + __ro))->{k.LaneFields[0].Path}, __ro);"
                : $"if ((__m & __vm{i}) != 0) {{ ref readonly var __sv = ref *({k.ValueTypeName}*)(__vd{i} + __ro); {Acc(k, "__sv", $"__ft{i}", $"__fh{i}", " ")} }}");
        }
        W(writer, "}");
    }

    static void DenseHas(StringBuilder writer, SystemAssignment assignment, List<int> fused, bool pick)
    {
        foreach (var i in fused)
            if (Lanes(assignment.Kinds[i])) W(writer, $"var __fh{i} = (__any & __vm{i}) != 0;");
            else if (pick && assignment.Kinds[i].Monoid == 5) W(writer, $"var __fh{i} = __bp{i} != -1L << 40; if (__fh{i}) __ft{i} = *({assignment.Kinds[i].ValueTypeName}*)(__vd{i} + __bo{i});");
    }

    static List<(int consumer, FeederDecl feeder)> FeedersOf(SystemAssignment assignment, KindDecl kind)
    {
        var feeders = new List<(int consumer, FeederDecl feeder)>();
        for (var c = 0; c < assignment.Consumers.Count; c++)
            foreach (var feeder in assignment.Consumers[c].Feeders)
                if (feeder.KindName == kind.Id) feeders.Add((c, feeder));
        feeders.Sort(static (a, b) =>
        {
            var by = string.CompareOrdinal(a.feeder.ConsumerMetadata, b.feeder.ConsumerMetadata);
            return by != 0 ? by : string.CompareOrdinal(a.feeder.MethodName, b.feeder.MethodName);
        });
        return feeders;
    }

    static void EmitValuesStruct(StringBuilder writer, SystemAssignment assignment, KernelShape shape, KindDecl kind, int index, bool spans)
    {
        var value = kind.ValueTypeName;
        var law = kind.Monoid != 0;
        W(writer, $"internal struct {(spans ? "KindSpans" : "KindPulses")}_{index} : Tl.IKindSpanValues<{value}>");
        W(writer, "{");
        if (law)
        {
            EmitLaw(writer, kind);
            W(writer, $"public bool Evaluate(int __r, Tl.LibraryStep* __def, Tl.LibraryTimeline* __tl, ushort __tick, bool __backward, out {value} __v)\n{{\nif (!__Evaluate(__r, __def, __tl, __tick, __backward, out __v)) return false;\n__Law(in __v);\nreturn true;\n}}");
        }
        W(writer, $"{(law ? "bool __Evaluate" : "public bool Evaluate")}(int __r, Tl.LibraryStep* __def, Tl.LibraryTimeline* __tl, ushort __tick, bool __backward, out {value} __v)");
        W(writer, "{");
        W(writer, "__v = default;");
        if (!spans) W(writer, "if (__tick < __def->WindowStart || __tick >= __def->WindowEnd) return false;");
        EmitFrameFlags(writer, null, null);
        EmitCases(writer, assignment, shape, FeedersOf(assignment, kind), spans, "return false", !spans);
        W(writer, "return true;");
        W(writer, "}");
        W(writer, law
            ? $"public void Combine(ref {value} total, in {value} next) {{ var __a = total; {LaneOp(kind, "__a", "next")}{kind.TypeName}.Combine(ref total, in next); __Same(__a, total); }}"
            : spans
            ? $"public void Combine(ref {value} total, in {value} next) => {kind.TypeName}.Combine(ref total, in next);"
            : $"public void Combine(ref {value} total, in {value} next) {{ }}");
        W(writer, "}");
    }

    static void EmitValueWalk(StringBuilder writer, KindDecl kind, bool trackListed = true)
    {
        W(writer, "for (var __q = 0; __q < __cnt + __smp; __q++)");
        W(writer, "{");
        W(writer, "var __i = __q < __smp ? __cnt + __q : __q - __smp;");
        W(writer, "var __pb = __run + __i;");
        W(writer, "if (__pb->Timeline == 0 || !Tl.KindScore.Listed(__pb->Flags)) continue;");
        W(writer, "var __vr = __kv->RowOf(__pb->Timeline, __pb->Tick);");
        W(writer, "if (__vr == null) continue;");
        W(writer, trackListed ? "if (__i < __cnt) { __listed = true; if (__sj != 0 || __pb->Rate != 0) continue; }" : "if (__i < __cnt) { if (__sj != 0 || __pb->Rate != 0) continue; }");
        W(writer, "else if (__pb->Phase != __sj) continue;");
        W(writer, "if ((__pb->Flags & Tl.PlaybackFlags.Paused) != 0) continue;");
        W(writer, "var __bk = forward ? (__pb->Flags & Tl.PlaybackFlags.Reverse) != 0 : (__pb->Flags & Tl.PlaybackFlags.Reverse) == 0;");
        W(writer, "if ((*(uint*)__vr >> __kv->Shift & (__bk ? 4u : 2u)) == 0) continue;");
        W(writer, $"ref readonly var __sv = ref *({kind.ValueTypeName}*)(__vr + (__bk ? __kv->Back : __kv->Front));");
        W(writer, Acc(kind, "__sv"));
        W(writer, "}");
    }

    static void EmitKind(StringBuilder writer, SystemAssignment assignment, KernelShape shape, KindDecl kind, int feedKey, int index, bool values)
    {
        var feeders = FeedersOf(assignment, kind);
        var valueAt = kind.Group.Length > 0 ? 12 : 8;
        var value = kind.ValueTypeName;
        var tail = ApplyTail(shape, kind);
        var feed = kind.Foreign;
        var spanless = !feed && kind.Accepts == 1;
        W(writer, "{");
        W(writer, $"var __routes = __ks.Join(\"{kind.Id}\", sizeof({value}), \"{Signature(assignment, kind)}\", {(feed ? feedKey : 0)}, out var __me);");
        W(writer, $"var __kid = __ks.IndexOf(\"{kind.Id}\");");
        W(writer, "var __kt = __ks.Table(__kid);");
        W(writer, "if (__kt != null && __routes != null)");
        W(writer, "{");
        W(writer, "if (__firstWord < 0) __firstWord = 0;");
        W(writer, "if (__endWord > __kt->Words) __endWord = __kt->Words;");
        W(writer, "if (__firstWord > __endWord) __firstWord = __endWord;");
        W(writer, "var __stride = __kt->Stride;");
        if (!spanless)
        {
            W(writer, "var __score = __ks.Score;");
            W(writer, "var __pl = __ks.Playing;");
            W(writer, "var __whole = __ks.RowsAreEntities(__kid);");
        }
        W(writer, "var __lst = __ks.ListedOf(__kid);");
        if (values) W(writer, "var __kfill = new KindFill { Store = __ks }; var __kv = __ks.SpanValues(__kid, __me, ref __kfill);");
        if (kind.PrecombinedPulses)
        {
            W(writer, $"var __kpe = default(KindPulses_{index}); var __kpv = __ks.PulseValues<{value}, KindPulses_{index}>(__kid, __me, ref __kpe);");
            W(writer, "if (__kpv != null)");
            W(writer, "{");
            W(writer, "var __ph = __ks.PulseHitsOf(__kid);");
            W(writer, "var __lo = __firstWord == 0 ? 0 : __ph->LowerBound(__firstWord << 6);");
            W(writer, "var __hi = __endWord >= __kt->Words ? __ph->Count : __ph->LowerBound(__endWord << 6);");
            W(writer, $"var __hits = __ph->Items; var __ps = __kpv->Start; var __pv = ({value}*)__kpv->Data; var __ken = __kt->Enabled; var __kac = __kt->Active;");
            W(writer, "for (var __idx = __lo; __idx < __hi; )");
            W(writer, "{");
            W(writer, "var __e = __hits[__idx].Entity;");
            W(writer, "if (__e >= __n) break;");
            W(writer, "var __ew = __e >> 6; var __eb = 1ul << (__e & 63);");
            W(writer, "if ((__ken[__ew] & __eb) == 0) { while (__idx < __hi && __hits[__idx].Entity == __e) __idx++; continue; }");
            if (!kind.Each) W(writer, $"{value} __total = default; var __has = false;");
            W(writer, "do");
            W(writer, "{");
            W(writer, "var __cell = __hits[__idx++].Cell;");
            W(writer, "for (var __p = __ps[__cell]; __p < __ps[__cell + 1]; __p++)");
            if (kind.Each) W(writer, $"{kind.TypeName}.Apply(in __pv[__p]{tail});");
            else W(writer, Acc(kind, "__pv[__p]", sep: " "));
            W(writer, "} while (__idx < __hi && __hits[__idx].Entity == __e);");
            W(writer, "if ((__kac[__ew] & __eb) != 0)");
            W(writer, "{");
            W(writer, "var __row = __e; var __len = (int)__kt->Length[__row]; byte* __data = __kt->Data(__row); var __run = __pview.RunOf(__e); var __cnt = __pview.CountOf(__e); var __sampled = false; var __sj = 0; var __pulses = 0;");
            EmitEntryWalk(writer, assignment, shape, kind, feeders, value, valueAt, tail);
            W(writer, "if (__len != 0) __kt->Clear(__row);");
            W(writer, "}");
            if (!kind.Each) W(writer, $"if (__has) {kind.TypeName}.Apply(in __total{tail});");
            W(writer, "}");
            W(writer, "}");
        }
        W(writer, "for (var __kw = __firstWord; __kw < __endWord; __kw++)");
        W(writer, "{");
        W(writer, spanless ? "var __kb = __kt->Enabled[__kw] & __kt->Active[__kw];" : "var __kb = __kt->Enabled[__kw] & (__whole ? __kt->Active[__kw] | __lst[__kw] | __pl[__kw] : ~0ul);");
        W(writer, "while (__kb != 0)");
        W(writer, "{");
        W(writer, "var __row = (__kw << 6) + Tl.KindStore.TrailingZeros(__kb);");
        W(writer, "__kb &= __kb - 1;");
        W(writer, "var __e = __kt->Entity[__row];");
        W(writer, "if (__e >= __n) continue;");
        W(writer, "var __len = (int)__kt->Length[__row];");
        W(writer, "byte* __data = __kt->Data(__row);");
        if (values || feed) W(writer, "if (__pview.IsDense(__e)) players.Settle(__e);");
        W(writer, "var __run = __pview.RunOf(__e);");
        W(writer, "var __cnt = __pview.CountOf(__e);");
        W(writer, "var __smp = __ks.SamplesOf(__e);");
        if (!feed)
        {
            W(writer, "var __pulses = 0;");
            if (!spanless) W(writer, "var __listed = false;");
            W(writer, "var __sampled = __smp != 0;");
            W(writer, "var __sk = __sampled ? Tl.KindRules.Depth(__run + __cnt, __smp) : 1;");
            W(writer, "for (var __sj = 0; __sj < __sk; __sj++)");
            W(writer, "{");
            if (!kind.Each)
            {
                W(writer, $"{value} __total = default;");
                W(writer, "var __has = false;");
            }
        }
        if (feed)
        {
            EmitDrop(writer, "(__q->Flags & Tl.KindEntryFlags.Span) != 0" + (kind.Group.Length > 0 ? " && *(ushort*)((byte*)__q + 8) == __kid" : "") + " && (__routes[__q->Feeder] >> 8) == __me");
            EmitFeedEntries(writer, assignment, shape, kind, feeders, value, valueAt);
        }
        if (values)
        {
            W(writer, "if (__kv != null)");
            W(writer, "{");
            EmitValueWalk(writer, kind);
            W(writer, "}");
            W(writer, "else");
            W(writer, "{");
        }
        if (!spanless) EmitSpanWalk(writer, assignment, shape, kind, feeders, feed, value, valueAt, tail);
        if (values) W(writer, "}");
        if (!feed) EmitEntryWalk(writer, assignment, shape, kind, feeders, value, valueAt, tail);
        if (!feed)
        {
            if (!kind.Each) W(writer, $"if (__has) {kind.TypeName}.Apply(in __total{tail});");
            W(writer, "}");
            W(writer, spanless ? "__lst[__row >> 6] &= ~(1ul << (__row & 63));" : "if (__listed) __lst[__row >> 6] |= 1ul << (__row & 63); else __lst[__row >> 6] &= ~(1ul << (__row & 63));");
            if (kind.Group.Length == 0) W(writer, "if (__len != 0) __kt->Clear(__row);");
            else
            {
                W(writer, "if (__sampled || __pulses != 0)");
                W(writer, "{");
                EmitDrop(writer, "*(ushort*)((byte*)__q + 8) == __kid");
                W(writer, "}");
            }
        }
        W(writer, "}");
        W(writer, "}");
        if (kind.IdleParams is not null) EmitIdle(writer, shape, kind);
        W(writer, "}");
        W(writer, "}");
    }

    static void EmitDrop(StringBuilder writer, string drop)
    {
        W(writer, "var __kept = 0;");
        W(writer, "for (var __j = 0; __j < __len; __j++)");
        W(writer, "{");
        W(writer, "var __q = (Tl.KindEntry*)(__data + (nuint)__j * (nuint)__stride);");
        W(writer, $"if ({drop}) continue;");
        W(writer, "if (__kept != __j) System.Buffer.MemoryCopy(__q, __data + (nuint)__kept * (nuint)__stride, __stride, __stride);");
        W(writer, "__kept++;");
        W(writer, "}");
        W(writer, "__len = __kept;");
        W(writer, "if (__kept == 0) __kt->Clear(__row); else __kt->Length[__row] = (ushort)__kept;");
    }

    static void EmitSpanWalk(StringBuilder writer, SystemAssignment assignment, KernelShape shape, KindDecl kind, List<(int consumer, FeederDecl feeder)> feeders, bool feed, string value, int valueAt, string tail)
    {
        W(writer, "for (var __q = 0; __q < __cnt + __smp; __q++)");
        W(writer, "{");
        W(writer, "var __i = __q < __smp ? __cnt + __q : __q - __smp;");
        W(writer, "var __pb = __run + __i;");
        W(writer, "if (__pb->Timeline == 0 || !Tl.KindScore.Listed(__pb->Flags)) continue;");
        W(writer, "var __cell = __score.CellOf(__pb->Timeline, __pb->Tick, __kid);");
        W(writer, "if (__cell < 0 || __score.Start[__cell] == __score.Start[__cell + 1]) continue;");
        if (feed) W(writer, "if (__i < __cnt && __pb->Rate != 0) continue;");
        else
        {
            W(writer, "if (__i < __cnt) { __listed = true; if (__sj != 0 || __pb->Rate != 0) continue; }");
            W(writer, "else if (__pb->Phase != __sj) continue;");
        }
        W(writer, "if ((__pb->Flags & Tl.PlaybackFlags.Paused) != 0) continue;");
        EmitSlotHead(writer, "__pb->Timeline");
        W(writer, "for (var __f = __score.Start[__cell]; __f < __score.Start[__cell + 1]; __f++)");
        W(writer, "{");
        W(writer, "var __sp = __score.Spans + __f;");
        W(writer, "var __r = __routes[__sp->Ordinal];");
        W(writer, "if ((__r >> 8) != __me) continue;");
        W(writer, "var __def = __sp->Step;");
        W(writer, "if (__def == null) continue;");
        EmitFrameFlags(writer, "Tl.KindScore.Synthetic(__pb->Flags, __tick, __def, __backward)", null);
        W(writer, $"{value} __v = default;");
        EmitCases(writer, assignment, shape, feeders, true);
        if (feed)
        {
            W(writer, "var __add = __kt->Append(__row);");
            W(writer, "*__add = new Tl.KindEntry { Timeline = __pb->Timeline, Step = __sp->Window, Slot = (byte)__i, Feeder = __sp->Ordinal, Flags = Tl.KindEntryFlags.Span | Tl.KindEntryFlags.Pulse | Tl.KindEntryFlags.Ready };");
            if (kind.Group.Length > 0) W(writer, "*(ushort*)((byte*)__add + 8) = (ushort)__kid;");
            W(writer, $"System.Runtime.CompilerServices.Unsafe.WriteUnaligned((byte*)__add + {valueAt}, __v);");
        }
        else if (kind.Each) W(writer, $"{kind.TypeName}.Apply(in __v{tail});");
        else W(writer, Acc(kind, "__v"));
        W(writer, "}");
        W(writer, "}");
    }

    static void EmitEntryHead(StringBuilder writer)
    {
        W(writer, "var __pb = __pview.SlotOf(__e, __en->Slot);");
        EmitSlotHead(writer, "__en->Timeline");
        EmitFrameFlags(writer, "(__en->Flags & Tl.KindEntryFlags.Synthetic) != 0", "(__en->Flags & Tl.KindEntryFlags.Interrupted) != 0");
    }

    static void EmitSlotHead(StringBuilder writer, string timeline)
    {
        W(writer, $"var __tl = Tl.LibraryViewReader.GetTimeline(in __view, new Tl.TimelineId({timeline}));");
        W(writer, "ushort __tick = __pb->Tick;");
        W(writer, "var __backward = forward ? (__pb->Flags & Tl.PlaybackFlags.Reverse) != 0 : (__pb->Flags & Tl.PlaybackFlags.Reverse) == 0;");
    }

    static void EmitFrameFlags(StringBuilder writer, string? synthetic, string? interrupted)
    {
        void Flag(string? t, string f) { if (t != null) W(writer, $"if ({t}) __kflags |= Tl.FrameFlags.{f};"); }
        W(writer, "var __kflags = Tl.FrameFlags.None;");
        Flag("__backward", "Reverse"); Flag(synthetic, "Synthetic"); Flag(interrupted, "Interrupted");
        Flag("__tick == 0", "TimelineStart"); Flag("__tick == (ushort)(__tl->Duration - 1)", "TimelineEnd");
        W(writer, "var __ok = false;");
    }

    static void EmitCases(StringBuilder writer, SystemAssignment assignment, KernelShape shape, List<(int consumer, FeederDecl feeder)> feeders, bool spans, string skip = "continue", bool preEval = false)
    {
        var any = false;
        for (var i = 0; i < feeders.Count; i++)
        {
            var (c, feeder) = feeders[i];
            if ((feeder.Trigger == FeederTrigger.Span) != spans) continue;
            if (!any) { W(writer, "switch (__r & 0xff)"); W(writer, "{"); any = true; }
            var consumer = assignment.Consumers[c];
            W(writer, $"case {i}:");
            W(writer, "{");
            if (feeder.Trigger == FeederTrigger.Marker)
            {
                W(writer, $"byte* __mptr{c};");
                W(writer, $"if (!Tl.MarkerTableRegistry.TryResolve(world, __tl->Id, __ks.MarkerOf(__en->Timeline, __en->Step), sizeof({consumer.MarkerTypeName}), out __mptr{c})) throw new System.InvalidOperationException(\"Tl: marker values are not published for this library.\");");
                W(writer, $"{consumer.MarkerTypeName} __m{c} = *({consumer.MarkerTypeName}*)__mptr{c};");
                W(writer, $"var __mf{c} = new Tl.MarkerFrame<{consumer.MarkerTypeName}>(in __m{c}, __tick, 0, __kflags);");
                W(writer, $"__v = {consumer.ConsumerTypeName}.{feeder.MethodName}({CallArgs(shape, feeder.Method, $"__mf{c}", "__e", "")});");
            }
            else
            {
                if (!spans && !preEval)
                {
                    W(writer, "var __def = __ks.StepOf(__en->Timeline, __en->Step, __tick);");
                    W(writer, "if (__def == null || __tick < __def->WindowStart || __tick >= __def->WindowEnd) break;");
                }
                EmitMaterialize(writer, consumer, c, "__tl", "__tick", "__backward", "__kflags");
                if (feeder.Method.Params.Any(static p => p.Kind == ConsumerParamKind.FoldFeed)) EmitFeeds(writer, consumer, c);
                var frameVar = $"__f{c}";
                if (IsTlFrame(feeder.Method))
                {
                    frameVar = $"__tf{c}";
                    W(writer, $"var {frameVar} = new Tl.TlFrame<{consumer.ClipTypeName}>(in __f{c});");
                }
                W(writer, $"__v = {consumer.ConsumerTypeName}.{feeder.MethodName}({CallArgs(shape, feeder.Method, frameVar, "__e", $"__fd{c}_")});");
            }
            W(writer, "__ok = true;");
            W(writer, "break;");
            W(writer, "}");
        }
        if (any) W(writer, "}");
        W(writer, $"if (!__ok) {skip};");
    }

    static void EmitEntryWalk(StringBuilder writer, SystemAssignment assignment, KernelShape shape, KindDecl kind, List<(int consumer, FeederDecl feeder)> feeders, string value, int valueAt, string tail)
    {
        W(writer, "for (var __j = 0; __j < __len; __j++)");
        W(writer, "{");
        W(writer, "var __en = (Tl.KindEntry*)(__data + (nuint)__j * (nuint)__stride);");
        if (kind.Group.Length > 0) W(writer, "if (*(ushort*)((byte*)__en + 8) != __kid) continue;");
        W(writer, "if (__sampled && !Tl.KindRules.Due(__en, __sj, __run, __cnt)) continue;");
        W(writer, $"{value} __v = default;");
        W(writer, "__pulses++;");
        W(writer, "if (__en->Timeline == 0)");
        W(writer, $"__v = System.Runtime.CompilerServices.Unsafe.ReadUnaligned<{value}>((byte*)__en + {valueAt});");
        W(writer, "else");
        W(writer, "{");
        W(writer, "var __r = __routes[__en->Feeder];");
        W(writer, "if ((__r >> 8) != __me)");
        W(writer, "{");
        W(writer, "if ((__en->Flags & Tl.KindEntryFlags.Ready) == 0) continue;");
        W(writer, $"__v = System.Runtime.CompilerServices.Unsafe.ReadUnaligned<{value}>((byte*)__en + {valueAt});");
        W(writer, "__en->Flags &= ~Tl.KindEntryFlags.Ready;");
        W(writer, "}");
        W(writer, "else");
        W(writer, "{");
        EmitEntryHead(writer);
        EmitCases(writer, assignment, shape, feeders, false);
        W(writer, "}");
        W(writer, "}");
        if (kind.Each) W(writer, $"{kind.TypeName}.Apply(in __v{tail});");
        else W(writer, Acc(kind, "__v"));
        W(writer, "}");
    }

    static void EmitFeedEntries(StringBuilder writer, SystemAssignment assignment, KernelShape shape, KindDecl kind, List<(int consumer, FeederDecl feeder)> feeders, string value, int valueAt)
    {
        W(writer, "for (var __j = 0; __j < __len; __j++)");
        W(writer, "{");
        W(writer, "var __en = (Tl.KindEntry*)(__data + (nuint)__j * (nuint)__stride);");
        if (kind.Group.Length > 0) W(writer, "if (*(ushort*)((byte*)__en + 8) != __kid) continue;");
        W(writer, "if (__en->Timeline == 0 || (__en->Flags & Tl.KindEntryFlags.Span) != 0) continue;");
        W(writer, "var __r = __routes[__en->Feeder];");
        W(writer, "if ((__r >> 8) != __me) continue;");
        W(writer, $"{value} __v = default;");
        EmitEntryHead(writer);
        EmitCases(writer, assignment, shape, feeders, false);
        W(writer, $"System.Runtime.CompilerServices.Unsafe.WriteUnaligned((byte*)__en + {valueAt}, __v);");
        W(writer, "__en->Flags |= Tl.KindEntryFlags.Ready;");
        W(writer, "}");
    }

    static void EmitIdle(StringBuilder writer, KernelShape shape, KindDecl kind)
    {
        var idleArgs = CallArgs(shape, new ConsumerMethod(ConsumerMethodKind.ExecuteActive, kind.IdleParams!, [], []), "", "__e", "");
        W(writer, "for (var __kw = __firstWord; __kw < __endWord; __kw++)");
        W(writer, "{");
        W(writer, "var __kb = ~(__kt->Active[__kw] | __lst[__kw]) & __kt->Enabled[__kw];");
        W(writer, "while (__kb != 0)");
        W(writer, "{");
        W(writer, "var __e = __kt->Entity[(__kw << 6) + Tl.KindStore.TrailingZeros(__kb)];");
        W(writer, "__kb &= __kb - 1;");
        W(writer, "if (__e >= __n) continue;");
        W(writer, $"{kind.TypeName}.Idle({idleArgs});");
        W(writer, "}");
        W(writer, "}");
    }

    static string BaseSig(KernelShape s, string name, bool range)
        => $"internal static void {name}(Tl.TimelineWorld world, Tl.PlaybackTable players, bool forward{ListArgs(s, i => $"{s.Columns[i].ElementTypeName}* __c{i}", range ? "int __n, int __firstWord, int __endWord" : "int __n", i => $"ref {s.Contexts[i].ElementTypeName} __ctx{i}", i => $"{s.Events[i].TypeName} __ev{i}")})";
    static string FullArgs(KernelShape s, bool range)
        => ListArgs(s, i => $"__c{i}", range ? "__n, 0, 2147483647" : "__n", i => $"ref __ctx{i}", i => $"__ev{i}");
