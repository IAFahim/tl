    static void EmitCloseLoop(StringBuilder writer, SystemAssignment assignment, KernelShape shape)
    {
        W(writer, "var __closing = players.Closing;");
        W(writer, "for (var __ci = 0; __ci < __closing->Count; __ci++)");
        W(writer, "{");
        W(writer, "__closing->Get(__ci, out var __ce, out var __cs, out var __cpb);");
        W(writer, "var __ctl = Tl.LibraryViewReader.GetTimeline(in __view, new Tl.TimelineId(__cpb.Timeline));");
        W(writer, "if (__ctl is null || __ctl->Duration == 0) continue;");
        W(writer, "var __ctick = __cpb.Tick < __ctl->Duration ? __cpb.Tick : (ushort)(__ctl->Duration - 1);");
        W(writer, "var __cstage = Tl.LibraryViewReader.StageAt(__ctl, __ctick);");
        W(writer, "if (__cstage is null) continue;");
        W(writer, "var __cbackward = forward ? (__cpb.Flags & Tl.PlaybackFlags.Reverse) != 0 : (__cpb.Flags & Tl.PlaybackFlags.Reverse) == 0;");
        EmitBind(writer, shape, "__ce", "__cs");
        EmitEventSteps(writer, assignment, shape, "__cstage", "__ctl", "__ctick", "Tl.FrameFlags.Interrupted", "__cbackward", "__ce", closing: true);
        W(writer, "}");
    }

    static void EmitEventSteps(StringBuilder writer, SystemAssignment assignment, KernelShape shape, string stage, string timeline, string tick, string flags, string backward, string entity, bool closing)
    {
        W(writer, $"for (var __i = 0; __i < {stage}->StepCount; __i++)");
        W(writer, "{");
        W(writer, $"var __def = {stage}->Steps + __i; if ({tick} < __def->WindowStart || {tick} >= __def->WindowEnd) continue;");
        for (var c = 0; c < assignment.Consumers.Count; c++)
        {
            var consumer = assignment.Consumers[c];
            var methods = consumer.Methods.Where(method => closing ? method.Kind == ConsumerMethodKind.OnClipEnd : IsEvent(method)).ToArray();
            if (methods.Length == 0) continue;
            W(writer, $"if (__def->PairKey == {consumer.PairKey}UL)");
            W(writer, "{");
            EmitMaterialize(writer, consumer, c, timeline, tick, backward, flags);
            foreach (var method in methods)
            {
                var condition = closing ? "" : method.Kind switch
                {
                    ConsumerMethodKind.OnClipStart => $"if ({tick} == __def->WindowStart && (__pb->Flags & Tl.PlaybackFlags.ReenterPending) == 0) ",
                    ConsumerMethodKind.OnClipEnd => $"if ({tick} == __def->WindowEnd - 1 && (__pb->Flags & Tl.PlaybackFlags.ReenterPending) == 0) ",
                    _ => "",
                };
                W(writer, $"{condition}{consumer.ConsumerTypeName}.{method.Kind}({CallArgs(shape, method, $"__f{c}", entity, "", consumer.ClipTypeName)});");
            }
            W(writer, "}");
        }
        W(writer, "}");
    }

    static void EmitMaterialize(StringBuilder writer, SystemConsumer consumer, int index, string tl, string tick, string backward, string flags)
    {
        W(writer, $"byte* __row{index} = (byte*)__def->FrameRow;");
        W(writer, $"byte* __first{index} = __row{index} + sizeof({consumer.TrackTypeName});");
        W(writer, $"byte* __second{index} = __def->FactorSpan == 0 ? null : __first{index} + sizeof({consumer.ClipTypeName});");
        W(writer, $"float __blend{index} = __def->FactorSpan == 0 ? 0f : (__def->FactorSpan <= 1 ? 0.5f : ({tick} - __def->FactorStart) / (float)(__def->FactorSpan - 1));");
        W(writer, $"ushort __len{index} = (ushort)(__def->WindowEnd - __def->WindowStart);");
        W(writer, $"ushort __within{index} = (ushort)({tick} - __def->WindowStart);");
        W(writer, $"sbyte __dir{index} = {backward} ? (sbyte)-1 : (sbyte)1;");
        W(writer, $"Frame_{index}(__row{index}, __first{index}, __second{index}, __blend{index}, {tick}, __len{index}, __within{index}, (ushort)__def->TrackIndex, (ushort){tl}->Duration, __dir{index}, {flags}, out var __t{index}, out var __cc{index}, out var __f{index});");
    }

    static void EmitFeeds(StringBuilder writer, SystemConsumer consumer, int index)
    {
        var fold = FoldOf(consumer);
        if (fold is null) return;
        for (var o = 0; o < fold.Params.Count; o++)
            W(writer, $"{fold.Params[o].TypeName} __fd{index}_{o} = default;");
        var args = string.Join(", ", fold.Params.Select((p, o) => $"{p.Modifier}__fd{index}_{o}"));
        W(writer, $"{consumer.ConsumerTypeName}.Fold(in __f{index}, {args});");
    }

    static string CallArgs(KernelShape shape, ConsumerMethod method, string frameVar, string rowVar, string feedPrefix, string? eventClip = null)
    {
        var args = new List<string>();
        var start = 0;
        if (method.Params.Count > 0 && method.Params[0].Kind is ConsumerParamKind.Frame or ConsumerParamKind.MarkerFrame)
        {
            args.Add(eventClip is not null && IsTlFrame(method) ? $"new global::Tl.TlFrame<{eventClip}>(in {frameVar})" : $"in {frameVar}");
            start = 1;
        }
        for (var p = start; p < method.Params.Count; p++)
        {
            var parameter = method.Params[p];
            switch (parameter.Kind)
            {
                case ConsumerParamKind.FoldFeed:
                    args.Add($"in {feedPrefix}{parameter.FoldIndex}");
                    break;
                case ConsumerParamKind.Column:
                {
                    var at = ColumnOf(shape, parameter.TypeName, true);
                    if (at >= 0) args.Add($"ref __c{at}[{rowVar}]");
                    else args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
                }
                case ConsumerParamKind.ColumnReadOnly:
                {
                    var at = ColumnOf(shape, parameter.TypeName, false);
                    if (at >= 0) args.Add($"in __c{at}[{rowVar}]");
                    else args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
                }
                case ConsumerParamKind.Context:
                    args.Add($"{parameter.Modifier}__ctx{ContextOf(shape, parameter.TypeName)}");
                    break;
                case ConsumerParamKind.Events:
                    args.Add($"ref __eb{EventOf(shape, Tl.Gen.CSharp.Analysis.SystemReader.EventElement(parameter.TypeName))}");
                    break;
            }
        }
        return string.Join(", ", args);
    }

    static void EmitRun(StringBuilder writer, SystemAssignment assignment, string id)
    {
        var system = assignment.System;
        var shape = ShapeOf(assignment, id);
        var ns = NamespaceOf(system.TypeName);
        var shortName = ShortNameOf(system.TypeName);
        var safe = $"{id}_{Sanitize(system.TypeName)}";
        void LenCheck()
        {
            W(writer, "int __len = players.EntityCapacity;");
            var first = true;
            foreach (var field in system.Fields)
            {
                if (field.Kind is not (SystemFieldKind.Column or SystemFieldKind.ColumnReadOnly)) continue;
                if (first) { W(writer, $"__len = this.{field.Name}.Length;"); first = false; }
                else W(writer, $"if (this.{field.Name}.Length != __len) throw new System.ArgumentException(\"{system.TypeName}: column {field.Name} lengths differ.\");");
            }
            W(writer, $"if (__len > players.EntityCapacity) throw new System.ArgumentException(\"{system.TypeName}: column length exceeds table capacity.\");");
        }
        var pins = new List<string>();
        for (var i = 0; i < shape.Columns.Count; i++) if (shape.UsedColumns[i]) pins.Add($"fixed ({shape.Columns[i].ElementTypeName}* __p{i} = this.{shape.Columns[i].Name})");
        void WithPins(Action body) { if (pins.Count == 0) body(); else { foreach (var pin in pins) { W(writer, pin); W(writer, "{"); } body(); foreach (var pin in pins) W(writer, "}"); } }
        string Args()
            => ListArgs(shape, i => $"__p{i}", "__len", i => $"ref this.{shape.Contexts[i].Name}", i => $"this.{shape.Events[i].Name}");
        if (ns.Length > 0) { W(writer, $"namespace {ns}"); W(writer, "{"); }
        W(writer, $"partial struct {shortName}");
        W(writer, "{");
        W(writer, $"public unsafe void Run(Tl.TimelineWorld world, Tl.PlaybackTable players, bool forward = true)");
        W(writer, "{");
        W(writer, "if (world is null) throw new System.ArgumentNullException(nameof(world));");
        W(writer, "if (players is null) throw new System.ArgumentNullException(nameof(players));");
        LenCheck();
        WithPins(() => W(writer, $"TlSystems.TlSystem_{safe}.Run(world, players, forward{Args()});"));
        W(writer, "}");
        if (assignment.Parallel)
        {
            var hasEvents = HasEvents(assignment);
            var init = new StringBuilder("var __st = new __PS { ");
            W(writer, "unsafe struct __PS { public System.IntPtr __w; public System.IntPtr __p;");
            for (var i = 0; i < shape.Columns.Count; i++) if (shape.UsedColumns[i]) { W(writer, $"public {shape.Columns[i].ElementTypeName}* __c{i};"); init.Append($"__c{i} = __p{i}, "); }
            W(writer, "public int __n; public int __forward;");
            for (var i = 0; i < shape.Contexts.Count; i++) if (shape.UsedContexts[i]) W(writer, $"public void* __x{i};");
            for (var i = 0; i < shape.Events.Count; i++) W(writer, $"public {shape.Events[i].TypeName}* __ev{i};");
            W(writer, "}");
            W(writer, "static unsafe void __PChunk(void* __p, int __fw, int __ew, int __chunk) { var __s = (__PS*)__p; var world = (Tl.TimelineWorld)Tl.TlWorkers.Target(__s->__w); var players = (Tl.PlaybackTable)Tl.TlWorkers.Target(__s->__p); var forward = __s->__forward != 0;");
            for (var i = 0; i < shape.Events.Count; i++) W(writer, $"{shape.Events[i].TypeName} __se{i} = __s->__ev{i}[__chunk].Writer;");
            if (hasEvents) W(writer, $"TlSystems.TlSystem_{safe}.RunEventRange(world, players, forward{PArgs(shape)});");
            if (assignment.Kinds.Count > 0) W(writer, $"var __ks = players.Kinds; if (__ks != null) TlSystems.TlSystem_{safe}.Kinds(world, players, __ks, forward{PArgs(shape, false)});");
            W(writer, "}");
            W(writer, "public unsafe void Run(Tl.TimelineWorld world, Tl.PlaybackTable players, bool forward, Tl.TlWorkers workers)");
            W(writer, "{");
            W(writer, "if (world is null) throw new System.ArgumentNullException(nameof(world)); if (players is null) throw new System.ArgumentNullException(nameof(players)); if (workers is null) throw new System.ArgumentNullException(nameof(workers));");
            LenCheck();
            WithPins(() =>
            {
                W(writer, $"if (workers.WorkerCount == 1) {{ TlSystems.TlSystem_{safe}.Run(world, players, forward{Args()}); return; }}");
                if (hasEvents) W(writer, $"TlSystems.TlSystem_{safe}.RunClose(world, players, forward{Args()});");
                W(writer, "var __words = players.PlayingWords; var __chunks = System.Math.Min(workers.WorkerCount * 8, __words); if (__chunks <= 0) return; var __ends = stackalloc int[__chunks]; Tl.TlWorkers.Split(players.Playing, __words, __ends, __chunks);");
                for (var i = 0; i < shape.Events.Count; i++) { W(writer, $"var __segs{i} = stackalloc {shape.Events[i].TypeName}[__chunks]; for (var __i = 0; __i < __chunks; __i++) __segs{i}[__i] = new {shape.Events[i].TypeName}(128);"); init.Append($"__ev{i} = __segs{i}, "); }
                for (var i = 0; i < shape.Contexts.Count; i++) if (shape.UsedContexts[i]) init.Append($"__x{i} = System.Runtime.CompilerServices.Unsafe.AsPointer(ref this.{shape.Contexts[i].Name}), ");
                init.Append("__n = __len, __forward = forward ? 1 : 0 };");
                W(writer, init.ToString());
                W(writer, "var __wh = Tl.TlWorkers.Pin(world); var __ph = Tl.TlWorkers.Pin(players); __st.__w = __wh; __st.__p = __ph; try { workers.Run(&__PChunk, &__st, __ends, __chunks); } finally { Tl.TlWorkers.Free(__wh); Tl.TlWorkers.Free(__ph); }");
                if (assignment.Kinds.Any(static k => k.PrecombinedPulses))
                {
                    W(writer, "if (players.Kinds != null)");
                    W(writer, "{");
                    EmitClearPulses(writer, assignment, "players.Kinds", "__len");
                    W(writer, "}");
                }
                for (var i = 0; i < shape.Events.Count; i++) { W(writer, $"this.{shape.Events[i].Name}.ConcatSegments(__segs{i}, __chunks); for (var __j = 0; __j < __chunks; __j++) __segs{i}[__j].Dispose();"); }
            });
            W(writer, "}");
        }
        W(writer, "}");
        if (ns.Length > 0) W(writer, "}");
    }
