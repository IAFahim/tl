    static List<(int consumer, FeederDecl feeder)> FeedersOf(SystemAssignment a, KindDecl k)
    {
        var fs = new List<(int consumer, FeederDecl feeder)>();
        for (var c = 0; c < a.Consumers.Count; c++)
            foreach (var f in a.Consumers[c].Feeders)
                if (f.KindName == k.Id) fs.Add((c, f));
        fs.Sort(static (x, y) =>
        {
            var by = string.CompareOrdinal(x.feeder.ConsumerMetadata, y.feeder.ConsumerMetadata);
            return by != 0 ? by : string.CompareOrdinal(x.feeder.MethodName, y.feeder.MethodName);
        });
        return fs;
    }

