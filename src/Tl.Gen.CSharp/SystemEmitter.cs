        EmitEntryHead(w);
        EmitCases(w, a, s, fs, false);
        W(w, $"System.Runtime.CompilerServices.Unsafe.WriteUnaligned((byte*)__en + {valueAt}, __v);\n__en->Flags |= Tl.KindEntryFlags.Ready;\n}}");
    }

    static void EmitIdle(StringBuilder w, KernelShape s, KindDecl k)
    {
        var idleArgs = CallArgs(s, new ConsumerMethod(ConsumerMethodKind.ExecuteActive, k.IdleParams!, [], []), 0, "", "__e", "");
