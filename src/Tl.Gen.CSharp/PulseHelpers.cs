using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Tl.Gen.CSharp.Model;

namespace Tl.Gen.CSharp;

internal static class PulseHelpers
{
    const int AcceptsSpansOnly = 0;
    internal const string GlobalNamespace = "TlUnityGenerated";

    static string NamespaceOf(string typeName)
    {
        var bare = typeName.StartsWith("global::", StringComparison.Ordinal) ? typeName.Substring(8) : typeName;
        var dot = bare.LastIndexOf('.');
        return dot < 0 ? "" : bare.Substring(0, dot);
    }

    internal static string Emit(IReadOnlyList<SystemAssignment> assignments)
    {
        var kinds = assignments.SelectMany(static a => a.Kinds)
            .Where(static k => !k.Foreign && k.Accepts != AcceptsSpansOnly && k.Id.IndexOf('+') < 0)
            .GroupBy(static k => k.Id, StringComparer.Ordinal)
            .Select(static g => g.First())
            .OrderBy(static k => k.Id, StringComparer.Ordinal)
            .ToList();
        if (kinds.Count == 0) return "";
        var text = new StringBuilder("// <auto-generated/>\n");
        foreach (var space in kinds.GroupBy(static k => NamespaceOf(k.TypeName), StringComparer.Ordinal).OrderBy(static g => g.Key, StringComparer.Ordinal))
        {
            text.Append("namespace ").Append(space.Key.Length == 0 ? GlobalNamespace : space.Key).Append("\n{\n");
            foreach (var kind in space)
                text.Append(kind.Derived == DerivedKind.None ? "public" : "internal").Append(" static class ").Append(kind.Name).Append("Kind\n{\n")
                    .Append("public static global::Tl.KindPulses<").Append(kind.ValueTypeName).Append("> Pulses(global::Tl.KindStore kinds) => kinds.Pulses<")
                    .Append(kind.ValueTypeName).Append(">(\"").Append(kind.Id).Append("\");\n}\n");
            text.Append("}\n");
        }
        return text.ToString();
    }
}
